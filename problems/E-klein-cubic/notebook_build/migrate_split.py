#!/usr/bin/env python3
"""Idempotent migration: NOTEBOOK.md -> notebook_build/{sections,entries}/.

This is a re-derivation, not a one-time split. It parses whatever NOTEBOOK.md
currently says, rebuilds the source tree from scratch, regenerates the digest,
and asserts the regenerated bytes equal the input bytes (after the two declared
preamble transforms below). Re-run it any time NOTEBOOK.md on main has drifted
back to hand-edited form -- e.g. after an in-flight branch lands an old-style
supplement.

What it does
  1. Applies the declared preamble transforms (idempotent; see PREAMBLE_*).
  2. Splits the digest into ordered chunks:
       - head region (everything before the first `# ` heading after the title)
         splits at every `## ` heading            -> sections/NNN-<slug>.md
       - tail region splits at every `# ` heading and every dated `## ` heading
                                                  -> entries/<date>-<nn>-<slug>.md
     A candidate boundary is *rejected* (the chunk stays glued to its
     predecessor) unless it is preceded by exactly one blank line; that is what
     makes byte-identical reassembly true by construction. Heading-shaped lines
     inside ``` fences are never boundaries.
  3. Seeds notebook_build/parent_head from the old in-file pin, if absent.
  4. Moves manifest.json's `known_branches` inventory to branches/ markers.
  5. Regenerates and verifies byte identity.

Usage:
    migrate_split.py [--force] [--dry-run] [--build-dir DIR]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_notebook import generate  # noqa: E402

BUILD_DIR = Path(__file__).resolve().parent
PROBLEM_ROOT = BUILD_DIR.parent

# --- declared preamble transforms ------------------------------------------
# The pin used to live in the digest text, which forced a digest diff on every
# branch that stamped it. It now lives in notebook_build/parent_head. This is
# the ONLY content transform the migration performs, and it is idempotent.

PIN_BLOCK_RE = re.compile(
    r"Snapshot metadata — notebook parent head: `([0-9a-f]{7,40})`.*?"
    r"equals the current HEAD\.\n",
    re.S,
)

PIN_BLOCK_NEW = """Snapshot metadata — notebook parent head: recorded in
`notebook_build/parent_head` (the repository state this revision was authored
against — a file cannot carry its own commit hash, so the committing revision
is always `git log -1 -- problems/E-klein-cubic/NOTEBOOK.md`).
`scripts/check_manifest_parity.py` verifies at pre-commit time that the
recorded parent equals the current HEAD. **This file is GENERATED** from
`notebook_build/sections/` and `notebook_build/entries/` by
`notebook_build/generate_notebook.py`: edit those sources, never this file, and
regenerate with `notebook_build/reconcile.py` — protocol in
`notebook_build/PROTOCOL.md`.
"""


def apply_preamble_transforms(text: str) -> tuple[str, str | None]:
    """Returns (transformed text, pin sha found in the old block or None)."""
    m = PIN_BLOCK_RE.search(text)
    if not m:
        return text, None  # already migrated (idempotent no-op)
    return text[: m.start()] + PIN_BLOCK_NEW + text[m.end():], m.group(1)


# --- chunking ---------------------------------------------------------------

DATED_H2_RE = re.compile(r"^## (20\d{2}-\d{2}-\d{2})")
DATE_IN_TEXT_RE = re.compile(r"(20\d{2})-(\d{2})-(\d{2})")
MARKER_DATE_RE = re.compile(r"_(20\d{2})(\d{2})(\d{2})\b")


def fence_mask(lines: list[str]) -> list[bool]:
    """True on lines that sit inside a ``` fenced block."""
    mask, inside = [], False
    for line in lines:
        if line.lstrip().startswith("```"):
            mask.append(True)
            inside = not inside
            continue
        mask.append(inside)
    return mask


CLOSING_MARKER_RE = re.compile(r"(?:^|[-_ ])END\s*-->\s*$")


def is_opening_marker(line: str) -> bool:
    """A provenance comment that labels the block *below* it.

    `<!-- FOO-BEGIN -->` / `<!-- FOO_20260810 -->` open a block; `<!-- FOO-END
    -->` closes the block above and must stay with it.
    """
    return line.startswith("<!--") and not CLOSING_MARKER_RE.search(line)


def pull_markers(lines: list[str], i: int) -> int:
    """Move a boundary up over preceding opening `<!-- ... -->` marker lines.

    At most one blank line may sit between the marker block and its heading --
    both spellings occur in the notebook.
    """
    k = i - 1
    if k >= 0 and lines[k].strip() == "":
        k -= 1
    j = i
    while k >= 0 and is_opening_marker(lines[k]):
        j = k
        k -= 1
    return j


def blank_run_before(lines: list[str], i: int) -> int:
    n = 0
    j = i - 1
    while j >= 0 and lines[j].strip() == "":
        n += 1
        j -= 1
    return n


def split_chunks(text: str) -> tuple[list[tuple[int, int]], int]:
    """Returns (chunk line-ranges, index of the first tail chunk)."""
    lines = text.split("\n")
    fenced = fence_mask(lines)

    def is_h1(i: int) -> bool:
        return lines[i].startswith("# ") and not fenced[i]

    def is_h2(i: int) -> bool:
        return lines[i].startswith("## ") and not fenced[i]

    head_end = len(lines)
    for i in range(1, len(lines)):
        if is_h1(i):
            head_end = pull_markers(lines, i)
            break

    boundaries: list[int] = [0]
    for i in range(1, len(lines)):
        b = pull_markers(lines, i)
        if b < head_end:
            candidate = is_h2(i)
        else:
            candidate = is_h1(i) or (is_h2(i) and DATED_H2_RE.match(lines[i]))
        if not candidate:
            continue
        if blank_run_before(lines, b) != 1:
            continue  # keep glued to the previous chunk: preserves bytes
        if b > boundaries[-1]:
            boundaries.append(b)

    ranges = [(boundaries[k], boundaries[k + 1]) for k in range(len(boundaries) - 1)]
    ranges.append((boundaries[-1], len(lines)))
    tail_index = next(k for k, (a, _) in enumerate(ranges) if a >= head_end)
    return ranges, tail_index


def heading_of(chunk: list[str]) -> str:
    for line in chunk:
        if line.startswith("#"):
            return line.lstrip("#").strip()
    return ""


def markers_of(chunk: list[str]) -> str:
    return " ".join(l for l in chunk[:4] if l.startswith("<!--"))


def slugify(s: str, limit: int = 52) -> str:
    s = s.replace("\\(", " ").replace("\\)", " ")
    s = re.sub(r"[`*$]", "", s).lower()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    if len(s) > limit:
        cut = s[:limit].rsplit("-", 1)[0]
        s = cut or s[:limit]
    return s or "section"


ENTRY_BOILERPLATE_RE = re.compile(
    r"^(notebook\s+supplement|supplement)\b[\s—:-]*", re.I)


def entry_slug(heading: str, marker: str) -> str:
    h = ENTRY_BOILERPLATE_RE.sub("", heading.strip())
    h = DATE_IN_TEXT_RE.sub(" ", h).strip(" —:-")
    slug = slugify(h)
    if slug in ("", "section"):
        slug = slugify(marker.replace("<!--", "").replace("-->", ""))
    return slug


def entry_date(heading: str, marker: str, previous: str | None) -> str:
    m = DATE_IN_TEXT_RE.search(heading)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
    m = MARKER_DATE_RE.search(marker)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
    if previous:
        return previous
    raise SystemExit(
        f"migrate_split: cannot date the first entry chunk: {heading!r}")


def plan(text: str) -> tuple[list[tuple[str, str]], list[str]]:
    """Returns ([(relative part path, part text)], notes)."""
    lines = text.split("\n")
    ranges, tail_index = split_chunks(text)
    parts: list[tuple[str, str]] = []
    notes: list[str] = []
    used: set[str] = set()

    prev_date: str | None = None
    day_counts: dict[str, int] = {}
    for k, (a, b) in enumerate(ranges):
        chunk = lines[a:b]
        body = "\n".join(chunk).strip("\n") + "\n"
        heading = heading_of(chunk)
        marker = markers_of(chunk)
        if k < tail_index:
            slug = "preamble" if k == 0 else slugify(heading)
            name = f"sections/{(k + 1) * 10:03d}-{slug}.md"
        else:
            date = entry_date(heading, marker, prev_date)
            prev_date = date
            day_counts[date] = day_counts.get(date, 0) + 1
            slug = entry_slug(heading, marker)
            name = f"entries/{date}-{day_counts[date]:02d}-{slug}.md"
        if name in used:
            stem, ext = name[:-3], ".md"
            n = 2
            while f"{stem}-{n}{ext}" in used:
                n += 1
            name = f"{stem}-{n}{ext}"
            notes.append(f"name collision resolved -> {name}")
        used.add(name)
        parts.append((name, body))
    return parts, notes


# --- branch inventory migration --------------------------------------------

def encode_branch(name: str) -> str:
    return name.replace("%", "%25").replace("/", "%2F")


def migrate_branches(build_dir: Path, dry_run: bool) -> int:
    manifest_path = build_dir / "manifest.json"
    if not manifest_path.is_file():
        return 0
    raw = manifest_path.read_text(encoding="utf-8")
    obj = json.loads(raw)
    known = obj.get("known_branches")
    branches_dir = build_dir / "branches"
    written = 0
    if known:
        if not dry_run:
            branches_dir.mkdir(exist_ok=True)
        for b in sorted(known):
            marker = branches_dir / encode_branch(b)
            if marker.exists():
                continue
            written += 1
            if not dry_run:
                # deterministic content: two sessions registering the same
                # branch write identical bytes, so add/add never conflicts
                marker.write_text(f"branch: {b}\n", encoding="utf-8")
        del obj["known_branches"]
        note = obj.get("as_of_commit", {}).get("note")
        if note and "only in NOTEBOOK.md" in note:
            obj["as_of_commit"]["note"] = (
                "the notebook's own parent head lives in "
                "notebook_build/parent_head and is checked by "
                "scripts/check_manifest_parity.py; the remote-branch inventory "
                "lives in notebook_build/branches/")
        if not dry_run:
            manifest_path.write_text(
                json.dumps(obj, indent=1, ensure_ascii=False) + "\n",
                encoding="utf-8")
    return written


# --- main -------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build-dir", default=str(BUILD_DIR))
    ap.add_argument("--force", action="store_true",
                    help="rebuild sections/ and entries/ even if they exist")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    build_dir = Path(args.build_dir).resolve()
    notebook = build_dir.parent / "NOTEBOOK.md"
    original = notebook.read_text(encoding="utf-8")
    transformed, old_pin = apply_preamble_transforms(original)

    parts, notes = plan(transformed)
    n_sections = sum(1 for n, _ in parts if n.startswith("sections/"))
    n_entries = len(parts) - n_sections
    print(f"plan: {n_sections} section part(s), {n_entries} entry part(s)")
    for note in notes:
        print(f"  note: {note}")

    rebuilt = generate_from_plan(parts)
    if rebuilt != transformed:
        print("FAIL migrate_split: reassembly is not byte-identical to input",
              file=sys.stderr)
        _report_first_diff(transformed, rebuilt)
        return 1
    delta = "" if old_pin is None else f" (pin `{old_pin[:12]}` moved out of the digest)"
    print(f"OK   reassembly byte-identical to the transformed input{delta}")

    if args.dry_run:
        for name, body in parts:
            print(f"  {name}  ({len(body)} bytes)")
        migrate_branches(build_dir, dry_run=True)
        return 0

    for dirname in ("sections", "entries"):
        d = build_dir / dirname
        if d.exists():
            if not args.force:
                print(f"FAIL migrate_split: {d} already exists; pass --force "
                      f"to rebuild it from NOTEBOOK.md", file=sys.stderr)
                return 1
            for child in d.iterdir():
                if child.is_file() and child.name.endswith(".md"):
                    child.unlink()
        d.mkdir(exist_ok=True)

    for name, body in parts:
        (build_dir / name).write_text(body, encoding="utf-8")

    pin_path = build_dir / "parent_head"
    if not pin_path.is_file():
        seed = old_pin or _git_head(build_dir)
        pin_path.write_text(seed + "\n", encoding="utf-8")
        print(f"seeded {pin_path.name} = {seed[:12]}")

    written = migrate_branches(build_dir, dry_run=False)
    if written:
        print(f"branch inventory: wrote {written} marker(s) to branches/, "
              f"removed known_branches from manifest.json")

    final = generate(build_dir)
    if final != transformed:
        print("FAIL migrate_split: on-disk regeneration differs from plan",
              file=sys.stderr)
        return 1
    notebook.write_text(final, encoding="utf-8")
    print(f"OK   wrote {notebook} from {len(parts)} source parts "
          f"({len(final)} bytes)")
    return 0


def generate_from_plan(parts: list[tuple[str, str]]) -> str:
    return "\n\n".join(body.strip("\n") for _, body in parts) + "\n"


def _report_first_diff(a: str, b: str) -> None:
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            print(f"  first difference at byte {i}:", file=sys.stderr)
            print(f"    input     ...{a[max(0, i-60):i+60]!r}", file=sys.stderr)
            print(f"    reassembly...{b[max(0, i-60):i+60]!r}", file=sys.stderr)
            return
    print(f"  identical prefix; lengths {len(a)} vs {len(b)}", file=sys.stderr)


def _git_head(build_dir: Path) -> str:
    import subprocess
    return subprocess.run(["git", "-C", str(build_dir), "rev-parse", "HEAD"],
                          capture_output=True, text=True,
                          check=True).stdout.strip()


if __name__ == "__main__":
    sys.exit(main())
