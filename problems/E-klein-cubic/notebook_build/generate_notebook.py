#!/usr/bin/env python3
"""Deterministic generator for problems/E-klein-cubic/NOTEBOOK.md.

NOTEBOOK.md is the single searchable digest for Problem E and stays committed.
It is no longer hand-edited: it is assembled, byte-deterministically, from

    notebook_build/sections/NNN-<slug>.md   stable preamble + core sections,
                                            emitted in filename order
    notebook_build/entries/<date>-<nn>-<slug>.md
                                            dated entries and supplements,
                                            emitted in filename order, after
                                            every section

Assembly rule (the whole contract):

    digest = "\\n\\n".join(part.strip("\\n") for part in parts) + "\\n"

with `parts` = sections in sorted filename order, then entries in sorted
filename order. Nothing else is inserted, reordered, or normalised, so the
generated bytes are a pure function of the source tree.

Concurrency: two sessions add two *different* entry files, so the source tree
merges cleanly by construction. The generated digest is regenerated rather than
merged (see notebook_build/merge_driver.py and PROTOCOL.md).

Usage:
    generate_notebook.py                 # write NOTEBOOK.md
    generate_notebook.py --stdout        # print the digest, write nothing
    generate_notebook.py --check         # exit 1 if committed digest is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BUILD_DIR = Path(__file__).resolve().parent
PROBLEM_ROOT = BUILD_DIR.parent
NOTEBOOK_PATH = PROBLEM_ROOT / "NOTEBOOK.md"

SECTIONS_DIRNAME = "sections"
ENTRIES_DIRNAME = "entries"

SECTION_RE = re.compile(r"^\d{3}-[A-Za-z0-9._-]+\.md$")
ENTRY_RE = re.compile(r"^\d{4}-\d{2}-\d{2}-[A-Za-z0-9._-]+\.md$")


class BuildError(Exception):
    pass


def part_names(build_dir: Path) -> list[str]:
    """Ordered list of part paths, relative to build_dir, as strings.

    Sections first (sorted), then entries (sorted). Sorting is plain
    lexicographic on the file name, which is why section names carry a numeric
    prefix and entry names start with an ISO date followed by a two-digit
    within-day ordinal.
    """
    names: list[str] = []
    for dirname, pattern, label in (
        (SECTIONS_DIRNAME, SECTION_RE, "section"),
        (ENTRIES_DIRNAME, ENTRY_RE, "entry"),
    ):
        d = build_dir / dirname
        if not d.is_dir():
            raise BuildError(f"missing source directory: {d}")
        found = []
        for child in d.iterdir():
            if child.name.startswith(".") or not child.is_file():
                continue
            if not child.name.endswith(".md"):
                raise BuildError(f"non-.md file in {dirname}/: {child.name}")
            if not pattern.match(child.name):
                raise BuildError(
                    f"{label} file name does not match the required pattern: "
                    f"{dirname}/{child.name}"
                )
            found.append(child.name)
        names.extend(f"{dirname}/{n}" for n in sorted(found))
    if not names:
        raise BuildError(f"no source parts found under {build_dir}")
    return names


def generate_from_parts(parts: list[tuple[str, str]]) -> str:
    """Assemble the digest from an ordered [(name, text)] list."""
    chunks = []
    for name, text in parts:
        stripped = text.strip("\n")
        if not stripped:
            raise BuildError(f"empty source part: {name}")
        chunks.append(stripped)
    return "\n\n".join(chunks) + "\n"


def generate(build_dir: Path = BUILD_DIR) -> str:
    names = part_names(build_dir)
    parts = [(n, (build_dir / n).read_text(encoding="utf-8")) for n in names]
    return generate_from_parts(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build-dir", default=str(BUILD_DIR))
    ap.add_argument("--out", default=None,
                    help="output path (default: the problem's NOTEBOOK.md)")
    ap.add_argument("--stdout", action="store_true", help="print, write nothing")
    ap.add_argument("--check", action="store_true",
                    help="compare against the existing digest; exit 1 if stale")
    args = ap.parse_args(argv)

    build_dir = Path(args.build_dir).resolve()
    out = Path(args.out) if args.out else (build_dir.parent / "NOTEBOOK.md")
    try:
        text = generate(build_dir)
    except BuildError as exc:
        print(f"generate_notebook: {exc}", file=sys.stderr)
        return 2

    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        if not out.is_file():
            print(f"generate_notebook: {out} does not exist", file=sys.stderr)
            return 1
        current = out.read_text(encoding="utf-8")
        if current == text:
            print(f"OK   digest fresh: {out} matches generator output "
                  f"({len(text)} bytes)")
            return 0
        print(f"FAIL digest stale: {out} differs from generator output "
              f"(committed {len(current)} bytes, generated {len(text)} bytes)",
              file=sys.stderr)
        return 1

    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text)} bytes, {len(part_names(build_dir))} parts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
