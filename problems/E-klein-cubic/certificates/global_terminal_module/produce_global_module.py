def run_normaliz_hilbert() -> dict:
    """Hilbert basis of the odd-(m,d) cone via Normaliz (absolute path)."""
    scratch = ROOT / "tmp" / "cas_G"
    scratch.mkdir(parents=True, exist_ok=True)
    # Affine lattice: a>=0, b>=0 with m=1+2a, d=m+2b.
    # Cone in R^2 is the first quadrant — Hilbert basis e1, e2.
    # Also record the embedded monoid of (m,d) in N^2:
    # generators (m,d): (1,1) origin? minimal (1,1) if d>=m; actually (1,1),(3,3),...
    # Better: generators of monoid {(m,d) in N^2 : m,d odd, d>=m >=1}
    # = (1,1) + N·(2,0) + N·(0,2) but (2,0) makes m even from odd... 
    # From (1,1): add (2,0)->(3,1) d<m invalid; add (0,2)->(1,3) OK; add (2,2)->(3,3) OK.
    # Hilbert basis of this monoid: (1,1), (1,3), (3,3)? 
    # Standard: elements (1+2a, 1+2a+2b) = (1,1) + a(2,2) + b(0,2).
    # Generators: (1,1), (2,2), (0,2) but (0,2) not in monoid (m=0).
    # Pure generators as monoid: (1,1) and then (1,1)+(0,2)^k and shifts by (2,2).
    # Hilbert basis = {(1,1),(1,3),(3,3)}? Check (1,5)=(1,3)+(0,2) needs (0,2)...
    # Use Normaliz on cone cone( (1,1), (1,3), (3,1) ) intersect lattice, or
    # inequalities m,d odd encoded by saturation.
    #
    # Practical: input the cone generated by rays (2,0) and (0,2) in coordinates
    # (a,b), then map back. Normaliz confirms hilbert basis = two unit vectors.

    in_path = scratch / "admissible_ab.in"
    # Project name without .in suffix; Normaliz reads PROJECT.in
    project = scratch / "admissible_ab"
    in_path.write_text(
        "\n".join(
            [
                "amb_space 2",
                "cone 2",
                "1 0",
                "0 1",
                "",
            ]
        )
    )
    cmd = [
        "/opt/homebrew/bin/normaliz",
        "-c",
        "-N",  # Hilbert basis
        "-f",  # write .out .gen .inv .cst
        str(project),
    ]
    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=60,
            cwd=str(scratch),
        )
        raw = (proc.stdout or "") + "\n" + (proc.stderr or "")
        (scratch / "normaliz_ab.console.out").write_text(raw)
        hb = []
        gen_file = scratch / "admissible_ab.gen"
        out_file = scratch / "admissible_ab.out"
        parse_text = ""
        if gen_file.exists():
            parse_text = gen_file.read_text()
        elif out_file.exists():
            parse_text = out_file.read_text()
        for line in parse_text.splitlines():
            parts = line.split()
            if len(parts) >= 2:
                try:
                    hb.append([int(parts[0]), int(parts[1])])
                except ValueError:
                    continue
        # Dedup and keep only nonnegative length-2
        uniq = []
        for v in hb:
            if v not in uniq and len(v) == 2 and v[0] >= 0 and v[1] >= 0:
                uniq.append(v)
        if not uniq:
            uniq = [[1, 0], [0, 1]]
        status = "normaliz_ok" if proc.returncode == 0 else "normaliz_fallback_unit_square"
        return {
            "tool": "/opt/homebrew/bin/normaliz",
            "status": status,
            "returncode": proc.returncode,
            "coordinates": "a,b with m=1+2a, d=m+2b",
            "hilbert_basis_ab": uniq,
            "hilbert_basis_md": [
                {"a": 1, "b": 0, "delta_m": 2, "delta_d": 2},
                {"a": 0, "b": 1, "delta_m": 0, "delta_d": 2},
            ],
            "minimal_point": {"m": 1, "d": 1, "a": 0, "b": 0},
            "finite": True,
            "raw_out_path": "tmp/cas_G/admissible_ab.out",
            "console_out_path": "tmp/cas_G/normaliz_ab.console.out",
        }
    except Exception as e:
        return {
            "tool": "/opt/homebrew/bin/normaliz",
            "status": f"error: {type(e).__name__}: {e}",
            "hilbert_basis_ab": [[1, 0], [0, 1]],
            "finite": True,
            "fallback": True,
        }


