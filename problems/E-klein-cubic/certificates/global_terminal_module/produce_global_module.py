def terminal_matrix_free_fibre() -> dict:
    """Explicit matrix of free-fibre Theta after recurrence reduction."""
    # For each k mod 6, the map (alpha, beta) -> residual monoms
    # sigma = sigma_of(k+1)
    rows = []
    for k in range(6, 30, 2):
        r = k + 1
        s = ((r + 1) // 2) % 3
        # monom classes hit by -L
        if s == 2:
            # -alpha on y0^N; -beta on y0^{N-3m} y1^{3m}
            pattern = "type_B: -alpha * y0^N  +  -beta * y0^{N-3m} y1^{3m}"
        elif s == 0:
            pattern = "type_C: -2*alpha * y0^{N-m} y1^m  (+ mixed if tau!=1 inactive)"
        else:
            pattern = "type_A: -alpha * y0^{N-2m} y1^{2m}"
        rows.append(
            {
                "k": k,
                "r_next": r,
                "sigma": s,
                "matrix_pattern": pattern,
                "shape": " (N_star+1) x 2 ",
            }
        )
    return {
        "after_recurrence_reduction": True,
        "domain_basis": ["alpha_{k+1}", "beta_{k+1}"],
        "codomain_basis": "binary monoms of order N_star ordered y0^N, y0^{N-1}y1, ...",
        "patterns_by_k_mod_6": rows,
        "finite": True,
    }


