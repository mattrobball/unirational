def enforce_limit() -> None:
    ceiling = CEILING_MIB * 1024**2
    try:
        resource.setrlimit(resource.RLIMIT_AS, (ceiling, ceiling))
    except (OSError, ValueError):
        if sys.platform != "darwin":
            raise
        if os.environ.get(CAP_ENV) == str(CEILING_MIB):
            return
        env = dict(os.environ)
        env[CAP_ENV] = str(CEILING_MIB)
        os.execve(
            "/usr/sbin/taskpolicy",
            ["taskpolicy", "-m", str(CEILING_MIB), sys.executable, *sys.argv],
            env,
        )


def file_hash(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def load_primitive_terms():
    terms = []
    with PRIMITIVE.open() as stream:
        assert next(stream).strip() == "A\tB\tY\tZ\tu\tcoefficient"
        for line in stream:
            a, b, y, z, u, c = map(int, line.split())
            terms.append(((a, b, y, z, u), c))
    assert len(terms) == 1593
    return terms


def specialize_A0_B2(terms, which: str) -> str:
    """Return M2 polynomial in Y,Z,u after A=0, B=2.

    which in {P, PA, PB, PY, PZ, Pu}.
    """

    var_index = {
        "P": None,
        "PA": 0,
        "PB": 1,
        "PY": 2,
        "PZ": 3,
        "Pu": 4,
    }[which]
    parts = []
    for exps, coeff in terms:
        if var_index is None:
            new = list(exps)
            c = coeff
        else:
            e = exps[var_index]
            if e == 0:
                continue
            new = list(exps)
            new[var_index] = e - 1
            c = coeff * e
        a, b, y, z, u = new
        if a > 0:
            continue
        c *= 2**b
        mon = []
        if c != 1 and c != -1:
            mon.append(f"({c})" if c < 0 else str(c))
        elif c == -1:
            mon.append("(-1)")
        for name, exp in (("Y", y), ("Z", z), ("u", u)):
            if exp == 1:
                mon.append(name)
            elif exp:
                mon.append(f"{name}^{exp}")
        if not mon:
            mon = ["1"]
        parts.append("*".join(mon))
    return "+".join(parts) if parts else "0"


def run_slice_critical_m2(terms) -> dict:
    polys = {name: specialize_A0_B2(terms, name) for name in ("P", "PA", "PB", "PY", "PZ", "Pu")}
    script = HERE / "slice_critical_qq.m2"
    log = HERE / "slice_critical_qq.m2.log"
    lines = [
        "-- generated by produce.py; do not hand-edit",
        "R=QQ[Y,Z,u,MonomialOrder=>GRevLex];",
        f"P={polys['P']};",
        f"PA={polys['PA']};",
        f"PB={polys['PB']};",
        f"PY={polys['PY']};",
        f"PZ={polys['PZ']};",
        f"Pu={polys['Pu']};",
        "J=ideal(P,PA,PB,PY,PZ,Pu);",
        'print "QQ_SLICE_CRITICAL_BUILT";',
        'print("QQ_SLICE_CRIT_DIM="|toString dim J);',
        'print("QQ_SLICE_CRIT_DEGREE="|toString degree J);',
        'print("QQ_SLICE_CRIT_CODIM="|toString codim J);',
        # intrinsic singular ideal of the specialized hypersurface P=0
        "Jsing=ideal(P,diff(Y,P),diff(Z,P),diff(u,P));",
        'print("QQ_SLICE_SING_DIM="|toString dim Jsing);',
        'print("QQ_SLICE_SING_DEGREE="|toString degree Jsing);',
        'print "QQ_SLICE_CRITICAL_CERTIFIED";',
        "exit 0;",
    ]
    script.write_text("\n".join(lines) + "\n")
    result = subprocess.run(
        [M2, "--stop", "--no-prompts", "--silent", str(script)],
        check=True,
        capture_output=True,
        text=True,
        timeout=600,
    )
    text = result.stdout + result.stderr
    log.write_text(text)
    data = {}
    for line in text.splitlines():
        if line.startswith("QQ_SLICE_CRIT_DIM="):
            data["critical_dim"] = int(line.split("=", 1)[1])
        elif line.startswith("QQ_SLICE_CRIT_DEGREE="):
            data["critical_degree"] = int(line.split("=", 1)[1])
        elif line.startswith("QQ_SLICE_CRIT_CODIM="):
            data["critical_codim"] = int(line.split("=", 1)[1])
        elif line.startswith("QQ_SLICE_SING_DIM="):
            data["sing_dim"] = int(line.split("=", 1)[1])
        elif line.startswith("QQ_SLICE_SING_DEGREE="):
            data["sing_degree"] = int(line.split("=", 1)[1])
    assert "QQ_SLICE_CRITICAL_CERTIFIED" in text
    assert data["critical_dim"] == 1
    assert data["critical_degree"] == 14
    assert data["critical_codim"] == 2
    assert data["sing_dim"] == 1
    assert data["sing_degree"] == 14
    return data


