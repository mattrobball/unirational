#!/usr/bin/env python3
"""WP-L2 shared exact helpers: relative L_r / omega_r free-module tower.

Does not import any producer or verifier.  Exact arithmetic (Fraction) only.
No timing fields.  Absolute-path safe.

Model
-----
Work in the normal-cone coordinates E_+ ⊕ E_- with the unique (up to scale)
D12-weight-compatible nondegenerate mixed polar

    B(z; y, y) = z_0 · (2 y_0 y_1) + z_1 · y_1² + z_2 · y_0²

which realises the isomorphism φ : E_+ → Sym² E_-^*,  z ↦ Q_z.
Nondegeneracy is elementary (the three coefficient binary quadrics are a basis
of Sym²).  The actual Klein polar is D12-isomorphic to this model; all
representation-theoretic rank statements transport.  Structure constants of
the concrete cyclotomic frame are used only as modular regression at 67.

Free R-modules over R = Sym(E_+^*) (base-plane coordinates):
  jet of normal order k, target T  ≅  free R-module of rank
      dim Sym^k(E_-^*) · dim T,
  generated by y-monomials of degree k times a basis of T.

L_1 = L_3 as polar operators: both are b ↦ B(b; a, a) with fixed leading a.
"""

