def memory_gate_ok(shape, nnz_est=None, limit_gb=8.0) -> dict:
    n_rows, n_cols = shape
    dense = n_rows * n_cols * 32
    sparse = (nnz_est or min(n_rows * n_cols, max(n_rows, n_cols) * 20)) * 32
    return {
        "dense_GB": round(dense / 1e9, 6),
        "sparse_GB": round(sparse / 1e9, 6),
        "ok_dense": dense / 1e9 <= limit_gb,
        "ok_sparse": sparse / 1e9 <= limit_gb,
        "limit_GB": limit_gb,
    }
