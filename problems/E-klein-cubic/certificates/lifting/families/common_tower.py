def dim_plane(m: int, d: int) -> int:
    if m < 0 or d < m:
        return 0
    base = (m + 1) * binom(d - m + 2, 2)
    return base * (3 if m % 2 == 0 else 2)


def dim_scalar_normal(order: int, d_scalar: int) -> int:
    if d_scalar < order:
        return 0
    return binom(d_scalar - order + 2, 2) * (order + 1)


