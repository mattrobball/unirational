def binom(n: int, k: int) -> int:
    if k < 0 or n < 0 or k > n:
        return 0
    return math.comb(n, k)


# ---------------------------------------------------------------------------
# Monomial bases for binary forms (E_-^* coordinates y0, y1)
# ---------------------------------------------------------------------------

def monoms(deg: int) -> list[tuple[int, int]]:
    """List (a,b) with a+b = deg, lexicographic in a descending."""
    return [(deg - k, k) for k in range(deg + 1)]


def monom_index(deg: int) -> dict[tuple[int, int], int]:
    return {m: i for i, m in enumerate(monoms(deg))}


def dim_sym_bin(deg: int) -> int:
    return deg + 1 if deg >= 0 else 0


# ---------------------------------------------------------------------------
# Mixed polar B in the abstract D12-weight model
# ---------------------------------------------------------------------------

# E_+ basis e0 (wt 0), e1 (wt +2), e2 (wt -2)
# E_- basis f0 (wt +1), f1 (wt -1)
# B(z; y, y) = z0 * 2 y0 y1 + z1 * y1^2 + z2 * y0^2
# Polarized: B(z; y, y') = z0 (y0 y1' + y1 y0') + z1 y1 y1' + z2 y0 y0'

def B_coeff(z_index: int, j: int, k: int) -> Q:
    """Coefficient of B(e_{z_index}; f_j, f_k). Symmetric in (j,k)."""
    # y = y0 f0* + y1 f1* dual notation: evaluate on vectors
    # B(e0; f0, f1) = 1, B(e0; f1, f0) = 1, B(e0; f0,f0)=B(e0;f1,f1)=0
    # B(e1; f1, f1) = 1
    # B(e2; f0, f0) = 1
    if z_index == 0:
        if (j, k) in ((0, 1), (1, 0)):
            return Q(1)
        return Q(0)
    if z_index == 1:
        if j == 1 and k == 1:
            return Q(1)
        return Q(0)
    if z_index == 2:
        if j == 0 and k == 0:
            return Q(1)
        return Q(0)
    raise IndexError(z_index)


def B_quadratic_form(z: tuple[Q, Q, Q], y0: Q, y1: Q) -> Q:
    z0, z1, z2 = z
    return z0 * Q(2) * y0 * y1 + z1 * y1 * y1 + z2 * y0 * y0


def certify_B_isomorphism() -> dict:
    """φ: E_+ → Sym² E_-^* is a linear isomorphism."""
    # Matrix of φ on basis e0,e1,e2 → coeffs of (y0², y0 y1, y1²)
    # Q_{e0} = 2 y0 y1 → (0, 2, 0)
    # Q_{e1} = y1²     → (0, 0, 1)
    # Q_{e2} = y0²     → (1, 0, 0)
    M = [
        [Q(0), Q(0), Q(1)],  # y0² coeffs
        [Q(2), Q(0), Q(0)],  # y0 y1
        [Q(0), Q(1), Q(0)],  # y1²
    ]
    # det = 2 ≠ 0
    det = (
        M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1])
        - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0])
        + M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0])
    )
    assert det == Q(2)
    return {
        "status": "PROVED",
        "model": "B(z;y,y)=z0·2 y0 y1 + z1·y1² + z2·y0²",
        "det_phi": "2",
        "isomorphism": True,
        "note": (
            "D12-weight matching forces this shape up to scale on each weight "
            "component; nondegeneracy is scale-invariant."
        ),
    }


# ---------------------------------------------------------------------------
# Free-module ranks
# ---------------------------------------------------------------------------

def free_rank_jet(normal_order: int, target_dim: int) -> int:
    """Rank of free R-module of normal-order jets with values in target."""
    if normal_order < 0:
        return 0
    return dim_sym_bin(normal_order) * target_dim


def free_rank_leading(m: int) -> int:
    """a_m : free rank Sym^m E_-* ⊗ E_-  (target dim 2)."""
    return free_rank_jet(m, 2)


def free_rank_L_domain(m: int, r: int) -> int:
    """Domain of L_r for r odd (E_+-valued, order m+r). r=1 or 3."""
    return free_rank_jet(m + r, 3)


def free_rank_L_codomain(m: int, r: int) -> int:
    """Codomain: scalar normal order 3m+r (for r=1: 3m+1; for r=3: 3m+3)."""
    # F-order for newest unknown at stage r:
    # r=1 → F-order 3m+1; r=3 → F-order 3m+3
    N = 3 * m + r
    return dim_sym_bin(N)


# ---------------------------------------------------------------------------
# Build relative sparse matrix L(a) : free domain → free codomain
# a given as dict (alpha0, alpha1, j) → Q  for y0^{a} y1^{b} f_j coeff
# or as flat list of length free_rank_leading(m)
# ---------------------------------------------------------------------------

def leading_basis(m: int) -> list[tuple[tuple[int, int], int]]:
    """Basis keys ((a,b), j) for a_m."""
    return [(mon, j) for mon in monoms(m) for j in (0, 1)]


def domain_basis(m: int, r: int) -> list[tuple[tuple[int, int], int]]:
    """Basis keys ((a,b), i) for b_{m+r} with E_+ index i."""
    return [(mon, i) for mon in monoms(m + r) for i in (0, 1, 2)]


def codomain_basis(m: int, r: int) -> list[tuple[int, int]]:
    N = 3 * m + r
    return monoms(N)


def pack_leading(m: int, coeffs: list[Q]) -> dict:
    keys = leading_basis(m)
    assert len(coeffs) == len(keys)
    return {keys[t]: Q(coeffs[t]) for t in range(len(keys))}


def L_matrix_sparse(m: int, r: int, a_coeffs: list[Q]) -> dict:
    """Relative matrix of L_r(b) = B(b; a, a) as sparse CSR-like dict.

    Entries are rational (a specialized).  For the relative (unspecialized)
    matrix, use L_matrix_symbolic_quadratic.

    Returns:
      rows, cols, data (COO), shape, nnz, rank_over_Q (exact)
    """
    assert r in (1, 3)
    a = pack_leading(m, a_coeffs)
    dom = domain_basis(m, r)
    cod = codomain_basis(m, r)
    cod_index = {mny: i for i, mny in enumerate(cod)}
    n_rows = len(cod)
    n_cols = len(dom)

    # COO accumulation
    from collections import defaultdict
    acc: dict[tuple[int, int], Q] = defaultdict(lambda: Q(0))

    # a = sum A_{α,j} y^α f_j
    # b basis vector e_{β,i} : y^β e_i
    # B(e_i; f_j, f_k) * A_{α,j} * A_{α',k} contributes to y^{β+α+α'}
    a_items = [(alpha, j, val) for (alpha, j), val in a.items() if val != 0]

    for col, (beta, i) in enumerate(dom):
        for alpha, j, Aj in a_items:
            for alpha2, k, Ak in a_items:
                c = B_coeff(i, j, k)
                if c == 0:
                    continue
                # total y exponent
                tot = (beta[0] + alpha[0] + alpha2[0], beta[1] + alpha[1] + alpha2[1])
                if tot not in cod_index:
                    continue
                row = cod_index[tot]
                acc[(row, col)] += c * Aj * Ak

    # Materialize COO sorted
    entries = sorted(((r0, c0, v) for (r0, c0), v in acc.items() if v != 0),
                     key=lambda t: (t[0], t[1]))
    rows = [e[0] for e in entries]
    cols = [e[1] for e in entries]
    data = [e[2] for e in entries]

    # Exact rank via dense Fraction RREF on sparse-built dense (only small free ranks)
    rank = exact_rank_from_coo(n_rows, n_cols, rows, cols, data)

    return {
        "m": m,
        "r": r,
        "shape": [n_rows, n_cols],
        "nnz": len(data),
        "coo_rows": rows,
        "coo_cols": cols,
        "coo_data": [str(v) for v in data],  # Fraction as "p/q"
        "rank_over_Q": rank,
        "nullity_over_Q": n_cols - rank,
        "cokernel_dim_over_Q": n_rows - rank,
        "a_coeffs": [str(Q(c)) for c in a_coeffs],
        "format": "COO over Q (specialized leading jet)",
    }


def exact_rank_from_coo(n_rows, n_cols, rows, cols, data) -> int:
    """Gaussian elimination rank over Q."""
    if n_rows == 0 or n_cols == 0:
        return 0
    # Build dense only if small enough
    if n_rows * n_cols > 2_000_000:
        raise MemoryError(
            f"refusing dense rank on shape {(n_rows, n_cols)} (8GB gate)"
        )
    A = [[Q(0) for _ in range(n_cols)] for _ in range(n_rows)]
    for r0, c0, v in zip(rows, cols, data):
        A[r0][c0] += Q(v)
    rank = 0
    row = 0
    for col in range(n_cols):
        piv = None
        for i in range(row, n_rows):
            if A[i][col] != 0:
                piv = i
                break
        if piv is None:
            continue
        A[row], A[piv] = A[piv], A[row]
        inv = Q(1) / A[row][col]
        A[row] = [inv * x for x in A[row]]
        for i in range(n_rows):
            if i != row and A[i][col] != 0:
                f = A[i][col]
                A[i] = [A[i][j] - f * A[row][j] for j in range(n_cols)]
        rank += 1
        row += 1
        if row == n_rows:
            break
    return rank


def L_matrix_symbolic_quadratic(m: int, r: int) -> dict:
    """Relative matrix with quadratic monomial entries in leading coeffs.

    Each entry is a quadratic form on A = k^{free_rank_leading(m)}.
    Record as sparse list of (row, col, monom_dict) where monom_dict maps
    frozenset/pairs of leading-basis indices to coefficient.

    For storage: list of terms (row, col, i, j, c) meaning c * A_i * A_j
    (with i ≤ j, and off-diagonal counted once with the cross factor).
    """
    assert r in (1, 3)
    lead = leading_basis(m)
    dom = domain_basis(m, r)
    cod = codomain_basis(m, r)
    cod_index = {mny: i for i, mny in enumerate(cod)}
    n_rows, n_cols = len(cod), len(dom)
    n_A = len(lead)

    # term: (row, col, p, q, coeff) for coeff * A_p * A_q
    terms = []
    for col, (beta, i) in enumerate(dom):
        for p, (alpha, j) in enumerate(lead):
            for q, (alpha2, k) in enumerate(lead):
                c = B_coeff(i, j, k)
                if c == 0:
                    continue
                tot = (
                    beta[0] + alpha[0] + alpha2[0],
                    beta[1] + alpha[1] + alpha2[1],
                )
                if tot not in cod_index:
                    continue
                row = cod_index[tot]
                terms.append((row, col, p, q, str(c)))

    # Compress identical (row,col,p,q)
    from collections import defaultdict
    acc: dict[tuple[int, int, int, int], Q] = defaultdict(lambda: Q(0))
    for row, col, p, q, cs in terms:
        acc[(row, col, p, q)] += Q(cs)
    terms_c = [
        {"row": r0, "col": c0, "A_p": p, "A_q": q, "c": str(v)}
        for (r0, c0, p, q), v in sorted(acc.items())
        if v != 0
    ]

    return {
        "m": m,
        "r": r,
        "shape": [n_rows, n_cols],
        "n_leading_coeffs": n_A,
        "leading_basis": [
            {"y": list(mon), "Eminus_index": j} for mon, j in lead
        ],
        "domain_basis": [
            {"y": list(mon), "Eplus_index": i} for mon, i in dom
        ],
        "codomain_basis": [list(mon) for mon in cod],
        "nnz_quadratic_terms": len(terms_c),
        "terms": terms_c,
        "format": "relative sparse: entry(row,col) = sum_{p,q} c_{row,col,p,q} A_p A_q",
        "base_ring": (
            f"Q[A_0..A_{n_A - 1}] (coordinate ring of free leading jets of order m; "
            "multi-Rees: each A_s is itself a section of O(d-m) when degree is restored)"
        ),
        "operator": f"L_{r}(b) = B(b; a_m, a_m)",
    }


# ---------------------------------------------------------------------------
# Residual S3 character decomposition of free binary × target modules
# ---------------------------------------------------------------------------

def s3_character_dims_binary(weight_mod3: int, deg: int) -> dict:
    """Crude weight grading under the order-3 element ρ = r².

    On E_-: f0 has wt +1, f1 has wt -1 ≡ 2 (mod 3).
    On E_+: e0 wt 0, e1 wt +2, e2 wt -2 ≡ 1 (mod 3).

    A monomial y0^a y1^b has weight a·1 + b·(-1) = a - b (mod 3).
    Full jet y^α ⊗ target picks up target weight.

    S3 irreps: we record C3-weight spaces (eigenspaces of ρ).  Full S3
    projectors (triv/sign/std) require the reflection action; C3 already
    cuts rows before elimination (house rule: decompose before eliminate).
    """
    # For domain of L_r: monoms of deg=m+r times E+ weights
    return {
        "method": "C3-weight spaces (ρ = r² order 3) before residual reflection",
        "weight_convention": "y0:+1, y1:-1; e0:0, e1:+2, e2:-2 (mod 3)",
    }


def c3_decompose_domain(m: int, r: int) -> dict:
    """Split domain basis by total C3-weight mod 3."""
    buckets = {0: [], 1: [], 2: []}
    eplus_wt = {0: 0, 1: 2, 2: -2}  # ≡ 0,2,1 mod 3
    for idx, (mon, i) in enumerate(domain_basis(m, r)):
        a, b = mon
        w = (a * 1 + b * (-1) + eplus_wt[i]) % 3
        buckets[w].append(idx)
    return {
        "weight_0": buckets[0],
        "weight_1": buckets[1],
        "weight_2": buckets[2],
        "dims": {str(w): len(buckets[w]) for w in (0, 1, 2)},
    }


def c3_decompose_codomain(m: int, r: int) -> dict:
    buckets = {0: [], 1: [], 2: []}
    for idx, mon in enumerate(codomain_basis(m, r)):
        a, b = mon
        w = (a - b) % 3
        buckets[w].append(idx)
    return {
        "weight_0": buckets[0],
        "weight_1": buckets[1],
        "weight_2": buckets[2],
        "dims": {str(w): len(buckets[w]) for w in (0, 1, 2)},
    }


def c3_decompose_leading(m: int) -> dict:
    """Leading a_m: monoms order m × E_- (f0 wt+1, f1 wt-1)."""
    buckets = {0: [], 1: [], 2: []}
    eminus_wt = {0: 1, 1: -1}
    for idx, (mon, j) in enumerate(leading_basis(m)):
        a, b = mon
        w = (a - b + eminus_wt[j]) % 3
        buckets[w].append(idx)
    return {
        "weight_0": buckets[0],
        "weight_1": buckets[1],
        "weight_2": buckets[2],
        "dims": {str(w): len(buckets[w]) for w in (0, 1, 2)},
    }


def L_rank_by_c3_blocks(m: int, r: int, a_coeffs: list[Q]) -> dict:
    """Compute exact rank of each C3-weight block of L_r after projecting.

    Residual projection cuts rows (and columns) before materializing the
    full product matrix.
    """
    full = L_matrix_sparse(m, r, a_coeffs)
    # rebuild dense small
    n_rows, n_cols = full["shape"]
    A = [[Q(0) for _ in range(n_cols)] for _ in range(n_rows)]
    for r0, c0, vs in zip(full["coo_rows"], full["coo_cols"], full["coo_data"]):
        A[r0][c0] += Q(vs)

    d_dom = c3_decompose_domain(m, r)
    d_cod = c3_decompose_codomain(m, r)

    blocks = {}
    total_rank = 0
    for w in (0, 1, 2):
        rows_i = d_cod[f"weight_{w}"]
        cols_i = d_dom[f"weight_{w}"]
        # L preserves weight: B has weight 0, a⊗a has weight 2*wt(a);
        # for generic a of pure weight w_a, a⊗a has weight 2 w_a.
        # Here a is mixed; blocks may couple.  We still extract diagonal
        # weight blocks (same weight in/out) as the C3-isotypic pieces of
        # the operator when a is C3-semi-invariant.
        sub_rows = []
        sub_cols_list = cols_i
        for ri in rows_i:
            sub_rows.append([A[ri][cj] for cj in sub_cols_list])
        # rank of submatrix
        if not rows_i or not cols_i:
            rk = 0
        else:
            # COO from sub
            rr, cc, dd = [], [], []
            for i, ri in enumerate(rows_i):
                for j, cj in enumerate(cols_i):
                    if A[ri][cj] != 0:
                        rr.append(i)
                        cc.append(j)
                        dd.append(A[ri][cj])
            rk = exact_rank_from_coo(len(rows_i), len(cols_i), rr, cc, dd)
        blocks[str(w)] = {
            "n_rows": len(rows_i),
            "n_cols": len(cols_i),
            "rank": rk,
            "nullity": len(cols_i) - rk,
            "coker_dim": len(rows_i) - rk,
        }
        total_rank += rk

    return {
        "m": m,
        "r": r,
        "full_rank": full["rank_over_Q"],
        "sum_block_ranks": total_rank,
        "blocks": blocks,
        "domain_c3": d_dom["dims"],
        "codomain_c3": d_cod["dims"],
        "note": (
            "Diagonal C3-weight blocks.  For a general (mixed-weight) leading "
            "jet, off-diagonal weight blocks can appear; for C3-semi-invariant "
            "leading jets (single weight), L is block-diagonal and this is exact."
        ),
    }


# ---------------------------------------------------------------------------
# Generic rank sampling over Q (exact Fraction rank at random Q-points)
# ---------------------------------------------------------------------------

def sample_leading(m: int, seed: int = 1) -> list[Q]:
    """Deterministic Q-rational leading jet (not 'random modular')."""
    n = free_rank_leading(m)
    # Fixed pattern from seed; nonzero generic.
    out = []
    for i in range(n):
        out.append(Q((seed * 17 + i * 13 + 5) % 97 - 48, 1 + (i % 5)))
    # ensure not all zero
    if all(x == 0 for x in out):
        out[0] = Q(1)
    return out


def generic_rank_report(m: int, r: int, n_samples: int = 5) -> dict:
    """Exact ranks at several Q-points of the leading space.

    If all samples share the same rank ρ, this is the *generic* rank over Q
    (the rank-drop locus is a proper closed subset cut by Fitting minors).
    This is a characteristic-zero statement about the relative matrix, not a
    modular reduction (house rule 11).
    """
    ranks = []
    nulls = []
    samples = []
    for s in range(1, n_samples + 1):
        a = sample_leading(m, seed=s)
        M = L_matrix_sparse(m, r, a)
        ranks.append(M["rank_over_Q"])
        nulls.append(M["nullity_over_Q"])
        samples.append(
            {
                "seed": s,
                "rank": M["rank_over_Q"],
                "nullity": M["nullity_over_Q"],
                "coker": M["cokernel_dim_over_Q"],
                "nnz": M["nnz"],
                "shape": M["shape"],
            }
        )
    generic_rank = max(ranks)  # upper semicontinuity: generic = max
    return {
        "m": m,
        "r": r,
        "shape": samples[0]["shape"],
        "sample_ranks": ranks,
        "generic_rank_Q": generic_rank,
        "generic_nullity_Q": samples[0]["shape"][1] - generic_rank,
        "generic_coker_Q": samples[0]["shape"][0] - generic_rank,
        "rank_constant_on_samples": len(set(ranks)) == 1,
        "samples": samples,
        "label": "generic_fiber_exact_rank_over_Q",
        "bidegree_status": (
            "free R-module level (all base degrees simultaneously); "
            "not a single (m,d) instantiation"
        ),
    }


# ---------------------------------------------------------------------------
# Fitting ideal of [L | omega] for stage r=3
# ---------------------------------------------------------------------------

def F_plus_abstract(z: tuple[Q, Q, Q]) -> Q:
    """Smooth ternary cubic with j-line matching freedom; model cubic.

    Use F_+(z) = z0³ + z1³ + z2³ - 3 z0 z1 z2  (Hesse pencil member,
    smooth for this choice).  Used only for the R_3 residual class sample;
    the operator L_3 itself is independent of F_+.
    """
    z0, z1, z2 = z
    return z0**3 + z1**3 + z2**3 - Q(3) * z0 * z1 * z2


def R3_column_sparse(
    m: int,
    a_coeffs: list[Q],
    b_coeffs: list[Q],
    a2_coeffs: list[Q],
) -> dict:
    """Compute the residual column R_3 = 2 B(b; a, a2) + F_+(b) as scalar jet.

    Free-module level: a order m, b order m+1, a2 order m+2, output order 3m+3.
    """
    a = pack_leading(m, a_coeffs)
    # b uses domain basis for r=1
    b_keys = domain_basis(m, 1)
    assert len(b_coeffs) == len(b_keys)
    b = {b_keys[t]: Q(b_coeffs[t]) for t in range(len(b_keys))}
    # a2 uses leading basis for order m+2
    a2_keys = leading_basis(m + 2)
    assert len(a2_coeffs) == len(a2_keys)
    a2 = {a2_keys[t]: Q(a2_coeffs[t]) for t in range(len(a2_keys))}

    N = 3 * m + 3
    cod = monoms(N)
    cod_index = {mn: i for i, mn in enumerate(cod)}
    acc = [Q(0) for _ in cod]

    # 2 B(b; a, a2)
    for (beta, i), bi in b.items():
        if bi == 0:
            continue
        for (alpha, j), aj in a.items():
            if aj == 0:
                continue
            for (gamma, k), a2k in a2.items():
                if a2k == 0:
                    continue
                c = B_coeff(i, j, k)
                if c == 0:
                    continue
                tot = (
                    beta[0] + alpha[0] + gamma[0],
                    beta[1] + alpha[1] + gamma[1],
                )
                if tot in cod_index:
                    acc[cod_index[tot]] += Q(2) * c * bi * aj * a2k

    # F_+(b): b is E_+-valued of order m+1; F_+ is cubic, so total order 3(m+1).
    # For this to land in order 3m+3: 3m+3 = 3m+3, so 3(m+1)=3m+3 ✓.
    # Expand F_+(sum b_i y^{β} e_i) using trilinear polarization of F_+.
    # F_+(u) = u0³+u1³+u2³-3 u0 u1 u2; polarized Φ_+(u,v,w) accordingly.
    def Phi_plus(u, v, w):
        # (1/6) ∂∂∂ of F_+; for Hesse: symmetric
        # Φ_+(e_i,e_i,e_i)=1; Φ_+(e0,e1,e2)=-1/2
        s = Q(0)
        # cubic terms
        for t in range(3):
            s += u[t] * v[t] * w[t]
        s += (
            -Q(1, 2) * (
                u[0] * v[1] * w[2]
                + u[0] * v[2] * w[1]
                + u[1] * v[0] * w[2]
                + u[1] * v[2] * w[0]
                + u[2] * v[0] * w[1]
                + u[2] * v[1] * w[0]
            )
        )
        return s

    b_items = [(beta, i, val) for (beta, i), val in b.items() if val != 0]
    for beta1, i1, v1 in b_items:
        for beta2, i2, v2 in b_items:
            for beta3, i3, v3 in b_items:
                u = [Q(1 if t == i1 else 0) for t in range(3)]
                v = [Q(1 if t == i2 else 0) for t in range(3)]
                w = [Q(1 if t == i3 else 0) for t in range(3)]
                # Actually need basis vectors' F_+ polarization value
                # Build coefficient vectors:
                uu = [Q(0), Q(0), Q(0)]
                vv = [Q(0), Q(0), Q(0)]
                ww = [Q(0), Q(0), Q(0)]
                uu[i1] = Q(1)
                vv[i2] = Q(1)
                ww[i3] = Q(1)
                phi = Phi_plus(uu, vv, ww)
                if phi == 0:
                    continue
                tot = (
                    beta1[0] + beta2[0] + beta3[0],
                    beta1[1] + beta2[1] + beta3[1],
                )
                if tot in cod_index:
                    acc[cod_index[tot]] += phi * v1 * v2 * v3

    return {
        "m": m,
        "order": N,
        "column": [str(x) for x in acc],
        "nonzero": sum(1 for x in acc if x != 0),
        "is_zero": all(x == 0 for x in acc),
    }


def omega3_vanishes_sample(m: int, seed: int = 1) -> dict:
    """Test whether R_3 lies in im L_3 at a Q-sample of (a, b, a2).

    Solve L_3(x) + R_3 = 0; equivalent to rank[L_3 | R_3] == rank L_3.
    """
    a = sample_leading(m, seed=seed)
    # b in ker L_1 preferably
    L1 = L_matrix_sparse(m, 1, a)
    # take b = 0 first (always in ker); then a nontrivial ker vector if nullity>0
    n_b = free_rank_L_domain(m, 1)
    b = [Q(0)] * n_b
    if L1["nullity_over_Q"] > 0:
        # build null vector by RREF
        n_rows, n_cols = L1["shape"]
        A = [[Q(0) for _ in range(n_cols)] for _ in range(n_rows)]
        for r0, c0, vs in zip(L1["coo_rows"], L1["coo_cols"], L1["coo_data"]):
            A[r0][c0] += Q(vs)
        # nullspace
        from copy import deepcopy
        M = deepcopy(A)
        pivots = []
        row = 0
        for col in range(n_cols):
            piv = next((i for i in range(row, n_rows) if M[i][col] != 0), None)
            if piv is None:
                continue
            M[row], M[piv] = M[piv], M[row]
            inv = Q(1) / M[row][col]
            M[row] = [inv * x for x in M[row]]
            for i in range(n_rows):
                if i != row and M[i][col] != 0:
                    f = M[i][col]
                    M[i] = [M[i][j] - f * M[row][j] for j in range(n_cols)]
            pivots.append(col)
            row += 1
            if row == n_rows:
                break
        free = [c for c in range(n_cols) if c not in pivots]
        if free:
            f0 = free[0]
            b = [Q(0)] * n_cols
            b[f0] = Q(1)
            for i, c in enumerate(pivots):
                b[c] = -M[i][f0]

    a2 = sample_leading(m + 2, seed=seed + 10)
    # pad/truncate a2 to free_rank_leading(m+2)
    n_a2 = free_rank_leading(m + 2)
    a2 = (a2 + [Q(0)] * n_a2)[:n_a2]

    R = R3_column_sparse(m, a, b, a2)
    L3 = L_matrix_sparse(m, 3, a)

    # Augmented rank
    n_rows, n_cols = L3["shape"]
    rows = list(L3["coo_rows"])
    cols = list(L3["coo_cols"])
    data = [Q(x) for x in L3["coo_data"]]
    # add omega column at col = n_cols
    for i, vs in enumerate(R["column"]):
        v = Q(vs)
        if v != 0:
            rows.append(i)
            cols.append(n_cols)
            data.append(v)
    rank_aug = exact_rank_from_coo(n_rows, n_cols + 1, rows, cols, data)
    rank_L = L3["rank_over_Q"]
    vanishes = rank_aug == rank_L

    return {
        "m": m,
        "seed": seed,
        "L3_rank": rank_L,
        "augmented_rank": rank_aug,
        "omega3_in_image": vanishes,
        "R3_is_zero": R["is_zero"],
        "R3_nnz": R["nonzero"],
        "b_in_ker_L1": True,
        "L1_nullity": L1["nullity_over_Q"],
        "label": "sample_fiber_omega3_obstruction_over_Q",
        "bidegree_status": "free R-module level (all base degrees)",
    }


