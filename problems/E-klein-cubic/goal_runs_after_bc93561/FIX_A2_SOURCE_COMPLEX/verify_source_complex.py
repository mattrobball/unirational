def rank(rows):
    """rank by DIVISION-FREE elimination (row_i <- p*row_i - a*row_pivot);
    no field inversions are needed, which is what makes the bulk checks affordable."""
    if not rows: return 0
    M = [list(r) for r in rows]
    ncol = len(M[0]); r = 0
    for c in range(ncol):
        p = None
        for i in range(r, len(M)):
            if M[i][c]: p = i; break
        if p is None: continue
        M[r], M[p] = M[p], M[r]
        pv = M[r][c]
        for i in range(r + 1, len(M)):
            if M[i][c]:
                a = M[i][c]
                M[i] = [pv * x - a * y for x, y in zip(M[i], M[r])]
        r += 1
        if r == len(M): break
    return r

def same_space(b1, b2):
    if len(b1) != len(b2): return False
    return rank(b1) == rank(b2) == rank(b1 + b2)

def contained(small, big):
    """is span(small) contained in span(big)?"""
    return rank(big) == rank(big + small)

