    n = 11
    for g in gens: n = LCM(n, ORD[g])
    out = []
    def rec(i, rows):
        if i == len(gens):
            K = nullspace(rows, n)
            if K: out.append((tuple(tuple(v) for v in K), n))
            return
        g = gens[i]; m = ORD[g]
        R = [[RHO[g][a][b].up(n) for b in range(5)] for a in range(5)]
