def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_path(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def compose(left: tuple[int, ...], right: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(left[right[index]] for index in range(4))


IDENTITY = tuple(range(4))
S4 = tuple(itertools.permutations(range(4)))

PARTITIONS = (
    frozenset((frozenset((0, 1)), frozenset((2, 3)))),
    frozenset((frozenset((0, 2)), frozenset((1, 3)))),
    frozenset((frozenset((0, 3)), frozenset((1, 2)))),
)


def closure(generators: tuple[tuple[int, ...], ...]) -> frozenset[tuple[int, ...]]:
    subgroup = {IDENTITY}
    queue = [IDENTITY]
    while queue:
        value = queue.pop()
        for generator in generators:
            candidate = compose(value, generator)
            if candidate not in subgroup:
                subgroup.add(candidate)
                queue.append(candidate)
    return frozenset(subgroup)


def is_transitive(group: frozenset[tuple[int, ...]]) -> bool:
    return {element[0] for element in group} == set(range(4))


def is_imprimitive(group: frozenset[tuple[int, ...]]) -> bool:
    for partition in PARTITIONS:
        if all(
            frozenset(
                frozenset(element[index] for index in block) for block in partition
            )
            == partition
            for element in group
        ):
            return True
    return False


def element_order(element: tuple[int, ...]) -> int:
    value = IDENTITY
    for order in range(1, 5):
        value = compose(value, element)
        if value == IDENTITY:
            return order
    raise AssertionError("element order not found in S4")


def group_name(group: frozenset[tuple[int, ...]]) -> str:
    order = len(group)
    if order == 4:
        orders = {element_order(element) for element in group if element != IDENTITY}
        return "C4" if 4 in orders else "V4"
    if order == 8:
        return "D4"
    if order == 12:
        return "A4"
    if order == 24:
        return "S4"
    raise AssertionError(f"unexpected transitive subgroup order {order}")


def transitive_subgroup_lattice() -> dict:
    """Enumerate all transitive subgroups of S4 up to equality as sets."""

    # Standard generators for the five conjugacy types of transitive subgroups.
    # A4 is generated by two 3-cycles (0 1 2) and (0 1 3), not by a 3-cycle and
    # a 4-cycle (the latter pair generates all of S4).
    seeds = {
        "C4": ((1, 2, 3, 0),),
        "V4": ((1, 0, 3, 2), (2, 3, 0, 1)),
        "D4": ((1, 2, 3, 0), (1, 0, 3, 2)),
        "A4": ((1, 2, 0, 3), (1, 3, 2, 0)),
        "S4": ((1, 0, 2, 3), (1, 2, 3, 0)),
    }
    found: dict[frozenset[tuple[int, ...]], str] = {}
    for seed_name, generators in seeds.items():
        base = closure(generators)
        assert is_transitive(base), seed_name
        assert group_name(base) == seed_name, (seed_name, group_name(base), len(base))
        for conjugator in S4:
            conjugate_gens = tuple(
                compose(compose(conjugator, generator), inverse(conjugator))
                for generator in generators
            )
            group = closure(conjugate_gens)
            assert is_transitive(group)
            found[group] = group_name(group)

    by_name: dict[str, list[frozenset[tuple[int, ...]]]] = {}
    for group, name in found.items():
        by_name.setdefault(name, []).append(group)

    summary = {
        name: {
            "subgroup_count_up_to_equality": len(groups),
            "order": len(groups[0]),
            "imprimitive": is_imprimitive(groups[0]),
            "primitive": not is_imprimitive(groups[0]),
        }
        for name, groups in sorted(by_name.items())
    }
    assert set(summary) == {"C4", "V4", "D4", "A4", "S4"}
    assert summary["C4"]["imprimitive"] is True
    assert summary["V4"]["imprimitive"] is True
    assert summary["D4"]["imprimitive"] is True
    assert summary["A4"]["primitive"] is True
    assert summary["S4"]["primitive"] is True
    assert summary["A4"]["order"] == 12
    assert summary["S4"]["order"] == 24
    return {
        "ambient": "S4 on four geometric points of an integral quartic",
        "transitive_types": summary,
        "no_section_excluded": ["C4", "V4", "D4"],
        "no_section_remaining": ["A4", "S4"],
        "exclusion_reason": (
            "Each of C4, V4, D4 preserves a 2+2 block system.  A conjugate pair "
            "then yields a degree-two cycle over the quadratic block field whose "
            "secant residual is an F-point, contradicting the no-section branch."
        ),
        "remaining_reason": (
            "A4 and S4 are the primitive transitive subgroups of S4; they do not "
            "preserve a 2+2 system, so the conjugate-pair residual does not "
            "descend to F."
        ),
        "line_monodromy_caveat": (
            "A quartic point need not lie on any of the 27 lines, so 27-line "
            "monodromy alone cannot remove A4 or S4."
        ),
    }


def inverse(perm: tuple[int, ...]) -> tuple[int, ...]:
    result = [0, 0, 0, 0]
    for index, image in enumerate(perm):
        result[image] = index
    return tuple(result)


