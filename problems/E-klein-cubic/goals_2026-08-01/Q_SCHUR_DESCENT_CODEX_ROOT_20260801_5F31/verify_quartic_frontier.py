#!/usr/bin/env python3
"""Check the exact arithmetic and logical scope of the quartic frontier.

The D12 contained-line and full-stabilizer facts are independently rebuilt by
the parent hostile verifier listed in WORKLOG.md.  This verifier checks that
the serialized Q consequence uses those inputs with the exact degrees and
does not turn Voisin's degree-four alternative into a rational point.
"""

from __future__ import annotations

import json
import math
from itertools import permutations, product
from pathlib import Path


HERE = Path(__file__).resolve().parent
DATA = json.loads((HERE / "quartic_frontier.json").read_text())

assert DATA["format"] == "Q-SCHUR-QUARTIC-FRONTIER-v4"
assert DATA["group_order"] == 660
assert DATA["line_stabilizer_order"] == 12
assert DATA["line_orbit_degree"] == 660 // 12 == 55
assert DATA["linear_section_degree"] == 3
assert math.gcd(DATA["line_orbit_degree"], DATA["linear_section_degree"]) == 1
assert DATA["voisin_alternative_degree"] == 4

# A separable quadratic point on a cubic in split projective space descends by
# taking the residual third intersection on the conjugate secant line.
assert 3 - 2 == DATA["quadratic_residual_degree"] == 1


def partitions(total: int, ceiling: int | None = None):
    if total == 0:
        yield ()
        return
    ceiling = total if ceiling is None else min(total, ceiling)
    for first in range(ceiling, 0, -1):
        for rest in partitions(total - first, first):
            yield (first,) + rest


# If degrees one and two are excluded, the only effective partition of four
# is a single degree-four closed point.  A 3+1 decomposition already has a
# rational component.
survivors = [
    list(partition)
    for partition in partitions(4)
    if all(degree not in (1, 2) for degree in partition)
]
assert survivors == [DATA["no_point_partition_of_four"]] == [[4]]


# Enumerate the transitive subgroups of S4 generated by pairs and check their
# degree-four block systems.  This independently recovers the classical list
# C4, V4, D4, A4, S4 and leaves only A4/S4 when an intermediate quadratic
# field is forbidden.
S4 = tuple(permutations(range(4)))
identity = tuple(range(4))


def compose(left, right):
    return tuple(left[right[index]] for index in range(4))


def generated(generators):
    group = {identity}
    changed = True
    while changed:
        changed = False
        for left, right in product(tuple(group), tuple(generators) + tuple(group)):
            value = compose(left, right)
            if value not in group:
                group.add(value)
                changed = True
    return frozenset(group)


groups = {generated((first, second)) for first in S4 for second in S4}
transitive = {
    group for group in groups if {permutation[0] for permutation in group} == set(range(4))
}
assert sorted({len(group) for group in transitive}) == [4, 8, 12, 24]
assert len(transitive) == 9

block_partitions = (
    frozenset((frozenset((0, 1)), frozenset((2, 3)))),
    frozenset((frozenset((0, 2)), frozenset((1, 3)))),
    frozenset((frozenset((0, 3)), frozenset((1, 2)))),
)


def sends_partition_to_itself(group, partition):
    return all(
        frozenset(
            frozenset(permutation[value] for value in block)
            for block in partition
        ) == partition
        for permutation in group
    )


primitive = [
    group
    for group in transitive
    if not any(sends_partition_to_itself(group, partition) for partition in block_partitions)
]
assert sorted(len(group) for group in primitive) == [12, 24]
assert DATA["no_point_intermediate_degrees"] == []
assert DATA["no_point_galois_closure_groups"] == ["A4", "S4"]

# If the integral quartic spans a plane, the at-least-two-dimensional vector
# space of plane conics through it has a member meeting the plane cubic
# properly.  Bezout leaves degree two, which descends by the secant argument.
# A linearly spanning dimension <= 1 likewise gives a K-point or a K-line in
# the cubic.  Thus only a full P3 span survives in the no-point branch.
assert DATA["planar_quartic_conic_intersection_degree"] == 2 * 3 == 6
assert (
    DATA["planar_quartic_conic_intersection_degree"]
    - DATA["voisin_alternative_degree"]
    == DATA["planar_quartic_residual_degree"]
    == 2
)
assert DATA["no_point_quartic_linear_span_dimension"] == 3

# A linearly independent quartic point has coordinates forming a K-basis of
# its residue field.  Comparing that basis with 1,u,u^2,u^3 transports the
# rational normal cubic to a K-defined twisted cubic through the point.
# Its proper cubic-surface intersection has degree nine and residual degree
# five.  Excluding point degrees one and two leaves only an integral quintic.
assert DATA["twisted_cubic_degree"] == 3
assert DATA["twisted_cubic_surface_intersection_degree"] == 3 * 3 == 9
assert (
    DATA["twisted_cubic_surface_intersection_degree"]
    - DATA["voisin_alternative_degree"]
    == DATA["twisted_cubic_quartic_residual_degree"]
    == 5
)
survivors_five = [
    list(partition)
    for partition in partitions(5)
    if all(degree not in (1, 2) for degree in partition)
]
assert survivors_five == [DATA["no_point_partition_of_residual_five"]] == [[5]]
assert "BINARY Q VERDICT STILL OPEN" in DATA["verdict"]

print("PASS D12 orbit arithmetic gives an exact odd degree-55 surface point")
print("PASS cubic-surface degrees 3 and 55 are coprime")
print("PASS no-point Voisin alternative is one integral quartic point")
print("PASS no-point quartic is primitive with Galois closure A4 or S4")
print("PASS no-point quartic spans its full K-hyperplane P3")
print("PASS K-twisted-cubic intersection is quartic plus integral quintic")
print("BOUNDARY primitive quartic is not descended to degree two or one")
print("Q_SCHUR_QUARTIC_FRONTIER_EXACT")
