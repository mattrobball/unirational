#!/usr/bin/env python3
"""Solve the degree-12 ambient Morita-projector scheme on a47=1.

The homogeneous system is regenerated by the sealed full-wedge scanner.  The
saved leading ideal proves that every projective point lies on this chart and
that the chart has length three.  This script asks msolve for the actual
rational parametrization instead of treating the interrupted leading-ideal
run as a point certificate.
"""

from __future__ import annotations

import json
import runpy
import subprocess
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
AFFINE_INPUT = HERE / "ambient_degree12_a47_chart.in"
RUR_OUTPUT = HERE / "ambient_degree12_a47_chart.rur"
META = HERE / "ambient_degree12_a47_chart.json"


def main():
    fw = runpy.run_path(str(ROOT / "tmp" / "pfaffian_rank2_idempotent_attack" / "full_wedge.py"))
    scanner = fw["FullWedgeScanner"]()
    seeds = scanner.covariant_basis(12)
    assert len(seeds) == 48
    equations = scanner.landing_equations(seeds, extra_points=180)
    rows = [row for _pivot, row in equations]
    assert len(rows) == 471
    homogeneous = fw["msolve_input"](rows, len(seeds)).rstrip()
    AFFINE_INPUT.write_text(homogeneous + ",\na47-1\n")
    command = [
        "msolve", "-f", str(AFFINE_INPUT), "-o", str(RUR_OUTPUT),
        "-t", "4", "-v", "2", "-l", "2", "--random-seed", "0",
    ]
    completed = subprocess.run(
        command, cwd=ROOT, text=True, stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT, timeout=1800, check=False,
    )
    print(completed.stdout, end="")
    assert completed.returncode == 0, completed.returncode
    assert RUR_OUTPUT.is_file() and RUR_OUTPUT.stat().st_size > 0
    output = RUR_OUTPUT.read_text()
    assert output.strip() not in {"[-1]", "[1, 48, -1,[]]"}
    META.write_text(json.dumps({
        "scope": "degree-12 ambient decomposable covariant only; not the Fano five-plane",
        "prime": 23,
        "degree": 12,
        "covariant_dimension": len(seeds),
        "quadratic_rank": len(rows),
        "chart": "a47=1",
        "solver_returncode": completed.returncode,
        "rur_bytes": len(output.encode()),
        "seeds": [[int(output_index), list(exponents)] for output_index, exponents in seeds],
    }, indent=2) + "\n")
    print(f"WROTE {RUR_OUTPUT}")
    print("AMBIENT-D12-A47-RUR-COMPUTED")


if __name__ == "__main__":
    main()
