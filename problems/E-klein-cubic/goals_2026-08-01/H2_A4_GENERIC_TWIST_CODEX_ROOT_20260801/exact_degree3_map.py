X = sp.symbols("X")
PHI33_EXPR = sp.cyclotomic_poly(33, X)
FIELD = QQ.alg_field_from_poly(sp.Poly(PHI33_EXPR, X))
T = FIELD.unit
ZERO, ONE = FIELD.zero, FIELD.one
ZETA11, OMEGA = T**3, T**11


def embed_cyclotomic(value):
    out = ZERO
    for exponent, coefficient in enumerate(value.a):
        coefficient = Fraction(coefficient)
        out += FIELD.convert(sp.Rational(coefficient.numerator, coefficient.denominator)) * ZETA11**exponent
    return out


def nullspace(rows):
    work = [[FIELD.convert(value) for value in row] for row in rows]
    row_count, column_count = len(work), len(work[0])
    pivots = []
    pivot_row = 0
    for column in range(column_count):
        pivot = next((row for row in range(pivot_row, row_count) if work[row][column] != ZERO), None)
        if pivot is None:
            continue
        work[pivot_row], work[pivot] = work[pivot], work[pivot_row]
        inverse = ONE / work[pivot_row][column]
        work[pivot_row] = [inverse * value for value in work[pivot_row]]
        for row in range(row_count):
            if row == pivot_row or work[row][column] == ZERO:
                continue
            scale = work[row][column]
            work[row] = [left - scale * right for left, right in zip(work[row], work[pivot_row])]
        pivots.append(column)
        pivot_row += 1
        if pivot_row == row_count:
            break
    free = [column for column in range(column_count) if column not in pivots]
    basis = []
    for free_column in free:
        vector = [ZERO] * column_count
        vector[free_column] = ONE
        for row, pivot in reversed(list(enumerate(pivots))):
            vector[pivot] = -sum(
                (work[row][column] * vector[column] for column in free),
                ZERO,
            )
        basis.append(vector)
    assert all(sum((a * b for a, b in zip(row, vector)), ZERO) == ZERO for row in rows for vector in basis)
    return basis


def monomials(degree):
    return tuple((a, b, degree - a - b) for a in range(degree + 1) for b in range(degree - a + 1))


def poly_add(left, right):
    out = dict(left)
    for exponent, coefficient in right.items():
        out[exponent] = out.get(exponent, ZERO) + coefficient
        if out[exponent] == ZERO:
            del out[exponent]
    return out


def poly_mul(left, right):
    out = {}
    for a, ca in left.items():
        for b, cb in right.items():
            exponent = tuple(x + y for x, y in zip(a, b))
            out[exponent] = out.get(exponent, ZERO) + ca * cb
    return {exponent: coefficient for exponent, coefficient in out.items() if coefficient != ZERO}


def poly_pow(polynomial, exponent):
    out = {(0, 0, 0): ONE}
    for _ in range(exponent):
        out = poly_mul(out, polynomial)
    return out


def monomial_transform(matrix, degree):
    basis = monomials(degree)
    index = {exponent: position for position, exponent in enumerate(basis)}
    linear = []
    for row in matrix:
        linear.append({tuple(int(i == variable) for i in range(3)): value for variable, value in enumerate(row) if value != ZERO})
    transform = [[ZERO] * len(basis) for _ in basis]
    for column, exponent in enumerate(basis):
        polynomial = {(0, 0, 0): ONE}
        for form, power in zip(linear, exponent):
            polynomial = poly_mul(polynomial, poly_pow(form, power))
        for output_exponent, coefficient in polynomial.items():
            transform[index[output_exponent]][column] = coefficient
    return transform


def exact_a4():
    first, _ = group.two_a5_classes()
    a, b, a5 = first
    involutions = [g for g in a5 if group.ORDERS[g] == 2]
    v4 = next(
        frozenset({group.ew.fone, x, y, group.gmul(x, y)})
        for index, x in enumerate(involutions)
        for y in involutions[index + 1:]
        if group.gmul(x, y) == group.gmul(y, x)
    )
    a4 = group.normalizer(v4, a5)
    ga, gb = group.gens(a4)
    assert group.ORDERS[ga] == 2 and group.ORDERS[gb] == 3
    assert group.order(group.gmul(ga, gb)) == 3
    rho = [
        [[embed_cyclotomic(value) for value in row] for row in group.ew.rho[g]]
        for g in (ga, gb)
    ]
    source = [
        [[-ONE, ZERO, ZERO], [ZERO, -ONE, ZERO], [ZERO, ZERO, ONE]],
        [[ZERO, ONE, ZERO], [ZERO, ZERO, ONE], [ONE, ZERO, ZERO]],
    ]
    return (ga, gb), source, rho


def covariant_basis(source, rho, degree, character):
    mons = monomials(degree)
    count = len(mons)
    rows = []
    # ga maps trivially to A4/V4; the selected gb maps to the square of the
    # canonical quotient generator, matching the installed subgroup audit.
    character_values = (ONE, OMEGA ** (2 * character))
    for sigma, target, scalar in zip(source, rho, character_values):
        transform = monomial_transform(sigma, degree)
        for output in range(5):
            for monomial in range(count):
                row = [ZERO] * (5 * count)
                # C * transform^T = scalar * rho * C.
                for source_monomial in range(count):
                    row[output * count + source_monomial] += transform[monomial][source_monomial]
                for source_output in range(5):
                    row[source_output * count + monomial] -= scalar * target[output][source_output]
                rows.append(row)
    vectors = nullspace(rows)
    return mons, vectors


def output_polynomials(mons, vector):
    count = len(mons)
    return [
        {exponent: vector[output * count + index] for index, exponent in enumerate(mons) if vector[output * count + index] != ZERO}
        for output in range(5)
    ]


def landing_equations(mons, basis):
    outputs = [output_polynomials(mons, vector) for vector in basis]
    dimension = len(basis)
    equations = {}
    for i in range(5):
        j = (i + 1) % 5
        for first in range(dimension):
            for second in range(dimension):
                square = poly_mul(outputs[first][i], outputs[second][i])
                for third in range(dimension):
                    term = poly_mul(square, outputs[third][j])
                    parameter_exponent = tuple(
                        int(first == k) + int(second == k) + int(third == k)
                        for k in range(dimension)
                    )
                    for source_exponent, coefficient in term.items():
                        target = equations.setdefault(source_exponent, {})
                        target[parameter_exponent] = target.get(parameter_exponent, ZERO) + coefficient
    return {
        exponent: {parameter: coefficient for parameter, coefficient in polynomial.items() if coefficient != ZERO}
        for exponent, polynomial in equations.items()
        if any(coefficient != ZERO for coefficient in polynomial.values())
    }


def rational_string(value):
    numerator, denominator = int(value.numerator), int(value.denominator)
    return str(numerator) if denominator == 1 else f"({numerator}/{denominator})"


def field_string(value):
    terms = []
    for (exponent,), coefficient in sorted(value.to_dict().items()):
        q = rational_string(coefficient)
        monomial = "1" if exponent == 0 else ("t" if exponent == 1 else f"t^{exponent}")
        terms.append(f"({q})*{monomial}")
    return "+".join(terms) if terms else "0"


def chart_string(polynomial, fixed):
    terms = []
    for exponent, coefficient in sorted(polynomial.items()):
        factors = []
        for index, power in enumerate(exponent):
            if index == fixed or not power:
                continue
            factors.append(f"p{index}" if power == 1 else f"p{index}^{power}")
        monomial = "*".join(factors) if factors else "1"
        terms.append(f"({field_string(coefficient)})*{monomial}")
    return "+".join(terms) if terms else "0"


def serialize_field(value):
    output = [[0, 1] for _ in range(20)]
    for (exponent,), coefficient in value.to_dict().items():
        output[exponent] = [int(coefficient.numerator), int(coefficient.denominator)]
    return output


def serialize_vector(vector):
    return [serialize_field(value) for value in vector]


def determinant(matrix):
    work = [list(row) for row in matrix]
    result = ONE
    for column in range(len(work)):
        pivot = next((row for row in range(column, len(work)) if work[row][column] != ZERO), None)
        if pivot is None:
            return ZERO
        if pivot != column:
            work[pivot], work[column] = work[column], work[pivot]
            result = -result
        unit = work[column][column]
        result *= unit
        for row in range(column + 1, len(work)):
            if work[row][column] == ZERO:
                continue
            scale = work[row][column] / unit
            work[row] = [left - scale * right for left, right in zip(work[row], work[column])]
    return result


def character_line(rho, character):
    scalars = (ONE, OMEGA ** (2 * character))
    rows = []
    for matrix, scalar in zip(rho, scalars):
        rows.extend([
            [matrix[i][j] - (scalar if i == j else ZERO) for j in range(5)]
            for i in range(5)
        ])
    basis = nullspace(rows)
    assert len(basis) == 1
    return basis[0]


def decomposition_matrix(source, rho):
    u = character_line(rho, 1)
    v = character_line(rho, 2)
    degree_one_monomials, standard_basis = covariant_basis(source, rho, 1, character=0)
    assert len(standard_basis) == 1
    vector = standard_basis[0]
    count = len(degree_one_monomials)
    coordinate_exponents = ((1, 0, 0), (0, 1, 0), (0, 0, 1))
    standard_columns = []
    for exponent in coordinate_exponents:
        monomial = degree_one_monomials.index(exponent)
        standard_columns.append([vector[output * count + monomial] for output in range(5)])
    columns = [u, v, *standard_columns]
    matrix = [[columns[column][row] for column in range(5)] for row in range(5)]
    assert determinant(matrix) != ZERO
    return matrix


def klein_in_basis(matrix):
    linear = []
    for row in range(5):
        linear.append({
            tuple(int(index == variable) for index in range(5)): matrix[row][variable]
            for variable in range(5)
            if matrix[row][variable] != ZERO
        })
    output = {}
    for index in range(5):
        term = poly_mul(poly_mul(linear[index], linear[index]), linear[(index + 1) % 5])
        output = poly_add(output, term)
    expected = {
        (3, 0, 0, 0, 0),
        (0, 3, 0, 0, 0),
        (1, 0, 2, 0, 0),
        (1, 0, 0, 2, 0),
        (1, 0, 0, 0, 2),
        (0, 1, 2, 0, 0),
        (0, 1, 0, 2, 0),
        (0, 1, 0, 0, 2),
        (0, 0, 1, 1, 1),
    }
    assert set(output) == expected
    constants = {
        "a": output[(3, 0, 0, 0, 0)],
        "b": output[(0, 3, 0, 0, 0)],
        "c": output[(1, 0, 2, 0, 0)],
        "d": output[(0, 1, 2, 0, 0)],
        "e": output[(0, 0, 1, 1, 1)],
    }
    assert all(value != ZERO for value in constants.values())
    assert output[(1, 0, 0, 2, 0)] == constants["c"] * OMEGA**2
    assert output[(1, 0, 0, 0, 2)] == constants["c"] * OMEGA
    assert output[(0, 1, 0, 2, 0)] == constants["d"] * OMEGA
    assert output[(0, 1, 0, 0, 2)] == constants["d"] * OMEGA**2
    return output, constants


