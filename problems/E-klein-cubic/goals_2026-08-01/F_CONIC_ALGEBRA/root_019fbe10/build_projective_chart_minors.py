#!/usr/bin/env python3
"""Build six-variable Jacobian-minor smoothness tests chart by chart.

This is an optimized companion to ``build_projective_residue_probe.py``.
After dehomogenizing one base and one plane coordinate, the complete
intersection ``(D_g,c)`` lives in affine six-space.  It is smooth exactly
when the ideal generated by ``D_g``, ``c``, and every 2-by-2 Jacobian minor
is the unit ideal.  Each of the fifteen projective chart pairs gets a
separate Singular script so runs are independently checkpointed.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import sympy as sp

from build_projective_residue_probe import (
    BASE,
    DEFAULT_PRIME,
    DEFAULT_ZETA,
    POINT,
    cubic,
    homogenize,
    primitive_affine,
    singular,
)


HERE = Path(__file__).resolve().parent


def emit(
    g: int,
    prime: int,
    zeta: int,
    selected_base: str | None = None,
    selected_point: str | None = None,
) -> dict:
    D, degree = homogenize(primitive_affine(g, prime), prime)
    c = cubic(prime, zeta)
    records = []
    for base_chart in BASE:
        if selected_base is not None and str(base_chart) != selected_base:
            continue
        for point_chart in POINT:
            if selected_point is not None and str(point_chart) != selected_point:
                continue
            substitutions = {base_chart: 1, point_chart: 1}
            variables = [item for item in (*BASE, *POINT) if item not in substitutions]
            Dexpr = sp.Poly(D.as_expr().subs(substitutions), *variables, modulus=prime).as_expr()
            cexpr = sp.Poly(c.as_expr().subs(substitutions), *variables, modulus=prime).as_expr()
            jacobian = [
                [sp.diff(Dexpr, variable) for variable in variables],
                [sp.diff(cexpr, variable) for variable in variables],
            ]
            minors = []
            for left in range(len(variables)):
                for right in range(left + 1, len(variables)):
                    value = sp.expand(
                        jacobian[0][left] * jacobian[1][right]
                        - jacobian[0][right] * jacobian[1][left]
                    )
                    if value != 0:
                        minors.append(sp.Poly(value, *variables, modulus=prime).as_expr())
            label = f"{base_chart}_{point_chart}"
            output = HERE / f"projective_minor_g{g}_p{prime}_{label}.sing"
            generators = [Dexpr, cexpr, *minors]
            rows = [
                f"ring R={prime},({','.join(map(str, variables))}),dp;",
                "option(redSB);",
                "short=0;",
                "ideal J=" + ",".join(singular(item) for item in generators) + ";",
                "ideal G=std(J);",
                f'print("T_MINOR_CHART_{label}_NF1="+string(reduce(1,G)));',
                f'print("T_MINOR_CHART_{label}_DIM="+string(dim(G)));',
                f'print("T_MINOR_CHART_{label}_DONE");',
                "quit;",
            ]
            output.write_text("\n".join(rows) + "\n")
            msolve_output = HERE / f"projective_minor_g{g}_p{prime}_{label}.ms"
            msolve_rows = [",".join(map(str, variables)), str(prime)]
            for index, generator in enumerate(generators):
                suffix = "," if index + 1 < len(generators) else ""
                msolve_rows.append(singular(generator) + suffix)
            msolve_output.write_text("\n".join(msolve_rows) + "\n")
            records.append(
                {
                    "base_chart": str(base_chart),
                    "point_chart": str(point_chart),
                    "variables": list(map(str, variables)),
                    "nonzero_minors": len(minors),
                    "script": output.name,
                    "msolve_input": msolve_output.name,
                }
            )
    payload = {
        "scope": "projective complete-intersection smoothness over finite residue field",
        "logical_use": "unit ideals lift smoothness to characteristic zero; no point-count inference",
        "g": g,
        "prime": prime,
        "zeta11_residue": zeta,
        "D_degree": degree,
        "charts": records,
    }
    (HERE / f"projective_minor_g{g}_p{prime}.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n"
    )
    return payload


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--g", type=int, default=1)
    parser.add_argument("--prime", type=int, default=DEFAULT_PRIME)
    parser.add_argument("--zeta", type=int, default=DEFAULT_ZETA)
    parser.add_argument("--base-chart", choices=[str(item) for item in BASE])
    parser.add_argument("--point-chart", choices=[str(item) for item in POINT])
    args = parser.parse_args()
    payload = emit(
        args.g,
        args.prime,
        args.zeta,
        selected_base=args.base_chart,
        selected_point=args.point_chart,
    )
    print(json.dumps(payload, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
