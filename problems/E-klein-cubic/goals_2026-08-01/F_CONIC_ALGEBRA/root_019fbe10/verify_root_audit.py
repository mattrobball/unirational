#!/usr/bin/env python3
"""Independent replay for the isolated terminal Goal F audit.

This verifier binds the parent terminal packet, checks the missing inverse
normalization identities directly, invokes an independent checker for every
hypothesis in the proper Nakayama lift of the base ideal, and reruns every
modular product chart used to bound the universal incidence singular locus.
"""

from __future__ import annotations

from hashlib import sha256
import json
from pathlib import Path
import shutil
import subprocess
import sys

import sympy as sp


HERE = Path(__file__).resolve().parent
PARENT = HERE.parent
LIFT_CHECK = HERE / "agent_valuation_classgroup/verify_lift_hypotheses.py"


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def digest(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def run(command: list[str], cwd: Path, timeout: int = 900) -> str:
    return subprocess.run(
        command,
        cwd=cwd,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=True,
        timeout=timeout,
    ).stdout


def verify_inverse_normalization() -> None:
    payload = json.loads((PARENT / "infinity_obstruction.json").read_text())
    A, B, Y, T = sp.symbols("A B Y T")
    D = sum(
        coefficient * A**a * B**b * Y**yy * T**tt
        for a, b, yy, tt, coefficient in payload["leading_coefficient"]["D_sparse"]
    )
    p = 100 * A + 4 * B + 2 * T + 12 * Y - 1623
    q = 212 * B + 106 * T + 36 * Y + 81
    rho = 53 * p - q
    r = p / rho
    denominator_base = (53 * A + 6 * Y - 861) ** 2
    differences = (
        A - (sp.Rational(33, 2) - 3750 * r**2),
        Y - (33125 * r**2 - sp.Rational(9, 4) + rho / 600),
        B - (-5625 * r**2 - T / 2 + (r / 4 - sp.Rational(1, 200)) * rho),
    )
    expected = (
        D / (8 * denominator_base),
        -53 * D / (48 * denominator_base),
        3 * D / (16 * denominator_base),
    )
    for index, (actual, wanted) in enumerate(zip(differences, expected, strict=True)):
        require(sp.cancel(actual - wanted) == 0, f"inverse normalization identity {index}")


def verify_normality_charts() -> None:
    executable = shutil.which("Singular") or "/opt/homebrew/bin/Singular"
    require(Path(executable).is_file(), "Singular executable")
    certificate = json.loads((HERE / "NET_NORMALITY_CERTIFICATE.json").read_text())
    require(certificate["prime"] == 89 and certificate["zeta"] == 2, "normality prime")
    records = certificate["charts"]
    require(len(records) == 9, "normality chart count")
    require(
        {(row["plane_chart"], row["lambda_chart"]) for row in records}
        == {(plane, lam) for plane in ("X", "y", "w") for lam in ("l0", "l1", "l2")},
        "normality chart cover",
    )
    for row in records:
        script = HERE / row["script"]
        output = run([executable, "-q", str(script)], HERE, timeout=240)
        dimension = None
        for line in output.splitlines():
            if line.startswith("DIM="):
                dimension = int(line.split("=", 1)[1])
        require(
            "UNIT=1" in output or (dimension is not None and dimension <= 0),
            f"positive-dimensional singular locus in {script.name}\n{output}",
        )
        require(
            f"NET_NORMALITY_{row['plane_chart']}_{row['lambda_chart']}_P89_DONE" in output,
            f"normality completion marker: {script.name}",
        )


def main() -> None:
    require((HERE / "STATUS.md").read_text().splitlines()[0] == "F-CONIC-CRITERION-EMPTY", "status")
    resolution = (HERE / "RESOLUTION.md").read_text()
    for phrase in (
        "ord_D(c6)=1",
        "integral separable closed point",
        "Cl(X_net) is generated by H_z, H_lambda, E",
        "ind(C/C(D))=3",
        "C(K_proj)=empty",
        "Klein-cubic headline remains `OPEN`",
    ):
        require(phrase in resolution, f"resolution boundary missing: {phrase}")

    parent = run([sys.executable, str(PARENT / "verify.py")], PARENT)
    for marker in (
        "GOAL_F_EXACT_FIELD_LAYER_ACCEPT",
        "GOAL_F_BOUNDED_SCREENS_SCOPED_ACCEPT",
        "GOAL_F_CONIC_CRITERION_EMPTY_ACCEPT",
    ):
        require(marker in parent, f"parent replay marker missing: {marker}")
    print("ROOT_PARENT_TERMINAL_PACKET_ACCEPT")

    verify_inverse_normalization()
    print("ROOT_INFINITY_NORMALIZATION_INVERSE_ACCEPT")

    require(LIFT_CHECK.is_file(), "base-scheme lift-hypothesis verifier")
    lift = run([sys.executable, str(LIFT_CHECK)], LIFT_CHECK.parent, timeout=600)
    for marker in (
        "EXACT_BASE_SUBSCHEME_INCLUSION_ACCEPT",
        "GOOD_FIBER_PROJECTIVE_IDEAL_EQUALITY_ACCEPT",
        "FINITE_FLAT_DEGREE3_MODEL_ACCEPT",
        "EXACT_CONORMAL_RANK2_INPUT_ACCEPT",
    ):
        require(marker in lift, f"base-lift marker missing: {marker}")
    print("ROOT_BASE_SCHEME_NAKAYAMA_LIFT_INPUTS_ACCEPT")

    verify_normality_charts()
    print("ROOT_UNIVERSAL_NET_NORMALITY_CHARTS_ACCEPT")

    seal_path = HERE / "SEAL.json"
    if seal_path.exists():
        seal = json.loads(seal_path.read_text())
        require(seal["exit"] == "F-CONIC-CRITERION-EMPTY", "seal exit")
        require(seal["headline"] == "OPEN", "headline scope")
        for relative, expected in seal["sha256"].items():
            require(digest(HERE / relative) == expected, f"seal hash mismatch: {relative}")

    print("ROOT_GOAL_F_CONIC_CRITERION_EMPTY_ACCEPT")


if __name__ == "__main__":
    main()
