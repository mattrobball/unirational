#!/usr/bin/env python3
"""Exact low-degree audit of the faithful polarized Stage-B Segre section.

The 690 rows of the polarized map are bilinear forms on

    P(Q) x P(Y) = P^36 x P^242,

where Y=(B1 tensor Q) direct_sum B2 has dimension 243.  Their common zero
scheme is the intersection of the Segre variety with the projectivized kernel
of the 690 by 8991 coefficient flattening.

This script does two things.

1. It computes exact Hilbert/Macaulay dimension floors for a certificate
   J_(a,b)=R_(a,b), where J is generated by the 690 bidegree-(1,1) equations.
2. It replays a bounded exact 10767-square minor of the complete P3
   contraction.  Together with the exact full M2-syzygy basis, this proves
   that the polarized equations have no q-linear syzygy and hence gives the
   exact quotient dimension in bidegree (2,1).

The latter is a genuine low-degree theorem but is not an emptiness
certificate.  No saturation or large Segre Macaulay matrix is launched.
"""

from __future__ import annotations

import argparse
import ctypes
import hashlib
import json
import math
import subprocess
from pathlib import Path

import numpy as np


HERE = Path(__file__).resolve().parent
P25 = HERE.parents[1]
ROOT = HERE.parents[3]
RELATION = ROOT / "certificates" / "degree25_finite_module" / "relation_matrix.npz"
GLOBAL = P25 / "parallel" / "stageb_global_basis"
FULL_BASIS = GLOBAL / "full_linear_syzygy_basis.npy"
FULL_BASIS_MANIFEST = GLOBAL / "full_basis_manifest.json"
FULL_P3 = GLOBAL / "full_p3_contractions.npy"
FULL_P3_MANIFEST = GLOBAL / "full_p3_manifest.json"
P3_MINOR = GLOBAL / "lt_cover_nonpure_minor.npz"
OUTPUT = HERE / "polarized_segre_result.json"

P = 89
NQ = 37
NY = 243
NROWS = 690
NULLITY = 10767


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_array(array: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(array).tobytes()).hexdigest()


def weak_compositions(total: int, parts: int) -> list[tuple[int, ...]]:
    if parts == 1:
        return [(total,)]
    answer: list[tuple[int, ...]] = []
    for first in range(total + 1):
        for tail in weak_compositions(total - first, parts - 1):
            answer.append((first,) + tail)
    return answer


def free_plus_speculative_gib() -> float | None:
    try:
        output = subprocess.check_output(["vm_stat"], text=True)
    except (FileNotFoundError, subprocess.CalledProcessError):
        return None
    page_size = 16384
    free = speculative = None
    for line in output.splitlines():
        if line.startswith("Mach Virtual Memory Statistics") and "page size of" in line:
            page_size = int(line.split("page size of", 1)[1].split("bytes", 1)[0])
        elif line.startswith("Pages free:"):
            free = int(line.split(":", 1)[1].strip().rstrip("."))
        elif line.startswith("Pages speculative:"):
            speculative = int(line.split(":", 1)[1].strip().rstrip("."))
    if free is None or speculative is None:
        return None
    return (free + speculative) * page_size / 2**30


def fflas_rank(matrix: np.ndarray) -> int:
    if matrix.dtype != np.float64 or not matrix.flags.c_contiguous:
        raise TypeError("FFLAS input must be contiguous float64")
    library = ctypes.CDLL("/opt/homebrew/lib/libffpack_c.dylib")
    function = library.Rank_modular_double
    function.argtypes = [
        ctypes.c_double,
        ctypes.c_size_t,
        ctypes.c_size_t,
        np.ctypeslib.ndpointer(np.float64, flags="C_CONTIGUOUS"),
        ctypes.c_size_t,
        ctypes.c_bool,
    ]
    function.restype = ctypes.c_size_t
    rows, columns = matrix.shape
    return int(function(float(P), rows, columns, matrix, columns, False))


def segre_piece(a: int, b: int) -> int:
    if a < 0 or b < 0:
        return 0
    return math.comb(a + 36, 36) * math.comb(b + 242, 242)


def macaulay_dimensions(a: int, b: int) -> tuple[int, int]:
    return NROWS * segre_piece(a - 1, b - 1), segre_piece(a, b)


def koszul_euler(a: int, b: int) -> int:
    """Coefficient of H_R(s,t)*(1-st)^690 at (a,b).

    This is an exact Euler characteristic, not by itself a Hilbert function:
    Koszul homology can be nonzero.
    """
    return sum(
        (-1) ** i * math.comb(NROWS, i) * segre_piece(a - i, b - i)
        for i in range(min(a, b, NROWS) + 1)
    )


def build_polarization() -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    with np.load(RELATION, allow_pickle=False) as frozen:
        seeds = frozen["seed_F3"].astype(np.uint8)
        offsets = frozen["off3"].astype(np.int32)
        if int(frozen["prime"]) != P:
            raise AssertionError("relation prime mismatch")
    if seeds.shape != (NROWS, 14134):
        raise AssertionError(f"unexpected relation shape {seeds.shape}")

    q1 = weak_compositions(1, NQ)
    q2 = weak_compositions(2, NQ)
    variable_of = [monomial.index(1) for monomial in q1]

    m2 = np.empty((NROWS, 21, NQ), dtype=np.uint8)
    for j in range(21):
        block = seeds[:, int(offsets[7 + j]) : int(offsets[8 + j])]
        for monomial_index, variable in enumerate(variable_of):
            m2[:, j, variable] = block[:, monomial_index]

    beta = np.zeros((NROWS, 6, NQ, NQ), dtype=np.uint8)
    inverse_two = pow(2, -1, P)
    for component in range(6):
        block = seeds[
            :, int(offsets[1 + component]) : int(offsets[2 + component])
        ]
        for monomial_index, exponent in enumerate(q2):
            variables = [
                variable
                for variable, power in enumerate(exponent)
                for _ in range(power)
            ]
            u, v = variables
            coefficient = block[:, monomial_index]
            if u == v:
                beta[:, component, u, v] = coefficient
            else:
                half = (
                    coefficient.astype(np.uint16) * inverse_two % P
                ).astype(np.uint8)
                beta[:, component, u, v] = half
                beta[:, component, v, u] = half

    # coeff[a,u,c] is the coefficient of q_u*y_c in row a.  The first
    # 222 y coordinates are (component,v), followed by the 21 B2 coordinates.
    coefficient = np.concatenate(
        [
            beta.transpose(0, 2, 1, 3).reshape(NROWS, NQ, 222),
            m2.transpose(0, 2, 1),
        ],
        axis=2,
    )
    if coefficient.shape != (NROWS, NQ, NY):
        raise AssertionError("bad polarized coefficient shape")

    # Recheck beta(q,q)=M1(q) coefficient by coefficient.
    for component in range(6):
        block = seeds[
            :, int(offsets[1 + component]) : int(offsets[2 + component])
        ]
        for monomial_index, exponent in enumerate(q2):
            variables = [
                variable
                for variable, power in enumerate(exponent)
                for _ in range(power)
            ]
            u, v = variables
            recovered = beta[:, component, u, v].astype(np.uint16)
            if u != v:
                recovered += beta[:, component, v, u]
            if not np.array_equal(recovered % P, block[:, monomial_index]):
                raise AssertionError("polarization identity failed")
    return seeds, m2, beta, coefficient


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--min-free-gib",
        type=float,
        default=10.0,
        help="guard for the roughly 0.95-GiB exact P3-minor rank",
    )
    parser.add_argument(
        "--skip-minor-rank",
        action="store_true",
        help="compute dimensions and hashes but do not allocate the rank matrix",
    )
    args = parser.parse_args()

    required = [
        RELATION,
        FULL_BASIS,
        FULL_BASIS_MANIFEST,
        FULL_P3,
        FULL_P3_MANIFEST,
        P3_MINOR,
    ]
    for path in required:
        if not path.is_file():
            raise FileNotFoundError(path)

    seeds, m2, beta, coefficient = build_polarization()
    flatten_m2 = m2.reshape(NROWS, 21 * NQ)
    column_nnz = np.count_nonzero(flatten_m2, axis=0)
    unit_columns = np.flatnonzero(column_nnz == 1)
    unit_rows = np.asarray(
        [int(np.flatnonzero(flatten_m2[:, column])[0]) for column in unit_columns],
        dtype=np.int32,
    )
    if len(unit_columns) != NROWS or len(np.unique(unit_rows)) != NROWS:
        raise AssertionError("M2 systematic identity columns missing")
    if not np.array_equal(
        flatten_m2[unit_rows][:, unit_columns], np.eye(NROWS, dtype=np.uint8)
    ):
        raise AssertionError("M2 systematic minor is not the identity")

    coefficient_nnz = int(np.count_nonzero(coefficient))
    row_nnz = np.count_nonzero(coefficient, axis=(1, 2))
    # M2 is a coordinate projection of the full coefficient flattening, so
    # the displayed identity minor also proves the 690 bilinear rows independent.
    equation_rank = NROWS
    kernel_dimension = NQ * NY - equation_rank

    feasible: list[dict] = []
    for a in range(1, 41):
        for b in range(1, 41):
            source, target = macaulay_dimensions(a, b)
            if source >= target:
                feasible.append(
                    {
                        "a": a,
                        "b": b,
                        "total_degree": a + b,
                        "source_dimension": source,
                        "target_dimension": target,
                        "source_excess": source - target,
                    }
                )
    min_total = min(item["total_degree"] for item in feasible)
    first_total = [item for item in feasible if item["total_degree"] == min_total]
    smallest_target = min(feasible, key=lambda item: item["target_dimension"])
    predecessor_dimension = segre_piece(
        smallest_target["a"] - 1, smallest_target["b"] - 1
    )
    smallest_target["formal_sparse_nonzeros"] = (
        predecessor_dimension * coefficient_nnz
    )
    smallest_target["dense_matrix_entries"] = (
        smallest_target["source_dimension"] * smallest_target["target_dimension"]
    )

    diagonal_first = None
    for degree in range(1, 100):
        source, target = macaulay_dimensions(degree, degree)
        if source >= target:
            diagonal_first = {
                "degree": degree,
                "source_dimension": source,
                "target_dimension": target,
            }
            break
    assert diagonal_first is not None and diagonal_first["degree"] == 4

    endpoint_q_one = next(
        item for item in feasible if item["a"] == 1
    )
    endpoint_y_one = next(
        item for item in feasible if item["b"] == 1
    )
    # Sorting is necessary because feasible was generated a-major.
    endpoint_q_one = min(
        (item for item in feasible if item["a"] == 1), key=lambda item: item["b"]
    )
    endpoint_y_one = min(
        (item for item in feasible if item["b"] == 1), key=lambda item: item["a"]
    )
    if endpoint_q_one["b"] != 14 or endpoint_y_one["a"] != 20:
        raise AssertionError("unexpected one-sided Macaulay floor")

    koszul_diagonal = [
        {"degree": degree, "euler_characteristic": koszul_euler(degree, degree)}
        for degree in range(0, 8)
    ]
    first_nonpositive_total = min(
        a + b
        for a in range(1, 30)
        for b in range(1, 30)
        if koszul_euler(a, b) <= 0
    )
    first_nonpositive_pairs = [
        {
            "a": a,
            "b": first_nonpositive_total - a,
            "euler_characteristic": koszul_euler(a, first_nonpositive_total - a),
        }
        for a in range(1, first_nonpositive_total)
        if koszul_euler(a, first_nonpositive_total - a) <= 0
    ]

    with FULL_BASIS_MANIFEST.open() as handle:
        basis_manifest = json.load(handle)
    with FULL_P3_MANIFEST.open() as handle:
        p3_manifest = json.load(handle)
    basis_hash = sha256(FULL_BASIS)
    p3_hash = sha256(FULL_P3)
    if basis_hash != basis_manifest["full_basis"]["file_sha256"]:
        raise AssertionError("full basis hash mismatch")
    if p3_hash != p3_manifest["file_sha256"]:
        raise AssertionError("full P3 hash mismatch")
    if basis_manifest["coefficient_matrix_rank"] != 14763:
        raise AssertionError("upstream M2-syzygy rank mismatch")
    if basis_manifest["nullity"] != NULLITY:
        raise AssertionError("upstream M2-syzygy nullity mismatch")

    with np.load(P3_MINOR, allow_pickle=False) as frozen:
        minor_columns = frozen["minor_columns"].astype(np.int32)
        recorded_minor_sha = str(frozen["minor_uint8_sha256"])
        recorded_minor_rank = int(frozen["minor_rank"])
        if int(frozen["prime"]) != P:
            raise AssertionError("P3 minor prime mismatch")
        if str(frozen["full_p3_sha256"]) != p3_hash:
            raise AssertionError("P3 minor source hash mismatch")
    if len(minor_columns) != NULLITY or recorded_minor_rank != NULLITY:
        raise AssertionError("P3 minor artifact has wrong size or rank")

    p3 = np.load(FULL_P3, mmap_mode="r")
    if p3.shape != (NULLITY, 6, 9139) or p3.dtype != np.uint8:
        raise AssertionError("unexpected full P3 array")
    minor_uint8 = np.ascontiguousarray(
        p3.reshape(NULLITY, 6 * 9139)[:, minor_columns], dtype=np.uint8
    )
    rebuilt_minor_sha = sha256_array(minor_uint8)
    if rebuilt_minor_sha != recorded_minor_sha:
        raise AssertionError("rebuilt P3 minor hash mismatch")

    observed_free = free_plus_speculative_gib()
    replayed_minor_rank: int | None = None
    if not args.skip_minor_rank:
        if observed_free is not None and observed_free < args.min_free_gib:
            raise SystemExit(
                f"resource guard: free+speculative={observed_free:.2f} GiB "
                f"< required {args.min_free_gib:.2f} GiB"
            )
        dense = minor_uint8.astype(np.float64)
        replayed_minor_rank = fflas_rank(dense)
        del dense
        if replayed_minor_rank != NULLITY:
            raise AssertionError("complete P3 contraction is not injective")

    # A q-linear relation among all 690 polarized equations first lies in the
    # 10767-dimensional kernel of the M2 component.  If it annihilates every
    # polarized B1 column, substituting y_(b,v)=q_v also annihilates M1.  The
    # full-rank P3 minor therefore kills that kernel relation.  Hence there are
    # no q-linear syzygies and mu_(2,1) is injective.
    q_linear_syzygy_dimension = 0 if replayed_minor_rank == NULLITY else None
    r21_target = segre_piece(2, 1)
    r21_source = NROWS * segre_piece(1, 0)
    r21_quotient = (
        r21_target - r21_source if q_linear_syzygy_dimension == 0 else None
    )

    # In standard Segre degree two, the 690 choose 2 elementary Koszul
    # relations are independent, giving a rigorous lower bound on the quotient.
    standard_degree2_target = segre_piece(2, 2)
    standard_degree2_source = NROWS * segre_piece(1, 1)
    elementary_koszul = math.comb(NROWS, 2)
    standard_degree2_quotient_lower_bound = (
        standard_degree2_target - standard_degree2_source + elementary_koszul
    )

    result = {
        "status": "PASS_POLARIZED_SEGRE_LOW_DEGREE_NONVERDICT",
        "prime": P,
        "geometry": {
            "q_projective_dimension": 36,
            "y_projective_dimension": 242,
            "segre_projective_dimension": 278,
            "ambient_projective_dimension": NQ * NY - 1,
            "equation_rank": equation_rank,
            "linear_kernel_vector_dimension": kernel_dimension,
            "linear_kernel_projective_dimension": kernel_dimension - 1,
            "expected_intersection_dimension": 278 + (kernel_dimension - 1) - (NQ * NY - 1),
            "equations_beyond_expected_empty_threshold": NROWS - 279,
            "maximal_possible_decomposable_free_vector_dimension": (NQ - 1) * (NY - 1),
            "segre_degree": math.comb(278, 36),
            "scope": "Expected dimension and the maximal-space bound are not an actual emptiness proof.",
        },
        "polarized_map": {
            "shape": [NROWS, NY],
            "coefficient_tensor_shape": list(coefficient.shape),
            "coefficient_nnz": coefficient_nnz,
            "coefficient_density": coefficient_nnz / coefficient.size,
            "row_nnz_min": int(row_nnz.min()),
            "row_nnz_max": int(row_nnz.max()),
            "row_nnz_mean": float(row_nnz.mean()),
            "m2_systematic_unit_columns": int(len(unit_columns)),
            "m2_systematic_free_columns": int(21 * NQ - len(unit_columns)),
            "polarization_identity_checked": True,
            "safe_implication": "Empty polarized Segre kernel implies Stage B empty.",
            "converse": False,
        },
        "macaulay": {
            "piece_formula": "dim R_(a,b)=C(a+36,36)*C(b+242,242)",
            "source_formula": "690*dim R_(a-1,b-1)",
            "necessary_surjectivity_inequality": "690*a*b >= (a+36)*(b+242)",
            "first_total_degree": min_total,
            "first_total_degree_pairs": first_total,
            "diagonal_first_dimensionally_possible": diagonal_first,
            "q_degree_one_endpoint": endpoint_q_one,
            "y_degree_one_endpoint": endpoint_y_one,
            "smallest_target_dimensionally_possible": smallest_target,
            "certificate_rule": "Surjectivity at one positive bidegree proves the projective Segre section empty.",
            "resource_verdict": "No full dimensionally admissible Macaulay matrix is remotely materializable.",
        },
        "koszul_euler_preflight": {
            "formula": "coefficient of H_R(s,t)*(1-s*t)^690",
            "diagonal_degrees_0_through_7": koszul_diagonal,
            "first_nonpositive_total_degree": first_nonpositive_total,
            "first_nonpositive_pairs": first_nonpositive_pairs,
            "warning": "These are exact Euler characteristics, not Hilbert values or rank certificates when Koszul homology is unknown.",
        },
        "bounded_exact_low_degree": {
            "full_m2_syzygy_rank": basis_manifest["coefficient_matrix_rank"],
            "full_m2_syzygy_nullity": basis_manifest["nullity"],
            "full_basis_sha256": basis_hash,
            "full_p3_sha256": p3_hash,
            "p3_minor_shape": [NULLITY, NULLITY],
            "p3_minor_uint8_sha256": rebuilt_minor_sha,
            "p3_minor_rank_replayed": replayed_minor_rank,
            "q_linear_syzygy_dimension": q_linear_syzygy_dimension,
            "bidegree_2_1_source_dimension": r21_source,
            "bidegree_2_1_target_dimension": r21_target,
            "bidegree_2_1_quotient_dimension": r21_quotient,
            "standard_degree_2_target_dimension": standard_degree2_target,
            "standard_degree_2_source_dimension": standard_degree2_source,
            "standard_degree_2_elementary_koszul_relations": elementary_koszul,
            "standard_degree_2_quotient_lower_bound": standard_degree2_quotient_lower_bound,
            "observed_free_plus_speculative_gib": observed_free,
        },
        "input_hashes": {
            str(RELATION.relative_to(ROOT)): sha256(RELATION),
            str(FULL_BASIS.relative_to(P25)): basis_hash,
            str(FULL_P3.relative_to(P25)): p3_hash,
            str(P3_MINOR.relative_to(P25)): sha256(P3_MINOR),
        },
        "theorem_boundary": {
            "proved": [
                "the 690 bilinear equations are linearly independent",
                "the exact raw multigraded Macaulay dimension floors",
                "the complete polarized equation system has no q-linear syzygy",
                "the exact bidegree-(2,1) quotient dimension 145299",
                "the standard degree-two quotient has dimension at least 14875053",
            ],
            "not_proved": [
                "surjectivity at any positive bidegree",
                "absence of a decomposable tensor in the 8301-dimensional kernel",
                "global injectivity of L(q)",
                "Stage-B emptiness or a true Stage-B point",
            ],
        },
    }
    OUTPUT.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print("PASS_POLARIZED_SEGRE_LOW_DEGREE_NONVERDICT")
    print(f"P3 minor rank: {replayed_minor_rank}/{NULLITY}")
    print(f"first raw Macaulay total degree: {min_total}")
    print(
        "smallest admissible target: "
        f"({smallest_target['a']},{smallest_target['b']}) "
        f"with {smallest_target['target_dimension']} rows"
    )


if __name__ == "__main__":
    main()
