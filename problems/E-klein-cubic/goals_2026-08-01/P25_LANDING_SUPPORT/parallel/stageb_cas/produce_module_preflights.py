#!/usr/bin/env python3
"""Produce exact Stage-B cokernel-module preflights.

For the contracted boundary equations, let A(q) be the r x 6 matrix whose
entries are the stored cubic forms P3.  Stage B for this subsystem is the
projective rank-drop locus rank(A(q)) < 6.  If N is the submodule of S^6
generated by the rows of A, then this locus is Proj Supp(S^6/N).  Thus

    dim(S^6/N) == 0

for the homogeneous module, or N=S^6 after setting q_chart=1, is an exact
emptiness certificate.  This removes all six b variables and the b-irrelevant
saturation; no determinant is expanded.

Only upstream sealed arrays are read.  Generated CAS inputs remain in this
isolated audit directory.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np


HERE = Path(__file__).resolve().parent
P25 = HERE.parents[1]
P = 89
NQ = 37


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while block := handle.read(2**20):
            digest.update(block)
    return digest.hexdigest()


def weak_compositions(total: int, parts: int) -> list[tuple[int, ...]]:
    if parts == 1:
        return [(total,)]
    out: list[tuple[int, ...]] = []
    for first in range(total + 1):
        for tail in weak_compositions(total - first, parts - 1):
            out.append((first,) + tail)
    return out


def polynomial_string(
    coefficients: np.ndarray,
    monomials: list[tuple[int, ...]],
    q_chart: int | None,
) -> str:
    terms: list[str] = []
    for raw, exponent in zip(coefficients, monomials):
        coefficient = int(raw) % P
        if coefficient == 0:
            continue
        factors: list[str] = []
        for variable, power in enumerate(exponent):
            if variable == q_chart or power == 0:
                continue
            name = f"q{variable}"
            factors.append(name if power == 1 else f"{name}^{power}")
        monomial = "*".join(factors) if factors else "1"
        terms.append(monomial if coefficient == 1 else f"{coefficient}*{monomial}")
    return "+".join(terms) if terms else "0"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rows", type=int, choices=(12, 24, 43, 48, 96, 256), default=43)
    parser.add_argument("--q-chart", type=int, choices=range(NQ))
    parser.add_argument("--module-order", choices=("C", "c"), default="C")
    args = parser.parse_args()

    source_rows = 48 if args.rows in (12, 24, 43) else args.rows
    source = P25 / f"syzygy_r{source_rows}_q0_contracted.npz"
    with np.load(source) as frozen:
        p3 = frozen["p3"].astype(np.uint8)[: args.rows]
        if int(frozen["prime"]) != P:
            raise RuntimeError("wrong prime")
    if p3.shape != (args.rows, 6, 9139):
        raise RuntimeError(f"unexpected P3 shape {p3.shape}")

    monomials = weak_compositions(3, NQ)
    variables = [f"q{i}" for i in range(NQ) if i != args.q_chart]
    chart_tag = "hom" if args.q_chart is None else f"q{args.q_chart}_1"
    # macOS's default filesystem is case-insensitive, so do not use C/c as a
    # filename discriminator even though Singular uses those exact tokens.
    order_tag = "ordC" if args.module_order == "C" else "ordc_lower"
    stem = f"module_r{args.rows}_{chart_tag}_{order_tag}"
    script = HERE / f"{stem}.sing"
    result = HERE / f"{stem}_result.txt"
    polys = [
        [polynomial_string(p3[row, component], monomials, args.q_chart) for component in range(6)]
        for row in range(args.rows)
    ]
    with script.open("w") as handle:
        handle.write(f"ring R={P},({','.join(variables)}),(dp,{args.module_order});\n")
        handle.write("option(prot);\n")
        handle.write("module N=\n")
        for row, entries in enumerate(polys):
            handle.write("[" + ",".join(entries) + "]")
            handle.write(",\n" if row + 1 < args.rows else ";\n")
        handle.write('print("input module gens="+string(size(N)));\n')
        handle.write("timer=1; module G=std(N); int elapsed=timer;\n")
        if args.q_chart is None:
            handle.write("int decisive=(dim(G)==0);\n")
            handle.write('print("std gens="+string(size(G))+" dim="+string(dim(G))+" elapsed_ms="+string(elapsed));\n')
        else:
            handle.write("int decisive=1; int j; for (j=1;j<=6;j++){ if (reduce(gen(j),G)!=0) { decisive=0; } }\n")
            handle.write('print("std gens="+string(size(G))+" full_module="+string(decisive)+" elapsed_ms="+string(elapsed));\n')
        handle.write(f'write(":w {result}","decisive="+string(decisive)+",std_gens="+string(size(G))+",elapsed_ms="+string(elapsed));\n')
        handle.write("quit;\n")

    metadata = {
        "prime": P,
        "rows": args.rows,
        "q_chart": args.q_chart,
        "module_order": args.module_order,
        "source": str(source),
        "source_sha256": sha256(source),
        "script": script.name,
        "script_sha256": sha256(script),
        "script_bytes": script.stat().st_size,
        "result": result.name,
        "criterion": (
            "homogeneous dim(S^6/N)=0" if args.q_chart is None else "after q_chart=1, N=S^6"
        ),
        "logical_scope": (
            "A decisive result proves emptiness for the retained contracted subsystem, "
            "hence for Stage B. Incomplete or nondecisive output proves nothing."
        ),
    }
    metadata_path = HERE / f"{stem}.json"
    metadata_path.write_text(json.dumps(metadata, indent=2, sort_keys=True) + "\n")
    print(json.dumps(metadata, sort_keys=True), flush=True)


if __name__ == "__main__":
    main()
