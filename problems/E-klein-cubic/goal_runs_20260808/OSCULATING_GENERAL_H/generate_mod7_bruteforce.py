#!/usr/bin/env python3
"""Generate a bounded parallel prime-field search for the normalized slice.

The search universe is exactly F_p^10 for one fixed rational-root
specialization.  It is a finite existence probe, not an emptiness certificate
over the generic characteristic-zero field.  The default is p=7; p=11 is the
independent-prime replay.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import sympy as sp

from probe_normalized_slice import build_system


ROOTS = (1, 2, 3, 4, "1/24")


def mod_coefficient(coefficient, prime):
    return (
        int(coefficient.p)
        * pow(int(coefficient.q) % prime, -1, prime)
    ) % prime


def render_monomial(monomial):
    factors = []
    for index, exponent in enumerate(monomial):
        if exponent == 1:
            factors.append(f"x[{index}]")
        elif exponent == 2:
            factors.append(f"x[{index}]*x[{index}]")
        elif exponent == 3:
            factors.append(f"x[{index}]*x[{index}]*x[{index}]")
        elif exponent:
            raise ValueError(exponent)
    return "*".join(factors) if factors else "1"


def render_polynomial(poly, prime):
    terms = []
    for monomial, coefficient in poly.terms():
        value = mod_coefficient(coefficient, prime)
        if value:
            terms.append(f"{value}LL*{render_monomial(monomial)}")
    return " + ".join(terms) if terms else "0"


def source(A_values, f_values, prime=7):
    variables, equations, _, H, *_ = build_system(
        ROOTS, A_values=A_values, f_values=f_values
    )
    assert len(variables) == len(equations) == 10
    rendered = [render_polynomial(poly, prime) for poly in equations]
    T = sp.Symbol("T")
    leading = [
        render_polynomial(sp.Poly(
            sp.Poly(poly, T).coeff_monomial(T**4),
            *variables,
            domain=sp.QQ,
        ), prime)
        for poly in H
    ]
    tests_leading = "\n".join(
        f"    if (({polynomial}) % P == 0) continue;"
        for polynomial in leading
    )
    tests_j3 = "\n".join(
        f"    if (({rendered[2 * k]}) % P != 0) continue;"
        for k in range(5)
    )
    tests_j4 = "\n".join(
        f"    if (({rendered[2 * k + 1]}) % P != 0) continue;"
        for k in range(5)
    )
    return f'''// Generated by generate_mod7_bruteforce.py.
#include <atomic>
#include <cstdint>
#include <iostream>
#include <mutex>
#include <thread>
#include <vector>

static constexpr long long P = {prime};
static constexpr std::uint64_t TOTAL = {prime ** 10}ULL; // p^10
static constexpr int MAX_POINTS = 50;
static std::atomic<int> found(0);
static std::mutex output_mutex;

void worker(std::uint64_t begin, std::uint64_t end) {{
  long long x[10];
  for (std::uint64_t code = begin; code < end && found.load() < MAX_POINTS; ++code) {{
    std::uint64_t q = code;
    for (int j = 0; j < 10; ++j) {{ x[j] = q % P; q /= P; }}
{tests_leading}
{tests_j3}
{tests_j4}
    int number = found.fetch_add(1);
    if (number < MAX_POINTS) {{
      std::lock_guard<std::mutex> lock(output_mutex);
      std::cout << "FOUND";
      for (int j = 0; j < 10; ++j) std::cout << " " << x[j];
      std::cout << "\\n";
    }}
    return;
  }}
}}

int main() {{
  unsigned n = std::thread::hardware_concurrency();
  if (n == 0) n = 4;
  std::vector<std::thread> threads;
  for (unsigned j = 0; j < n; ++j) {{
    std::uint64_t lo = TOTAL * j / n;
    std::uint64_t hi = TOTAL * (j + 1) / n;
    threads.emplace_back(worker, lo, hi);
  }}
  for (auto &thread : threads) thread.join();
  if (!found.load()) std::cout << "NO_FP_POINT p=" << P << "\\n";
  else std::cout << "POINTS " << found.load() << "\\n";
}}
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    parser.add_argument("--A", default="1,1,1,1,1")
    parser.add_argument("--f", default="1,1,1,1,1")
    parser.add_argument("--prime", type=int, default=7)
    args = parser.parse_args()
    A_values = tuple(map(int, args.A.split(",")))
    f_values = tuple(map(int, args.f.split(",")))
    if len(A_values) != 5 or len(f_values) != 5:
        parser.error("--A and --f must each have five comma-separated entries")
    args.output.write_text(source(A_values, f_values, args.prime))
    print(args.output)


if __name__ == "__main__":
    main()
