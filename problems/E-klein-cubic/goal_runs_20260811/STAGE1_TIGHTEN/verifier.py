"""STAGE1_TIGHTEN -- verifier.

Replays, at p = 331 and p = 661:
  * the saturation apparatus and the threshold Theta = 6 (Task 2);
  * the identification of the two full-flag rows and the residue-indexed
    sigma-band count (Task 1);
  * the arithmetic that carries STAGE2's odd-order collapse into it.

    python3 verifier.py            # both primes
    python3 verifier.py 331        # one prime
"""
import itertools
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "scripts"))

from s1enum import Stage1                                     # noqa: E402
from s1window import exact_window                             # noqa: E402
from s1recount import build_tables, coherent_count            # noqa: E402
from s3sweep import FullSweep                                 # noqa: E402
from s3sat import classes, contribution, minimal_realized     # noqa: E402
from s3residue import degree_tables, full_flag_rows, d10_split  # noqa: E402
from s1coherence import linear_characters                     # noqa: E402

FAILS, CHECKS = [], []
IMM1 = 6 ** 8 * 4 ** 10 * 5 ** 4
IMM2 = 3 ** 8
CORE = {0: 10752, 2: 672, 4: 672}


def check(name, cond, detail=""):
    CHECKS.append((name, bool(cond), detail))
    print("CHECK %-64s : %s%s" % (name, "PASS" if cond else "FAIL",
                                  ("  " + str(detail)) if detail else ""), flush=True)
    if not cond:
        FAILS.append(name)


def run(p):
    print("\n===== p = %d =====" % p, flush=True)
    E = Stage1(p, verbose=False)
    sw = [r["id"] for r in E.rows
          if any(v[0] == "dom" and v[1] == "L" for v in E.dom[r["id"]])]
    check("A1 15 sweep-capable rows, 80-row census, 145 relations (p=%d)" % p,
          len(sw) == 15 and len(E.rows) == 80 and len(E.orbit_relations) == 145)

    # ---------------- B. saturation (Task 2) -----------------------------
    gmax, thr, upok, nfull = 0, 0, True, []
    for rid in sw:
        S = FullSweep(E, rid)
        if sum(S.dims) == 5:
            nfull.append(rid)
        for i in range(S.nslot):
            g = S.invariant_degree(i)
            check_g = (g is not None and 6 % g == 0)
            if not check_g:
                upok = False
            gmax = max(gmax, g or 99)
        box = 17 if S.nslot <= 2 else 11
        for _nm, psi in linear_characters(E.m, S.Gam):
            mins, R, ok = minimal_realized(S, box=box, psi=psi)
            if not ok:
                upok = False
            if mins:
                thr = max(thr, max(max(a) for a in mins))
    check("B1 every slot of every sweep row carries a Gamma-invariant form of "
          "degree dividing 6, non-vanishing at all children (p=%d)" % p,
          gmax <= 6 and upok, "max g_r = %d" % gmax)
    check("B2 the realized set is exactly the up-set generated by its minimal "
          "elements under the steps 6.e_r, for every character (p=%d)" % p, upok)
    check("B3 SATURATION THRESHOLD Theta = 6: every minimal realized multidegree "
          "has all coordinates <= 6 (p=%d)" % p, thr == 6, thr)
    # the image really is stable past the threshold, on one representative row
    S1 = FullSweep(E, 1)
    im = {}
    for B in (6, 8):
        acc = set()
        for a in itertools.product(range(B + 1), repeat=S1.nslot):
            if sum(a) == 0 or not S1.module_dim(a):
                continue
            c = contribution(S1, a, E)
            if c is None:
                continue
            acc.add(tuple(sorted(c.items())))
        im[B] = acc
    check("B4 the image of D_{P_sigma} at box 6 equals the image at box 8 (p=%d)" % p,
          im[6] == im[8], (len(im[6]), len(im[8])))

    # ---------------- C. the character rule, psi = trivial ---------------
    tested = bad = 0
    for rid in (8, 9, 11, 5, 4, 1):
        S = FullSweep(E, rid)
        md = 3 if max(S.dims) > 2 else 4
        for a in itertools.product(range(md + 1), repeat=S.nslot):
            if sum(a) == 0:
                continue
            nV, ev = S.explicit(a)
            if nV != S.module_dim(a) % p:
                bad += 1
            for kid in S.kids:
                rk, w = ev[kid["idx"]]
                tested += 1
                if rk == 2:
                    bad += 1
                elif rk == 1:
                    U = E.m.canon([list(tuple(sum(w[i] * S.Wm[i][c] for i in range(2))
                                              % p for c in range(5)))])
                    if S.value(a, kid) != U:
                        bad += 1
    check("C1 character rule = explicit evaluation, and trace formula = nullspace "
          "dimension, for psi = trivial (p=%d)" % p, bad == 0,
          "%d cases, %d failures" % (tested, bad))
    ex = exact_window(E.m, S1.sig, dmax=14)
    ok = all(S1.module_dim((d - mm, mm)) % p == ex[(d, mm)][0] % p
             for d in range(1, 13) for mm in range(d + 1))
    check("C2 the D_{P_sigma} module is the sealed STAGE1 Layer-3 module: "
          "dim V((d-m,m),1) = N(d,m) (p=%d)" % p, ok)

    # ---------------- D. full flags and the degree entry ------------------
    ff = full_flag_rows(E)
    check("D1 exactly two rows have slot dimensions summing to 5 -- the two dim-3 "
          "divisors; psi = 1 is forced only there (p=%d)" % p,
          sorted(ff) == sorted(nfull) and len(ff) == 2 and
          all([q for q in E.rows if q["id"] == i][0]["dim"] == 3 for i in ff), ff)
    S2 = FullSweep(E, ff[1])
    par1 = all(tuple(x % 6 for x in a)[1] % 2 == 1
               for a in itertools.product(range(7), repeat=2) if S1.module_dim(a))
    par2 = all(tuple(x % 6 for x in a)[0] % 2 == 1
               for a in itertools.product(range(7), repeat=2) if S2.module_dim(a))
    check("D2 psi = 1 reproduces the sealed jet parities: m odd on D_{P_sigma} "
          "(H0-1) and ord_{L_sigma}(T) = d+1 mod 2 on D_{L^-_sigma} (STAGE2 "
          "Prop 1.4(ii)) (p=%d)" % p, par1 and par2)
    deg = degree_tables(E)
    check("D3 each full-flag row offers 3 usable component classes per residue "
          "d mod 6 (p=%d)" % p,
          all(len(v.get(e, [])) == 3 for v in deg.values() for e in range(6)))

    # ---------------- E. the residue-indexed count ------------------------
    base, _meta = build_tables(E)
    res = {}
    for e in range(6):
        t = dict(base)
        for rid, per in deg.items():
            t[rid] = per.get(e, [])
        tot, _b = coherent_count(E, t)
        res[e] = tot
    check("E1 the sigma-band factor is 10752 for d = 0 (mod 6) and 672 for "
          "d = 2, 4 (mod 6) (p=%d)" % p,
          all(res[e] // (23 * IMM1) == CORE[e] for e in (0, 2, 4)),
          {e: res[e] // (23 * IMM1) for e in (0, 2, 4)})
    check("E2 the even residues give totals 272211848944680960000 (d=0) and "
          "17013240559042560000 (d=2,4) (p=%d)" % p,
          res[0] == 272211848944680960000 and res[2] == res[4] == 17013240559042560000)
    check("E3 FLAGGED, NOT CLAIMED: the odd residues return 0 -- recorded and "
          "reproduced, not asserted (p=%d)" % p,
          res[1] == res[3] == res[5] == 0, {e: res[e] for e in (1, 3, 5)})
    check("E4 each degree constraint ALONE is consistent at every residue "
          "(so the odd-d zero is a joint effect) (p=%d)" % p,
          all(coherent_count(E, {**base, rid: deg[rid][e]})[0] > 0
              for rid in deg for e in range(6)))

    # ---------------- F. the D10 row --------------------------------------
    rid16, onE, onL = d10_split(E)
    check("F1 the D10 C2-line's 23 values split 13 (on E_sigma) + 10 (on L_sigma) "
          "by the tau-weight of the value (p=%d)" % p,
          len(onE) == 13 and len(onL) == 10, (len(onE), len(onL)))

    # ---------------- G. carrying STAGE2 in ------------------------------
    check("G1 STAGE2 immune collapse 6^8.4^10.5^4 -> 3^8 is a factor "
          "2^28 . 5^4 = 167772160000", IMM1 // IMM2 == 2 ** 28 * 5 ** 4)
    check("G2 STAGE1 x STAGE2 (degree-blind) = 43008 . 23 . 3^8 = 6490036224",
          43008 * 23 * IMM2 == 6490036224)
    check("G3 tightened totals: 917070336 (d=0 mod 6) and 57316896 (d=2,4 mod 6) "
          "on the E-branch of the D10 row",
          CORE[0] * 13 * IMM2 == 917070336 and CORE[2] * 13 * IMM2 == 57316896)
    check("G4 L-branch variants 705438720 and 44089920",
          CORE[0] * 10 * IMM2 == 705438720 and CORE[2] * 10 * IMM2 == 44089920)
    return E, res


def main():
    ps = [int(x) for x in sys.argv[1:]] or [331, 661]
    outs = [run(p) for p in ps]
    if len(outs) == 2:
        check("H1 the two primes give identical residue tables",
              outs[0][1] == outs[1][1])
    print("\n%d checks, %d failures" % (len(CHECKS), len(FAILS)))
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    with open(os.path.join(HERE, "results", "verifier_stdout.txt"), "w") as f:
        for n, c, d in CHECKS:
            f.write("CHECK %-64s : %s  %s\n" % (n, "PASS" if c else "FAIL", d))
        f.write("\n%d checks, %d failures\n" % (len(CHECKS), len(FAILS)))
        if not FAILS:
            f.write("STAGE1_TIGHTEN_VERIFY_OK\nALLGREEN\n")
    if FAILS:
        print("FAILURES:", FAILS)
        sys.exit(1)
    print("STAGE1_TIGHTEN_VERIFY_OK")
    print("ALLGREEN")


if __name__ == "__main__":
    main()
