def mmul(A, B, p):
    Bt = list(zip(*B))
    return tuple(tuple(sum(x * y for x, y in zip(row, col)) % p for col in Bt) for row in A)


def matvec(A, v, p):
    return tuple(sum(x * y for x, y in zip(row, v)) % p for row in A)


def eye(n):
    return tuple(tuple(1 if i == j else 0 for j in range(n)) for i in range(n))


def rref(rows, p):
    A = [[x % p for x in r] for r in rows]
    if not A:
        return [], []
    r, piv, ncol = 0, [], len(A[0])
    for c in range(ncol):
        q = next((i for i in range(r, len(A)) if A[i][c]), None)
        if q is None:
            continue
        A[r], A[q] = A[q], A[r]
        iv = pow(A[r][c], p - 2, p)
        A[r] = [(x * iv) % p for x in A[r]]
        for i in range(len(A)):
            if i != r and A[i][c]:
                t = A[i][c]
                A[i] = [(x - t * y) % p for x, y in zip(A[i], A[r])]
        piv.append(c)
        r += 1
        if r == len(A):
            break
    return [tuple(x) for x in A[:r]], piv


def kernel(rows, nvar, p):
    R, piv = rref(rows, p)
    free = [j for j in range(nvar) if j not in piv]
    out = []
    for f in free:
        v = [0] * nvar
        v[f] = 1
        for row, pc in zip(R, piv):
            v[pc] = (-row[f]) % p
        out.append(tuple(v))
    return out


def rank(rows, p):
    return len(rref(rows, p)[0])


def inv_matrix(A, p):
    n = len(A)
    Mx = [list(r) + [1 if i == j else 0 for j in range(n)] for i, r in enumerate(A)]
    R, piv = rref(Mx, p)
    assert piv == list(range(n)), "matrix not invertible"
    return tuple(tuple(row[n:]) for row in R)


class Echelon:
    """incremental row echelon form; add() returns True when independent."""

    def __init__(self, p):
        self.p, self.piv, self.rows = p, [], []

    def add(self, v):
        p = self.p
        w = [x % p for x in v]
        for c, r in zip(self.piv, self.rows):
            if w[c]:
                t = w[c]
                for i in range(len(w)):
                    if r[i]:
                        w[i] = (w[i] - t * r[i]) % p
        c = next((i for i, x in enumerate(w) if x), None)
        if c is None:
            return False
        iv = pow(w[c], p - 2, p)
        self.piv.append(c)
        self.rows.append([x * iv % p for x in w])
        return True

    @property
    def rank(self):
        return len(self.rows)


def lam2(Mx, p):
    return tuple(tuple((Mx[i][k] * Mx[j][l] - Mx[i][l] * Mx[j][k]) % p for (k, l) in PAIRS)
                 for (i, j) in PAIRS)


def det4(sub, p):
    s = 0
    for pi, sg in zip(PERMS4, SGN4):
        t = 1
        for i in range(4):
            t = t * sub[i][pi[i]]
        s += sg * t
    return s % p


def lam4(Mx, p):
    return tuple(tuple(det4([[Mx[K[i]][L[j]] for j in range(4)] for i in range(4)], p)
                       for L in QUADS) for K in QUADS)


