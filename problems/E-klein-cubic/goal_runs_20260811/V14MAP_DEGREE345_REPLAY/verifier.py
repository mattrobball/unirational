def wedge_of(u, v, p):
    return tuple((u[i] * v[j] - u[j] * v[i]) % p for (i, j) in PAIRS)


def wedge_square(om, p):
    q = [0] * 15
    for i in range(15):
        if not om[i]:
            continue
        for j in range(15):
            if om[j] and (i, j) in WEDGE:
                K, sg = WEDGE[(i, j)]
                q[K] = (q[K] + sg * om[i] * om[j]) % p
    return tuple(q)


def v14_points(mod, want, seed=20260811):
    """F_p-points of V14 = Gr(2,U) cap P(M) -- the parent packet's kernel-jump
    generator.  For u in U the map v -> u ^ v followed by the five linear
    conditions D that cut M out of Lambda^2 U gives a 5 x 6 matrix N(u) whose
    kernel always contains u; where the kernel jumps to dimension 2, any v in
    it independent of u gives a decomposable bivector u ^ v lying in M."""
    p, D, piv = mod['p'], mod['D'], mod['piv']
    rng = random.Random(seed)

    def Nmat(u):
        cols = []
        for j in range(6):
            w = [0] * 15
            for k in range(6):
                if k == j or not u[k] % p:
                    continue
                if k < j:
                    w[PIDX[(k, j)]] = u[k] % p
                else:
                    w[PIDX[(j, k)]] = (-u[k]) % p
            cols.append(w)
        return [[sum(D[i][a] * cols[j][a] for a in range(15)) % p for j in range(6)]
                for i in range(len(D))]

    out, raw, seen, tries = [], [], set(), 0
    while len(out) < want and tries < 100000:
        tries += 1
        u0 = [rng.randrange(p) for _ in range(6)]
        u1 = [rng.randrange(p) for _ in range(6)]
        N0, N1 = Nmat(u0), Nmat(u1)
        for t in range(p):
            N = [[(N0[i][j] + t * N1[i][j]) % p for j in range(6)] for i in range(len(D))]
            ker = kernel(N, 6, p)
            if len(ker) < 2:
                continue
            u = [(u0[j] + t * u1[j]) % p for j in range(6)]
            for v in ker:
                om = wedge_of(u, v, p)
                if any(om):
                    k0 = next(i for i in range(15) if om[i])
                    iv = pow(om[k0], p - 2, p)
                    key = tuple(x * iv % p for x in om)
                    if key in seen:
                        continue
                    seen.add(key)
                    raw.append(om)
                    out.append(tuple(om[j] for j in piv))
                    break
            if len(out) >= want:
                break
    return out, raw


