def run_prime(p, npts):
    tag = str(p)
    print("--- prime %d ---" % p)
    mod = build_model(p)
    if not check_model(mod, tag):
        return False
    pts, raw = v14_points(mod, npts)
    ok = check_v14(mod, tag, pts, raw)
    okk, nA, nAd = check_koszul(mod, tag)
    ok &= okk
    okc, CA, CAd = check_invcubic(mod, tag)
    ok &= okc
    ok &= check_m2(mod, tag)
    for d in (2, 3, 4, 5):
        for dual in (False, True):
            good, r = check_degree(mod, tag, d, dual, pts,
                                   CAd if dual else CA,
                                   (nAd if dual else nA)[d])
            ok &= good
    return ok


