def _sym_from_psums(pk, d):
    h = [Fraction(1)]
    for n in range(1, d + 1):
        s = Fraction(0)
        for k in range(1, n + 1):
            s += Fraction(pk[k]) * h[n - k]
        h.append(s / n)
    assert h[d].denominator == 1
    return int(h[d])


def sym_char_M(n, d):
    """chi_{Sym^d M}(g) for g of projective order n, exactly."""
    if d == 0:
        return 1
    from math import gcd
    pk = {k: CHI10P[n // gcd(n, k)] for k in range(1, d + 1)}
    return _sym_from_psums(pk, d)


def mult_slot(d):
    """dim Hom_G(Sym^d(M*), S), S either 5-dim slot -- exactly, and equal for both."""
    tot = Fraction(0)
    for n, size in ORD_SIZE.items():
        h = sym_char_M(n, d)
        tot += Fraction(h * CHI_A_11_WEIGHT) if n == 11 else Fraction(size * h * CHI_A_RAT[n])
    tot /= 660
    assert tot.denominator == 1
    return int(tot)


def mult_trivial(d):
    tot = Fraction(0)
    for n, size in ORD_SIZE.items():
        tot += Fraction(size * sym_char_M(n, d))
    tot /= 660
    assert tot.denominator == 1
    return int(tot)


