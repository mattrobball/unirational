RES = paths.RES
K = L.DIM37  # 37


def nmon(d, n=K):
    r = 1
    for i in range(d):
        r = r * (n + i) // (i + 1)
    return r


def mon_list(d, n=K):
    return list(itertools.combinations_with_replacement(range(n), d))


def inv(a, p):
    return pow(int(a) % p, p - 2, p)


# ---------------------------------------------------------------------------
class Echelon:
    """Row-echelon basis over F_p; store dense basis rows."""

    def __init__(self, ncols, p):
        self.p = int(p)
        self.ncols = ncols
        self.basis = np.zeros((0, ncols), dtype=np.int64)
        self.pivots = []

    @property
    def rank(self):
        return len(self.pivots)

    def reduce(self, v):
        p = self.p
        v = np.array(v, dtype=np.int64, copy=True) % p
        for i, piv in enumerate(self.pivots):
            if v[piv]:
                v -= int(v[piv]) * self.basis[i]
                v %= p
        return v

    def try_add(self, v, store_orig=None, origs=None):
        p = self.p
        v = self.reduce(v)
        nz = np.nonzero(v)[0]
        if not nz.size:
            return False
        piv = int(nz[0])
        v = (v * inv(int(v[piv]), p)) % p
        if self.basis.shape[0]:
            col = self.basis[:, piv].copy()
            nz2 = np.nonzero(col)[0]
            if nz2.size:
                self.basis[nz2] = (self.basis[nz2] - np.outer(col[nz2], v)) % p
        self.basis = (
            np.vstack([self.basis, v]) if self.basis.shape[0] else v.reshape(1, -1)
        )
        self.pivots.append(piv)
        if store_orig is not None and origs is not None:
            origs.append(np.asarray(store_orig, dtype=np.int64) % p)
        return True

    def try_add_batch(self, rows, report_every=0):
        """Add many rows; return number added."""
        added = 0
        for i, r in enumerate(rows):
            if self.try_add(r):
                added += 1
            if report_every and (i + 1) % report_every == 0:
                print("    batch row %d/%d rank=%d" % (
                    i + 1, len(rows), self.rank), flush=True)
        return added


