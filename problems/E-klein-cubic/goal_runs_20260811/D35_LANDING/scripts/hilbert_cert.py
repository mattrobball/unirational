"""Hilbert function of the landing ideal I on the 37-cell (pure linear algebra).

I is generated by cubics F(T_c(x)). Graded pieces:
  I_3 = span of sampled cubic rows in Sym^3 (dim N3 = binom(39,3) = 9139)
  I_{k+1} = span{ x_i * f : f in I_k, i = 0..36 }

HF(d) = N_d - dim I_d.  HF(d) = 0 certifies V(I) = {0} over F_p-bar
(EMPTY by linear algebra; Tier-2 modular). Never runs monolithic msolve.
"""
from __future__ import annotations

