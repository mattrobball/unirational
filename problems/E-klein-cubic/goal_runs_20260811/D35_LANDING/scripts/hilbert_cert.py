def load_or_sample_I3(p, max_pts=12000, stable_window=500, seed=20260811,
                     resume_path=None, extra_batches=2, extra_size=400):
    cell = L.load_cell(p)
    fr = SL.build_frame(p, verbose=True)
    N3 = nmon(3)
    assert N3 == 9139
    ech = Echelon(N3, p)
    indep_orig = []
    curve = []
    t0 = time.time()
    n_tested = 0
    stable = 0
    rng = np.random.default_rng(seed + p)

    if resume_path and os.path.exists(resume_path):
        rows = np.load(resume_path)
        print("[I3] seeding from %s shape=%s" % (resume_path, rows.shape), flush=True)
        for i, r in enumerate(rows):
            ech.try_add(r, store_orig=r, origs=indep_orig)
            n_tested += 1
            if (i + 1) % 100 == 0:
                print("  seed n=%d rank=%d (%.1fs)" % (
                    i + 1, ech.rank, time.time() - t0), flush=True)
        curve.append({"n": n_tested, "rank": ech.rank, "phase": "seed",
                      "t": time.time() - t0})
        print("[I3] after seed: rank=%d" % ech.rank, flush=True)

    print("[I3] saturating p=%d max=%d stable_win=%d" % (
        p, max_pts, stable_window), flush=True)
    while n_tested < max_pts and stable < stable_window:
        b = 16
        pts = rng.integers(0, p, size=(b, 5), dtype=np.int64)
        for i in range(b):
            if not pts[i].any():
                pts[i, 0] = 1
        Mall = L.eval_cell_at_points(fr, cell, pts)
        for q in range(b):
            if n_tested >= max_pts or stable >= stable_window:
                break
            row, _ = L.cubic_coeff_row(Mall[q], p)
            n_tested += 1
            if ech.try_add(row, store_orig=row, origs=indep_orig):
                stable = 0
            else:
                stable += 1
            if n_tested % 100 == 0:
                curve.append({"n": n_tested, "rank": ech.rank, "stable": stable,
                              "t": time.time() - t0, "phase": "main"})
                print("  n=%d rank=%d stable=%d HF3=%d (%.1fs)" % (
                    n_tested, ech.rank, stable, N3 - ech.rank,
                    time.time() - t0), flush=True)

    extra_ranks = []
    for bi in range(extra_batches):
        brng = np.random.default_rng(seed + p + 1000 * (bi + 1) + 7)
        before = ech.rank
        added = 0
        for _ in range(extra_size):
            pt = brng.integers(0, p, size=(1, 5), dtype=np.int64)
            if not pt[0].any():
                pt[0, 0] = 1
            Mall = L.eval_cell_at_points(fr, cell, pt)
            row, _ = L.cubic_coeff_row(Mall[0], p)
            n_tested += 1
            if ech.try_add(row, store_orig=row, origs=indep_orig):
                added += 1
        extra_ranks.append({
            "batch": bi, "seed": seed + p + 1000 * (bi + 1) + 7,
            "size": extra_size, "rank_before": before,
            "rank_after": ech.rank, "added": added,
        })
        print("[I3] extra batch %d: +%d (%d -> %d)" % (
            bi, added, before, ech.rank), flush=True)

    # Independent-seed cross-check: sample from a fresh seed into a separate
    # span and verify it sits inside the echelon (no new directions).
    cross = _crosscheck_span(fr, cell, ech, p, npts=300,
                             seed=seed + p + 99991)
    print("[I3] cross-check seed: new_dirs=%d / %d" % (
        cross["new_directions"], cross["npts"]), flush=True)

    meta = {
        "p": p, "N3": N3, "P3": ech.rank, "HF3": N3 - ech.rank,
        "npts_tested": n_tested, "stable_window": stable_window,
        "stable_final": stable,
        "saturated_main": stable >= stable_window or ech.rank == N3,
        "extra_batches": extra_ranks,
        "extra_added_total": sum(e["added"] for e in extra_ranks),
        "saturation_ok": all(e["added"] == 0 for e in extra_ranks),
        "crosscheck": cross,
        "rank_curve": curve,
        "seconds": time.time() - t0,
        "seed": seed + p,
    }
    np.save(os.path.join(RES, "cubic_indep_p%d.npy" % p),
            np.array(indep_orig, dtype=np.int64) if indep_orig
            else np.zeros((0, N3), dtype=np.int64))
    np.save(os.path.join(RES, "I3_echelon_p%d.npy" % p), ech.basis)
    np.save(os.path.join(RES, "I3_pivots_p%d.npy" % p),
            np.array(ech.pivots, dtype=np.int64))
    with open(os.path.join(RES, "plateau_p%d.json" % p), "w") as f:
        json.dump(meta, f, indent=2)
    print("[I3] DONE P3=%d HF(3)=%d sat_ok=%s (%.1fs)" % (
        ech.rank, N3 - ech.rank, meta["saturation_ok"], meta["seconds"]),
          flush=True)
    return meta, ech, cell, fr


def _crosscheck_span(fr, cell, ech, p, npts, seed):
    rng = np.random.default_rng(seed)
    new_dirs = 0
    for _ in range(npts):
        pt = rng.integers(0, p, size=(1, 5), dtype=np.int64)
        if not pt[0].any():
            pt[0, 0] = 1
        Mall = L.eval_cell_at_points(fr, cell, pt)
        row, _ = L.cubic_coeff_row(Mall[0], p)
        if np.any(ech.reduce(row)):
            new_dirs += 1
    return {"npts": npts, "seed": seed, "new_directions": new_dirs}


