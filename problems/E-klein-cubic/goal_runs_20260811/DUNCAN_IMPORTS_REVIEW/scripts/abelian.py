"""Shared helpers: finite abelian groups as products of cyclic factors,
their character groups, kernels, and cyclicity tests.

A group is a tuple of moduli  n = (n_1, ..., n_k), meaning  Z/n_1 x ... x Z/n_k.
Its elements are tuples  x = (x_1, ..., x_k),  0 <= x_i < n_i.
A character is a tuple  c = (c_1, ..., c_k) mod n, acting by
    chi_c(x) = exp(2 pi i * sum_i c_i x_i / n_i).
Every character of a finite abelian group arises this way exactly once
(Pontryagin duality for the chosen decomposition), so this parametrisation
of Hom(H, C^*) is complete.
"""

from itertools import product
from math import gcd
from fractions import Fraction
from functools import reduce


def elements(n):
    return list(product(*[range(m) for m in n]))


def pairing(c, x, n):
    """chi_c(x) as an element of Q/Z, returned as a Fraction in [0,1)."""
    s = Fraction(0)
    for ci, xi, ni in zip(c, x, n):
        s += Fraction(ci * xi, ni)
    return s - int(s)


def kernel(c, n):
    return [x for x in elements(n) if pairing(c, x, n) == 0]


def is_injective(c, n):
    return len(kernel(c, n)) == 1


def order(n):
    return reduce(lambda a, b: a * b, n, 1)


def element_order(x, n):
    """order of x in Z/n_1 x ... x Z/n_k"""
    o = 1
    for xi, ni in zip(x, n):
        if xi == 0:
            oi = 1
        else:
            oi = ni // gcd(xi, ni)
        o = o * oi // gcd(o, oi)
    return o


def is_cyclic(n):
    return any(element_order(x, n) == order(n) for x in elements(n))


def char_mul(c1, c2, n):
    return tuple((a + b) % m for a, b, m in zip(c1, c2, n))


def char_pow(c, e, n):
    return tuple((e * a) % m for a, m in zip(c, n))


def char_word(c1, c2, e1, e2, n):
    """chi_1^{e1} chi_2^{e2}"""
    return char_mul(char_pow(c1, e1, n), char_pow(c2, e2, n), n)


def joint_kernel(chars, n):
    """intersection of the kernels of the given characters"""
    ker = elements(n)
    for c in chars:
        ker = [x for x in ker if pairing(c, x, n) == 0]
    return ker


def generate_dual(chars, n):
    """subgroup of the character group generated by `chars` (as a set of tuples)"""
    seen = {tuple(0 for _ in n)}
    frontier = [tuple(0 for _ in n)]
    while frontier:
        cur = frontier.pop()
        for c in chars:
            nxt = char_mul(cur, c, n)
            if nxt not in seen:
                seen.add(nxt)
                frontier.append(nxt)
    return seen


def all_groups(max_order, max_factors=3):
    """all (n_1,...,n_k) with n_i >= 2, product <= max_order, k <= max_factors"""
    out = []

    def rec(prefix, prod):
        if prefix:
            out.append(tuple(prefix))
        if len(prefix) == max_factors:
            return
        start = prefix[-1] if prefix else 2
        for m in range(start, max_order + 1):
            if prod * m <= max_order:
                rec(prefix + [m], prod * m)

    rec([], 1)
    return out
