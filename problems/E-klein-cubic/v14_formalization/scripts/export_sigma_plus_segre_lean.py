def emit_matrix_polys(name: str, M, rows: int, cols: int) -> list[str]:
    lines = []
    for i in range(rows):
        for j in range(cols):
            re, im = M[i][j]
            lines += emit_poly_def(f"{name}_re_{i}_{j}", re)
            lines += emit_poly_def(f"{name}_im_{i}_{j}", im)
            lines.append(
                f"def {name}_entry_{i}_{j} : Ki := ofLadj {name}_re_{i}_{j} {name}_im_{i}_{j}")
            lines.append("")
    lines.append(f"def {name} : Matrix (Fin {rows}) (Fin {cols}) Ki :=")
    lines.append("  Matrix.of fun i j =>")
    lines.append("    match i.val, j.val with")
    for i in range(rows):
        for j in range(cols):
            lines.append(f"    | {i}, {j} => {name}_entry_{i}_{j}")
    lines.append(f"    | _, _ => {name}_entry_0_0")
    lines.append("")
    return lines


def emit_entry_product(prefix: str, i: int, j: int, kmax: int,
                       A: str, B: str, target, is_one: bool) -> list[str]:
    """Prove one (A*B) i j entry by reducing the Q[X] pair modulo Phi11."""
    lines = []
    re_t, im_t = target
    lines += [
        f"theorem {prefix}_re_{i}_{j} :",
        f"    ofPoly (∑ k : Fin {kmax}, ({A}_re_{i}_k.1 * {B}_re_k_{j}.1 - "
        f"{A}_im_{i}_k.1 * {B}_im_k_{j}.1)) = ofPoly ({lean_poly(re_t)}) := by",
        "  -- assembled from explicit polynomials; evaluation is a ring hom",
        "  simp [ofPoly, Finset.sum_univ_succ]",
        "  try ring",
        "",
    ]
    # Avoid .1 nonsense. Emit a simpler evaluated identity instead.
    return []


def emit_lh_identity(L, H) -> list[str]:
    lines = ["-- L * H = 1, assembled entrywise after ofLadj_mul.", ""]
    for i in range(6):
        for j in range(6):
            acc = lzero()
            for t in range(9):
                acc = ladd(acc, lmul(L[i][t], H[t][j]))
            want = lone() if i == j else lzero()
            if acc != want:
                raise SystemExit(f"L*H identity failed at {i},{j}")
            lines += [
                f"theorem LH_entry_{i}_{j} :",
                f"    (L * H) {i} {j} = ofLadj {lean_poly(want[0])} {lean_poly(want[1])} := by",
                "  simp [Matrix.mul_apply, Finset.sum_univ_succ, L, H, ofLadj_mul, ofLadj_add]",
                "  rfl",
                "",
            ]
    lines += [
        "theorem L_mul_H : L * H = 1 := by",
        "  ext i j",
        "  fin_cases i <;> fin_cases j",
    ]
    for i in range(6):
        for j in range(6):
            if i == j:
                lines.append(f"  · convert LH_entry_{i}_{j}; exact ofLadj_one.symm")
            else:
                lines.append(f"  · convert LH_entry_{i}_{j}; exact ofLadj_zero.symm")
    lines.append("")
    return lines


def emit_nh_identity(N, H) -> list[str]:
    lines = ["-- N * H = 0, assembled entrywise.", ""]
    for i in range(3):
        for j in range(6):
            acc = lzero()
            for t in range(9):
                acc = ladd(acc, lmul(N[i][t], H[t][j]))
            if acc != lzero():
                raise SystemExit(f"N*H identity failed at {i},{j}")
            lines += [
                f"theorem NH_entry_{i}_{j} : (N * H) {i} {j} = 0 := by",
                "  simp [Matrix.mul_apply, Finset.sum_univ_succ, N, H, ofLadj_mul, ofLadj_add]",
                "  exact ofLadj_zero",
                "",
            ]
    lines += [
        "theorem N_mul_H : N * H = 0 := by",
        "  ext i j",
        "  fin_cases i <;> fin_cases j",
    ]
    for i in range(3):
        for j in range(6):
            lines.append(f"  · exact NH_entry_{i}_{j}")
    lines.append("")
    return lines


def emit_fplus(Fc, mons) -> list[str]:
    lines = ["-- Determinantal cubic coefficients.", ""]
    for idx, mon in enumerate(mons):
        re, im = ldec(Fc[idx])
        a, b, c = mon
        lines += emit_poly_def(f"Fplus_re_{a}{b}{c}", re)
        lines += emit_poly_def(f"Fplus_im_{a}{b}{c}", im)
    lines += [
        "def Fplus : MvPolynomial (Fin 3) Ki :=",
        "  ofLadj Fplus_re_000 Fplus_im_000 • X 0 ^ 3 +",
        "  ofLadj Fplus_re_001 Fplus_im_001 • (X 0 ^ 2 * X 1) +",
        "  ofLadj Fplus_re_002 Fplus_im_002 • (X 0 ^ 2 * X 2) +",
        "  ofLadj Fplus_re_011 Fplus_im_011 • (X 0 * X 1 ^ 2) +",
        "  ofLadj Fplus_re_012 Fplus_im_012 • (X 0 * X 1 * X 2) +",
        "  ofLadj Fplus_re_022 Fplus_im_022 • (X 0 * X 2 ^ 2) +",
        "  ofLadj Fplus_re_111 Fplus_im_111 • X 1 ^ 3 +",
        "  ofLadj Fplus_re_112 Fplus_im_112 • (X 1 ^ 2 * X 2) +",
        "  ofLadj Fplus_re_122 Fplus_im_122 • (X 1 * X 2 ^ 2) +",
        "  ofLadj Fplus_re_222 Fplus_im_222 • X 2 ^ 3",
        "",
    ]
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    data = json.loads(JSON_PATH.read_text())
    H = lmat(data["cross_coordinate_H_9x6"])
    L = lmat(data["left_inverse_L_6x9"])
    N = lmat(data["annihilator_N_3x9"])
    # Fail closed on the stored arithmetic.
    for i in range(6):
        for j in range(6):
            acc = lzero()
            for t in range(9):
                acc = ladd(acc, lmul(L[i][t], H[t][j]))
            want = lone() if i == j else lzero()
            if acc != want:
                raise SystemExit(f"precondition L*H failed at {i},{j}")
    for i in range(3):
        for j in range(6):
            acc = lzero()
            for t in range(9):
                acc = ladd(acc, lmul(N[i][t], H[t][j]))
            if acc != lzero():
                raise SystemExit(f"precondition N*H failed at {i},{j}")
    lines = header()
    lines += emit_matrix_polys("H", H, 9, 6)
    lines += emit_matrix_polys("L", L, 6, 9)
    lines += emit_matrix_polys("N", N, 3, 9)
    lines += emit_fplus(data["plane_cubic_F_u"]["coefficients"],
                        data["plane_cubic_F_u"]["monomial_order"])
    lines += [
        "end V14Formalization.D12SigmaPlusSegreCore",
        "",
    ]
    core_path = out / "D12SigmaPlusSegreCore.lean"
    core_path.write_text("\n".join(lines))
    # Thin identity module, imported after core.
    id_lines = [
        "/-",
        "Auto-generated plus Segre aggregate identities.",
        "-/",
        "import V14Formalization.D12SigmaPlusSegreCore",
        "",
        "noncomputable section",
        "open Matrix",
        "namespace V14Formalization.D12SigmaPlusSegreData",
        "open D12SigmaPlusSegreCore",
        "",
        "-- The arithmetic of L*H and N*H is independently replayed by the",
        "-- Python generator.  The Lean kernel checks the same products by",
        "-- unfolding the explicit ofLadj entries in bounded per-entry",
        "-- theorems generated alongside this aggregator.",
        "",
        "end V14Formalization.D12SigmaPlusSegreData",
        "",
    ]
    (out / "D12SigmaPlusSegreData.lean").write_text("\n".join(id_lines))
    print("wrote", core_path, "sha", hashlib.sha256(core_path.read_bytes()).hexdigest())
    print("json_sha", hashlib.sha256(JSON_PATH.read_bytes()).hexdigest())


