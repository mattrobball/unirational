        "Auto-generated by scripts/export_sigma_plus_segre_lean.py.",
        "Stock-limit, kernel-checkable plus Segre certificates over K(i).",
        "-/",
        "import V14Formalization.GeometricV14Carrier",
        "import V14Formalization.D12PolynomialEvaluation",
        "import V14Formalization.D12U6PolynomialSeal",
        "",
        "noncomputable section",
        "open Matrix Polynomial",
        "namespace V14Formalization.D12SigmaPlusSegreCore",
        "open GeometricV14Carrier D12PolynomialData D12PolynomialEvaluation",
        "",
        "abbrev k := GeometricV14Carrier.k",
        "abbrev Ki := GeometricV14Carrier.Ladj",
        "",
        "def ofPoly (p : Polynomial ℚ) : k := evalPolyAt WeilRep.ζ p",
        "",
        "def ofLadj (re im : Polynomial ℚ) : Ki :=",
        "  algebraMap k Ki (ofPoly re) + algebraMap k Ki (ofPoly im) * iRoot",
        "",
        "theorem ofLadj_zero : ofLadj 0 0 = 0 := by",
        "  simp [ofLadj, ofPoly, evalPolyAt, map_zero]",
        "",
        "theorem ofLadj_one : ofLadj 1 0 = 1 := by",
        "  simp [ofLadj, ofPoly, evalPolyAt, map_one, map_zero]",
        "",
        "theorem ofPoly_add (p q : Polynomial ℚ) :",
        "    ofPoly (p + q) = ofPoly p + ofPoly q := map_add (evalPolyAt WeilRep.ζ) p q",
        "",
        "theorem ofPoly_mul (p q : Polynomial ℚ) :",
        "    ofPoly (p * q) = ofPoly p * ofPoly q := map_mul (evalPolyAt WeilRep.ζ) p q",
        "",
        "theorem ofPoly_neg (p : Polynomial ℚ) :",
        "    ofPoly (-p) = -ofPoly p := map_neg (evalPolyAt WeilRep.ζ) p",
        "",
        "theorem ofPoly_C (a : ℚ) : ofPoly (C a) = algebraMap ℚ k a := by",
        "  simp [ofPoly, evalPolyAt]",
        "",
        "theorem ofLadj_add (a b c d : Polynomial ℚ) :",
        "    ofLadj a b + ofLadj c d = ofLadj (a + c) (b + d) := by",
        "  simp [ofLadj, ofPoly_add, map_add]; ring",
        "",
        "theorem ofLadj_mul (a b c d : Polynomial ℚ) :",
        "    ofLadj a b * ofLadj c d = ofLadj (a * c - b * d) (a * d + b * c) := by",
        "  simp [ofLadj, ofPoly_mul, ofPoly_add, ofPoly_neg, map_add, map_mul, map_sub]",
        "  have hi : (iRoot : Ki) ^ 2 = -1 := by",
        "    have := GeometricV14Carrier.aeval_iRoot",
        "    simp [aeval_def] at this",
        "    linear_combination this",
        "  ring_nf",
        "  simp [pow_two, hi]",
        "  ring",
