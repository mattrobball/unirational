#!/usr/bin/env python3
"""Emit kernel-checkable minorCoeffsH = minorQ identities.

Each (minor, monom) entry is its own Lean file.  The identity is the
bilinear combination of four H-rows against the stored minorQ cell.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import export_sigma_plus_identities as g

JSON_PATH = ROOT / "results" / "sigma_plus_segre_Ki.json"

MONOMS = [(i, j) for i in range(6) for j in range(i, 6)]
assert len(MONOMS) == 21

ORDER = [
    (0, 1, 0, 1),
    (0, 1, 0, 2),
    (0, 1, 1, 2),
    (0, 2, 0, 1),
    (0, 2, 0, 2),
    (0, 2, 1, 2),
    (1, 2, 0, 1),
    (1, 2, 0, 2),
    (1, 2, 1, 2),
]


def is_zero(cell) -> bool:
    re, im = g.reduce_phi(cell[0]), g.reduce_phi(cell[1])
    return (not re or all(x == 0 for x in re)) and (not im or all(x == 0 for x in im))


def header() -> list[str]:
    return [
        "/-",
        "Auto-generated by scripts/export_sigma_plus_minor_h.py.",
        "Stock-limit, kernel-checkable H-minor vs stored minorQ identities.",
        "-/",
        "import V14Formalization.D12SigmaPlusSegreEval",
        "import V14Formalization.D12SigmaPlusSegreApplyH",
        "import V14Formalization.D12SigmaPlusSegreMinorQ",
        "import V14Formalization.D12SigmaPlusSegreGeom",
        "",
        "noncomputable section",
        "open Matrix Polynomial",
        "namespace V14Formalization.D12SigmaPlusSegreCore",
        "open D12PolynomialData",
        "open D12SigmaPlusQuadric6",
        "",
    ]


def footer() -> list[str]:
    return [
        "end V14Formalization.D12SigmaPlusSegreCore",
        "",
    ]


def emit_product(prefix: str, p: int, q: int, i: int, j: int, H) -> list[str]:
    """Prove H_entry_p_i * H_entry_q_j = ofLadj pre pim."""
    lines: list[str] = []
    Hp = H[p][i]
    Hq = H[q][j]
    raw = g.lmul_raw(Hp, Hq)
    # Keep the unreduced product so the polynomial identity is definitional
    # over ℚ.  Φ₁₁ reduction is applied only to the assembled minor.
    pre, pim = raw[0], raw[1]
    lines += [
        f"def {prefix}_pre : Polynomial ℚ := {g.lean_poly(pre)}",
        f"def {prefix}_pim : Polynomial ℚ := {g.lean_poly(pim)}",
    ]
    if is_zero(Hp) or is_zero(Hq):
        zsrc = f"H_entry_{p}_{i}" if is_zero(Hp) else f"H_entry_{q}_{j}"
        lines += [
            f"theorem {prefix}_mul :",
            f"    H_entry_{p}_{i} * H_entry_{q}_{j} =",
            f"      ofLadj {prefix}_pre {prefix}_pim := by",
            f"  have hz : {zsrc} = 0 := by",
            f"    rw [{zsrc}]; exact ofLadj_zero",
            f"  rw [hz, {prefix}_pre, {prefix}_pim]",
            "  simp [ofLadj_zero]",
            "",
        ]
    else:
        lines += [
            f"theorem {prefix}_pre_eq :",
            f"    H_re_{p}_{i} * H_re_{q}_{j} - H_im_{p}_{i} * H_im_{q}_{j} =",
            f"      {prefix}_pre := by",
            "  refine Polynomial.funext fun r => ?_",
            f"  simp only [H_re_{p}_{i}, H_im_{p}_{i}, H_re_{q}_{j}, H_im_{q}_{j},",
            f"    {prefix}_pre]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem {prefix}_pim_eq :",
            f"    H_re_{p}_{i} * H_im_{q}_{j} + H_im_{p}_{i} * H_re_{q}_{j} =",
            f"      {prefix}_pim := by",
            "  refine Polynomial.funext fun r => ?_",
            f"  simp only [H_re_{p}_{i}, H_im_{p}_{i}, H_re_{q}_{j}, H_im_{q}_{j},",
            f"    {prefix}_pim]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem {prefix}_mul :",
            f"    H_entry_{p}_{i} * H_entry_{q}_{j} =",
            f"      ofLadj {prefix}_pre {prefix}_pim := by",
            f"  rw [H_entry_{p}_{i}, H_entry_{q}_{j}, ofLadj_mul,",
            f"    {prefix}_pre_eq, {prefix}_pim_eq]",
            "",
        ]
    return lines, (pre, pim)


def emit_entry(s: int, k: int, H, minorQ) -> list[str]:
    a0, a1, b0, b1 = ORDER[s]
    p = 3 * a0 + b0
    q = 3 * a1 + b1
    r = 3 * a0 + b1
    t = 3 * a1 + b0
    i, j = MONOMS[k]
    pref = f"HM_{s}_{k}"
    lines = header()
    if i == j:
        # bilinear = H_p_i * H_q_i - H_r_i * H_t_i
        l1, c1 = emit_product(f"{pref}_A", p, q, i, i, H)
        l2, c2 = emit_product(f"{pref}_B", r, t, i, i, H)
        lines += l1 + l2
        raw_re = g.sub(c1[0], c2[0])
        raw_im = g.sub(c1[1], c2[1])
        qre, rre = g.divmod_phi(raw_re)
        qim, rim = g.divmod_phi(raw_im)
        tgt = minorQ[s][k]
        tgt_re, tgt_im = g.reduce_phi(tgt[0]), g.reduce_phi(tgt[1])
        if rre != tgt_re or rim != tgt_im:
            raise SystemExit(
                f"mismatch HM {s} {k}: got {(rre, rim)} want {(tgt_re, tgt_im)}"
            )
        lines += [
            f"def {pref}_qre : Polynomial ℚ := {g.lean_poly(qre)}",
            f"def {pref}_qim : Polynomial ℚ := {g.lean_poly(qim)}",
            f"theorem {pref}_bilin :",
            f"    bilinearCoeffs (Hrow {p}) (Hrow {q}) {k} -",
            f"        bilinearCoeffs (Hrow {r}) (Hrow {t}) {k} =",
            f"      ofLadj {pref}_A_pre {pref}_A_pim -",
            f"        ofLadj {pref}_B_pre {pref}_B_pim := by",
            f"  have hpq : bilinearCoeffs (Hrow {p}) (Hrow {q}) {k} =",
            f"      H_entry_{p}_{i} * H_entry_{q}_{i} := by",
            f"    simp [bilinearCoeffs, monomPair_{k}, Hrow, H_apply_{p}_{i},",
            f"      H_apply_{q}_{i}]",
            f"  have hrt : bilinearCoeffs (Hrow {r}) (Hrow {t}) {k} =",
            f"      H_entry_{r}_{i} * H_entry_{t}_{i} := by",
            f"    simp [bilinearCoeffs, monomPair_{k}, Hrow, H_apply_{r}_{i},",
            f"      H_apply_{t}_{i}]",
            f"  rw [hpq, hrt, {pref}_A_mul, {pref}_B_mul]",
            f"theorem {pref}_sub :",
            f"    ofLadj {pref}_A_pre {pref}_A_pim -",
            f"        ofLadj {pref}_B_pre {pref}_B_pim =",
            f"      ofLadj ({pref}_A_pre - {pref}_B_pre)",
            f"        ({pref}_A_pim - {pref}_B_pim) :=",
            "  ofLadj_sub _ _ _ _",
            f"theorem {pref}_red :",
            f"    {pref}_A_pre - {pref}_B_pre =",
            f"      minorQ_re_{s}_{k} + Phi11 * {pref}_qre := by",
            "  refine Polynomial.funext fun r => ?_",
            "  rw [Phi11_expand]",
            f"  simp only [{pref}_A_pre, {pref}_B_pre, minorQ_re_{s}_{k}, {pref}_qre]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem {pref}_redim :",
            f"    {pref}_A_pim - {pref}_B_pim =",
            f"      minorQ_im_{s}_{k} + Phi11 * {pref}_qim := by",
            "  refine Polynomial.funext fun r => ?_",
            "  rw [Phi11_expand]",
            f"  simp only [{pref}_A_pim, {pref}_B_pim, minorQ_im_{s}_{k}, {pref}_qim]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem HM_entry_{s}_{k} :",
            f"    minorCoeffsH {s} {k} = minorQ {s} {k} := by",
            "  unfold minorCoeffsH",
            f"  simp [minorOrder_{s}, crossIndex]",
            f"  have h := {pref}_bilin",
            "  -- reshape the four cross indices to p,q,r,t",
            f"  change bilinearCoeffs (Hrow {p}) (Hrow {q}) {k} -",
            f"      bilinearCoeffs (Hrow {r}) (Hrow {t}) {k} =",
            f"    minorQ {s} {k}",
            f"  rw [h, {pref}_sub, {pref}_red, {pref}_redim, ofLadj_add_Phi11]",
            f"  change ofLadj minorQ_re_{s}_{k} minorQ_im_{s}_{k} = minorQ {s} {k}",
            "  rfl",
            "",
        ]
    else:
        # bilinear = (H_p_i H_q_j + H_p_j H_q_i) - (H_r_i H_t_j + H_r_j H_t_i)
        l1, c1 = emit_product(f"{pref}_A", p, q, i, j, H)
        l2, c2 = emit_product(f"{pref}_B", p, q, j, i, H)
        l3, c3 = emit_product(f"{pref}_C", r, t, i, j, H)
        l4, c4 = emit_product(f"{pref}_D", r, t, j, i, H)
        lines += l1 + l2 + l3 + l4
        raw_re = g.sub(g.add(c1[0], c2[0]), g.add(c3[0], c4[0]))
        raw_im = g.sub(g.add(c1[1], c2[1]), g.add(c3[1], c4[1]))
        qre, rre = g.divmod_phi(raw_re)
        qim, rim = g.divmod_phi(raw_im)
        tgt = minorQ[s][k]
        tgt_re, tgt_im = g.reduce_phi(tgt[0]), g.reduce_phi(tgt[1])
        if rre != tgt_re or rim != tgt_im:
            raise SystemExit(
                f"mismatch HM {s} {k}: got {(rre, rim)} want {(tgt_re, tgt_im)}"
            )
        lines += [
            f"def {pref}_qre : Polynomial ℚ := {g.lean_poly(qre)}",
            f"def {pref}_qim : Polynomial ℚ := {g.lean_poly(qim)}",
            f"theorem {pref}_bilin :",
            f"    bilinearCoeffs (Hrow {p}) (Hrow {q}) {k} -",
            f"        bilinearCoeffs (Hrow {r}) (Hrow {t}) {k} =",
            f"      (ofLadj {pref}_A_pre {pref}_A_pim +",
            f"          ofLadj {pref}_B_pre {pref}_B_pim) -",
            f"        (ofLadj {pref}_C_pre {pref}_C_pim +",
            f"            ofLadj {pref}_D_pre {pref}_D_pim) := by",
            f"  have hpq : bilinearCoeffs (Hrow {p}) (Hrow {q}) {k} =",
            f"      H_entry_{p}_{i} * H_entry_{q}_{j} +",
            f"        H_entry_{p}_{j} * H_entry_{q}_{i} := by",
            f"    simp [bilinearCoeffs, monomPair_{k}, Hrow, H_apply_{p}_{i},",
            f"      H_apply_{q}_{j}, H_apply_{p}_{j}, H_apply_{q}_{i}]",
            f"  have hrt : bilinearCoeffs (Hrow {r}) (Hrow {t}) {k} =",
            f"      H_entry_{r}_{i} * H_entry_{t}_{j} +",
            f"        H_entry_{r}_{j} * H_entry_{t}_{i} := by",
            f"    simp [bilinearCoeffs, monomPair_{k}, Hrow, H_apply_{r}_{i},",
            f"      H_apply_{t}_{j}, H_apply_{r}_{j}, H_apply_{t}_{i}]",
            f"  rw [hpq, hrt, {pref}_A_mul, {pref}_B_mul, {pref}_C_mul, {pref}_D_mul]",
            f"theorem {pref}_sum :",
            f"    (ofLadj {pref}_A_pre {pref}_A_pim +",
            f"        ofLadj {pref}_B_pre {pref}_B_pim) -",
            f"      (ofLadj {pref}_C_pre {pref}_C_pim +",
            f"          ofLadj {pref}_D_pre {pref}_D_pim) =",
            f"      ofLadj ({pref}_A_pre + {pref}_B_pre - {pref}_C_pre - {pref}_D_pre)",
            f"        ({pref}_A_pim + {pref}_B_pim - {pref}_C_pim - {pref}_D_pim) := by",
            f"  rw [ofLadj_add, ofLadj_add, ofLadj_sub, sub_add_eq_sub_sub,",
            "    sub_add_eq_sub_sub]",
            f"theorem {pref}_red :",
            f"    {pref}_A_pre + {pref}_B_pre - {pref}_C_pre - {pref}_D_pre =",
            f"      minorQ_re_{s}_{k} + Phi11 * {pref}_qre := by",
            "  refine Polynomial.funext fun r => ?_",
            "  rw [Phi11_expand]",
            f"  simp only [{pref}_A_pre, {pref}_B_pre, {pref}_C_pre, {pref}_D_pre,",
            f"    minorQ_re_{s}_{k}, {pref}_qre]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem {pref}_redim :",
            f"    {pref}_A_pim + {pref}_B_pim - {pref}_C_pim - {pref}_D_pim =",
            f"      minorQ_im_{s}_{k} + Phi11 * {pref}_qim := by",
            "  refine Polynomial.funext fun r => ?_",
            "  rw [Phi11_expand]",
            f"  simp only [{pref}_A_pim, {pref}_B_pim, {pref}_C_pim, {pref}_D_pim,",
            f"    minorQ_im_{s}_{k}, {pref}_qim]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem HM_entry_{s}_{k} :",
            f"    minorCoeffsH {s} {k} = minorQ {s} {k} := by",
            "  unfold minorCoeffsH",
            f"  simp [minorOrder_{s}, crossIndex]",
            f"  change bilinearCoeffs (Hrow {p}) (Hrow {q}) {k} -",
            f"      bilinearCoeffs (Hrow {r}) (Hrow {t}) {k} =",
            f"    minorQ {s} {k}",
            f"  rw [{pref}_bilin, {pref}_sum, {pref}_red, {pref}_redim,",
            "    ofLadj_add_Phi11]",
            f"  change ofLadj minorQ_re_{s}_{k} minorQ_im_{s}_{k} = minorQ {s} {k}",
            "  rfl",
            "",
        ]
    lines += footer()
    return lines


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", type=Path, required=True)
    args = ap.parse_args()
    out: Path = args.out_dir
    out.mkdir(parents=True, exist_ok=True)
    data = g.json.loads(JSON_PATH.read_text())
    H = g.lmat(data["cross_coordinate_H_9x6"])
    minorQ = g.lmat(data["segree_minors"]["quadrics"])
    n = 0
    for s in range(9):
        for k in range(21):
            path = out / f"D12SigmaPlusSegreHM_{s}_{k}.lean"
            path.write_text("\n".join(emit_entry(s, k, H, minorQ)))
            n += 1
    print(f"wrote {n} HM files to {out}")


if __name__ == "__main__":
    main()
