def is_zero(cell) -> bool:
    re, im = g.reduce_phi(cell[0]), g.reduce_phi(cell[1])
    return (not re or all(x == 0 for x in re)) and (not im or all(x == 0 for x in im))


def pad_to_adder(n: int) -> int:
    for k in (1, 2, 3, 4, 6, 9, 12, 15, 18):
        if k >= n:
            return k
    raise SystemExit(f"too many terms: {n}")


def header(extra_imports=None) -> list[str]:
    extras = extra_imports or []
    return [
        "/-",
        "Auto-generated by scripts/export_sigma_plus_span_identities.py.",
        "Stock-limit, kernel-checkable plus Segre span identities.",
        "-/",
        "import V14Formalization.D12SigmaPlusSegreEval",
        *extras,
        "",
        "noncomputable section",
        "open Matrix Polynomial",
        "namespace V14Formalization.D12SigmaPlusSegreCore",
        "open D12PolynomialData",
        "",
    ]


def footer() -> list[str]:
    return [
        "end V14Formalization.D12SigmaPlusSegreCore",
        "",
    ]


def emit_matrix(name: str, M, rows: int, cols: int) -> list[str]:
    lines = []
    for i in range(rows):
        for j in range(cols):
            re, im = g.reduce_phi(M[i][j][0]), g.reduce_phi(M[i][j][1])
            lines += [
                f"def {name}_re_{i}_{j} : Polynomial ℚ := {g.lean_poly(re)}",
                f"def {name}_im_{i}_{j} : Polynomial ℚ := {g.lean_poly(im)}",
                f"def {name}_entry_{i}_{j} : Ki := ofLadj {name}_re_{i}_{j} {name}_im_{i}_{j}",
                "",
            ]
    lines.append(f"def {name} : Matrix (Fin {rows}) (Fin {cols}) Ki :=")
    lines.append("  fun i j =>")
    lines.append("    match i.val, j.val with")
    for i in range(rows):
        for j in range(cols):
            lines.append(f"    | {i}, {j} => {name}_entry_{i}_{j}")
    lines += [f"    | _, _ => {name}_entry_0_0", ""]
    return lines


def emit_apply(name: str, rows: int, cols: int) -> list[str]:
    lines = header(["import V14Formalization.D12SigmaPlusSegreSpanCore"])
    for i in range(rows):
        for j in range(cols):
            lines += [
                f"theorem {name}_apply_{i}_{j} :",
                f"    {name} ({i} : Fin {rows}) ({j} : Fin {cols}) = {name}_entry_{i}_{j} := by",
                f"  unfold {name}",
                "  simp [Matrix.of_apply]",
                "",
            ]
    lines += footer()
    return lines


def emit_mul_identity(
    prefix: str,
    A: str,
    B: str,
    C: str,
    i: int,
    j: int,
    acols: int,
    Arows,
    Brows,
    terms_all,
    q_re,
    q_im,
) -> list[str]:
    extra = [
        "import V14Formalization.D12SigmaPlusSegreSpanCore",
    ]
    lines = header(extra)
    lines += [
        f"def {prefix}_qre_{i}_{j} : Polynomial ℚ := {g.lean_poly(q_re)}",
        f"def {prefix}_qim_{i}_{j} : Polynomial ℚ := {g.lean_poly(q_im)}",
        "",
    ]
    for t, (pre, pim, zeroA, zeroB) in enumerate(terms_all):
        lines += [
            f"def {prefix}_pre_{i}_{j}_{t} : Polynomial ℚ := {g.lean_poly(pre)}",
            f"def {prefix}_pim_{i}_{j}_{t} : Polynomial ℚ := {g.lean_poly(pim)}",
        ]
        if zeroA or zeroB:
            zsrc = f"{A}_entry_{i}_{t}" if zeroA else f"{B}_entry_{t}_{j}"
            lines += [
                f"theorem {prefix}_term_{i}_{j}_{t} :",
                f"    {A}_entry_{i}_{t} * {B}_entry_{t}_{j} =",
                f"      ofLadj {prefix}_pre_{i}_{j}_{t} {prefix}_pim_{i}_{j}_{t} := by",
                f"  have hz : {zsrc} = 0 := by",
                f"    rw [{zsrc}]; exact ofLadj_zero",
                f"  rw [hz, {prefix}_pre_{i}_{j}_{t}, {prefix}_pim_{i}_{j}_{t}]",
                "  simp [ofLadj_zero]",
                "",
            ]
        else:
            lines += [
                f"theorem {prefix}_pre_eq_{i}_{j}_{t} :",
                f"    {A}_re_{i}_{t} * {B}_re_{t}_{j} - {A}_im_{i}_{t} * {B}_im_{t}_{j} =",
                f"      {prefix}_pre_{i}_{j}_{t} := by",
                "  refine Polynomial.funext fun r => ?_",
                f"  simp only [{A}_re_{i}_{t}, {A}_im_{i}_{t}, {B}_re_{t}_{j}, {B}_im_{t}_{j},",
                f"    {prefix}_pre_{i}_{j}_{t}]",
                "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
                "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
                "    Polynomial.eval_neg, Polynomial.eval_zero]",
                "  try ring",
                f"theorem {prefix}_pim_eq_{i}_{j}_{t} :",
                f"    {A}_re_{i}_{t} * {B}_im_{t}_{j} + {A}_im_{i}_{t} * {B}_re_{t}_{j} =",
                f"      {prefix}_pim_{i}_{j}_{t} := by",
                "  refine Polynomial.funext fun r => ?_",
                f"  simp only [{A}_re_{i}_{t}, {A}_im_{i}_{t}, {B}_re_{t}_{j}, {B}_im_{t}_{j},",
                f"    {prefix}_pim_{i}_{j}_{t}]",
                "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
                "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
                "    Polynomial.eval_neg, Polynomial.eval_zero]",
                "  try ring",
                f"theorem {prefix}_term_{i}_{j}_{t} :",
                f"    {A}_entry_{i}_{t} * {B}_entry_{t}_{j} =",
                f"      ofLadj {prefix}_pre_{i}_{j}_{t} {prefix}_pim_{i}_{j}_{t} := by",
                f"  rw [{A}_entry_{i}_{t}, {B}_entry_{t}_{j}, ofLadj_mul,",
                f"    {prefix}_pre_eq_{i}_{j}_{t}, {prefix}_pim_eq_{i}_{j}_{t}]",
                "",
            ]

    re_named = " + ".join(f"{prefix}_pre_{i}_{j}_{t}" for t in range(acols))
    im_named = " + ".join(f"{prefix}_pim_{i}_{j}_{t}" for t in range(acols))
    unfold_pre = ", ".join(f"{prefix}_pre_{i}_{j}_{t}" for t in range(acols))
    unfold_pim = ", ".join(f"{prefix}_pim_{i}_{j}_{t}" for t in range(acols))
    term_thms = ", ".join(f"{prefix}_term_{i}_{j}_{t}" for t in range(acols))
    term_sum = " + ".join(
        f"{A}_entry_{i}_{t} * {B}_entry_{t}_{j}" for t in range(acols)
    )
    if acols == 15:
        adder = "ofLadj_add15"
        summer = "sum_fin15"
    elif acols == 9:
        adder = "ofLadj_add9"
        summer = "sum_fin9"
    else:
        raise SystemExit(f"unsupported inner dim {acols}")
    add_args = []
    for t in range(acols):
        add_args.append(f"{prefix}_pre_{i}_{j}_{t}")
        add_args.append(f"{prefix}_pim_{i}_{j}_{t}")

    lines += [
        f"theorem {prefix}_sum_poly_re_{i}_{j} :",
        f"    {re_named} = {C}_re_{i}_{j} + Phi11 * {prefix}_qre_{i}_{j} := by",
        "  refine Polynomial.funext fun r => ?_",
        "  rw [Phi11_expand]",
        f"  simp only [{unfold_pre}, {C}_re_{i}_{j}, {prefix}_qre_{i}_{j}]",
        "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
        "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
        "    Polynomial.eval_neg, Polynomial.eval_zero, Polynomial.eval_one]",
        "  try ring",
        "",
        f"theorem {prefix}_sum_poly_im_{i}_{j} :",
        f"    {im_named} = {C}_im_{i}_{j} + Phi11 * {prefix}_qim_{i}_{j} := by",
        "  refine Polynomial.funext fun r => ?_",
        "  rw [Phi11_expand]",
        f"  simp only [{unfold_pim}, {C}_im_{i}_{j}, {prefix}_qim_{i}_{j}]",
        "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
        "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
        "    Polynomial.eval_neg, Polynomial.eval_zero, Polynomial.eval_one]",
        "  try ring",
        "",
        f"theorem {prefix}_sum_entries_{i}_{j} :",
        f"    {term_sum} =",
        f"      ofLadj ({re_named}) ({im_named}) := by",
        f"  simp only [{term_thms}]",
        f"  simpa [add_assoc] using {adder} " + " ".join(add_args),
        "",
        f"theorem {prefix}_eval_{i}_{j} :",
        f"    ofLadj ({re_named}) ({im_named}) = {C}_entry_{i}_{j} := by",
        f"  rw [{prefix}_sum_poly_re_{i}_{j}, {prefix}_sum_poly_im_{i}_{j},",
        f"    ofLadj_add_Phi11, {C}_entry_{i}_{j}]",
        "",
        f"theorem {prefix}_entry_{i}_{j} : ({A} * {B}) {i} {j} = {C} {i} {j} := by",
        "  rw [Matrix.mul_apply]",
        f"  rw [{summer}]",
        f"  change {term_sum} = {C}_entry_{i}_{j}",
        f"  exact ({prefix}_sum_entries_{i}_{j}).trans {prefix}_eval_{i}_{j}",
        "",
    ]
    lines += footer()
    return lines


