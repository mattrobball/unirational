ZERO_A_ENTRIES: set[tuple[str, int, int]] = set()


def is_zero_entry_name(A: str, i: int, t: int) -> bool:
    return (A, i, t) in ZERO_A_ENTRIES


def bilinear_coeff(a, b, k: int):
    p, q = MONOMS[k]
    if p == q:
        return g.lmul_raw(a[p], b[p])
    left = g.lmul_raw(a[p], b[q])
    right = g.lmul_raw(a[q], b[p])
    return (g.add(left[0], right[0]), g.add(left[1], right[1]))


def emit_minor_h_identity(s: int, k: int, H, minorQ) -> list[str]:
    """Prove minorCoeffsH s k = minorQ s k from H-row products."""
    # minorOrder matches exporter combinations
    meta = [
        (0, 1, 0, 1), (0, 1, 0, 2), (0, 1, 1, 2),
        (0, 2, 0, 1), (0, 2, 0, 2), (0, 2, 1, 2),
        (1, 2, 0, 1), (1, 2, 0, 2), (1, 2, 1, 2),
    ]
    a0, a1, b0, b1 = meta[s]
    r00 = 3 * a0 + b0
    r11 = 3 * a1 + b1
    r01 = 3 * a0 + b1
    r10 = 3 * a1 + b0
    p, q = MONOMS[k]
    # bilinearCoeffs (Hrow r00) (Hrow r11) k - bilinearCoeffs (Hrow r01) (Hrow r10) k
    if p == q:
        pairs = [((r00, p), (r11, p), 1), ((r01, p), (r10, p), -1)]
    else:
        pairs = [
            ((r00, p), (r11, q), 1),
            ((r00, q), (r11, p), 1),
            ((r01, p), (r10, q), -1),
            ((r01, q), (r10, p), -1),
        ]
    acc_re, acc_im = [], []
    term_data = []
    for (rA, cA), (rB, cB), sgn in pairs:
        pre, pim = g.lmul_raw(H[rA][cA], H[rB][cB])
        if sgn < 0:
            pre, pim = g.neg(pre), g.neg(pim)
        term_data.append((rA, cA, rB, cB, sgn, pre, pim))
        acc_re = g.add(acc_re, pre)
        acc_im = g.add(acc_im, pim)
    qre, rre = g.divmod_phi(acc_re)
    qim, rim = g.divmod_phi(acc_im)
    tgt = minorQ[s][k]
    if rre != g.reduce_phi(tgt[0]) or rim != g.reduce_phi(tgt[1]):
        # compare reduced target
        tqre, trre = g.divmod_phi(tgt[0])
        tqim, trim = g.divmod_phi(tgt[1])
        if rre != trre or rim != trim:
            raise SystemExit(
                f"minorCoeffsH mismatch at {s},{k}: {rre},{rim} vs {trre},{trim}"
            )
    lines = header([
        "import V14Formalization.D12SigmaPlusSegreApplyH",
        "import V14Formalization.D12SigmaPlusSegreApply_minorQ",
        "import V14Formalization.D12SigmaPlusQuadric6",
        "import V14Formalization.D12SigmaPlusSegreGeom",
    ])
    lines += [
        f"def MH_{s}_{k}_qre : Polynomial ℚ := {g.lean_poly(qre)}",
        f"def MH_{s}_{k}_qim : Polynomial ℚ := {g.lean_poly(qim)}",
        "",
    ]
    for idx, (rA, cA, rB, cB, sgn, pre, pim) in enumerate(term_data):
        raw_pre, raw_pim = g.lmul_raw(H[rA][cA], H[rB][cB])
        lines += [
            f"def MH_{s}_{k}_rawpre_{idx} : Polynomial ℚ := {g.lean_poly(raw_pre)}",
            f"def MH_{s}_{k}_rawpim_{idx} : Polynomial ℚ := {g.lean_poly(raw_pim)}",
            f"theorem MH_{s}_{k}_rawpre_eq_{idx} :",
            f"    H_re_{rA}_{cA} * H_re_{rB}_{cB} - H_im_{rA}_{cA} * H_im_{rB}_{cB} =",
            f"      MH_{s}_{k}_rawpre_{idx} := by",
            "  refine Polynomial.funext fun r => ?_",
            f"  simp only [H_re_{rA}_{cA}, H_im_{rA}_{cA}, H_re_{rB}_{cB}, H_im_{rB}_{cB},",
            f"    MH_{s}_{k}_rawpre_{idx}]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem MH_{s}_{k}_rawpim_eq_{idx} :",
            f"    H_re_{rA}_{cA} * H_im_{rB}_{cB} + H_im_{rA}_{cA} * H_re_{rB}_{cB} =",
            f"      MH_{s}_{k}_rawpim_{idx} := by",
            "  refine Polynomial.funext fun r => ?_",
            f"  simp only [H_re_{rA}_{cA}, H_im_{rA}_{cA}, H_re_{rB}_{cB}, H_im_{rB}_{cB},",
            f"    MH_{s}_{k}_rawpim_{idx}]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try ring",
            f"theorem MH_{s}_{k}_raw_{idx} :",
            f"    H_entry_{rA}_{cA} * H_entry_{rB}_{cB} =",
            f"      ofLadj MH_{s}_{k}_rawpre_{idx} MH_{s}_{k}_rawpim_{idx} := by",
            f"  rw [H_entry_{rA}_{cA}, H_entry_{rB}_{cB}, ofLadj_mul,",
            f"    MH_{s}_{k}_rawpre_eq_{idx}, MH_{s}_{k}_rawpim_eq_{idx}]",
            "",
        ]
        if sgn < 0:
            lines += [
                f"def MH_{s}_{k}_pre_{idx} : Polynomial ℚ := {g.lean_poly(pre)}",
                f"def MH_{s}_{k}_pim_{idx} : Polynomial ℚ := {g.lean_poly(pim)}",
                f"theorem MH_{s}_{k}_pre_eq_{idx} :",
                f"    -MH_{s}_{k}_rawpre_{idx} = MH_{s}_{k}_pre_{idx} := by",
                "  refine Polynomial.funext fun r => ?_",
                f"  simp only [MH_{s}_{k}_rawpre_{idx}, MH_{s}_{k}_pre_{idx}]",
                "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
                "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
                "    Polynomial.eval_neg, Polynomial.eval_zero]",
                "  try ring",
                f"theorem MH_{s}_{k}_pim_eq_{idx} :",
                f"    -MH_{s}_{k}_rawpim_{idx} = MH_{s}_{k}_pim_{idx} := by",
                "  refine Polynomial.funext fun r => ?_",
                f"  simp only [MH_{s}_{k}_rawpim_{idx}, MH_{s}_{k}_pim_{idx}]",
                "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
                "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
                "    Polynomial.eval_neg, Polynomial.eval_zero]",
                "  try ring",
                f"theorem MH_{s}_{k}_term_{idx} :",
                f"    -(H_entry_{rA}_{cA} * H_entry_{rB}_{cB}) =",
                f"      ofLadj MH_{s}_{k}_pre_{idx} MH_{s}_{k}_pim_{idx} := by",
                f"  rw [MH_{s}_{k}_raw_{idx}, ofLadj_neg, MH_{s}_{k}_pre_eq_{idx},",
                f"    MH_{s}_{k}_pim_eq_{idx}]",
                "",
            ]
        else:
            lines += [
                f"def MH_{s}_{k}_pre_{idx} : Polynomial ℚ := {g.lean_poly(pre)}",
                f"def MH_{s}_{k}_pim_{idx} : Polynomial ℚ := {g.lean_poly(pim)}",
                f"theorem MH_{s}_{k}_pre_eq_{idx} :",
                f"    MH_{s}_{k}_rawpre_{idx} = MH_{s}_{k}_pre_{idx} := rfl",
                f"theorem MH_{s}_{k}_pim_eq_{idx} :",
                f"    MH_{s}_{k}_rawpim_{idx} = MH_{s}_{k}_pim_{idx} := rfl",
                f"theorem MH_{s}_{k}_term_{idx} :",
                f"    H_entry_{rA}_{cA} * H_entry_{rB}_{cB} =",
                f"      ofLadj MH_{s}_{k}_pre_{idx} MH_{s}_{k}_pim_{idx} :=",
                f"  MH_{s}_{k}_raw_{idx}",
                "",
            ]

    n = len(term_data)
    pad_n = pad_to_adder(n)
    re_named = " + ".join(
        [f"MH_{s}_{k}_pre_{idx}" for idx in range(n)]
        + ["(0 : Polynomial ℚ)"] * (pad_n - n)
    )
    im_named = " + ".join(
        [f"MH_{s}_{k}_pim_{idx}" for idx in range(n)]
        + ["(0 : Polynomial ℚ)"] * (pad_n - n)
    )
    unfold_pre = ", ".join(f"MH_{s}_{k}_pre_{idx}" for idx in range(n))
    unfold_pim = ", ".join(f"MH_{s}_{k}_pim_{idx}" for idx in range(n))
    adder = ADDER[pad_n]
    add_args = []
    for idx in range(n):
        add_args += [f"MH_{s}_{k}_pre_{idx}", f"MH_{s}_{k}_pim_{idx}"]
    for _ in range(pad_n - n):
        add_args += ["(0 : Polynomial ℚ)", "(0 : Polynomial ℚ)"]
    signed_terms = []
    for idx, (rA, cA, rB, cB, sgn, _, _) in enumerate(term_data):
        prod = f"H_entry_{rA}_{cA} * H_entry_{rB}_{cB}"
        signed_terms.append(f"-({prod})" if sgn < 0 else prod)
    term_sum = " + ".join(signed_terms)
    term_thms = ", ".join(f"MH_{s}_{k}_term_{idx}" for idx in range(n))
    of_sum = " + ".join(
        [f"ofLadj MH_{s}_{k}_pre_{idx} MH_{s}_{k}_pim_{idx}" for idx in range(n)]
        + ["ofLadj 0 0"] * (pad_n - n)
    )
    lines += [
        f"theorem MH_{s}_{k}_sum_poly_re :",
        f"    {re_named} = minorQ_re_{s}_{k} + Phi11 * MH_{s}_{k}_qre := by",
        "  refine Polynomial.funext fun r => ?_",
        "  rw [Phi11_expand]",
        f"  simp only [{unfold_pre}, minorQ_re_{s}_{k}, MH_{s}_{k}_qre]",
        "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
        "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
        "    Polynomial.eval_neg, Polynomial.eval_zero, Polynomial.eval_one]",
        "  try ring",
        "",
        f"theorem MH_{s}_{k}_sum_poly_im :",
        f"    {im_named} = minorQ_im_{s}_{k} + Phi11 * MH_{s}_{k}_qim := by",
        "  refine Polynomial.funext fun r => ?_",
        "  rw [Phi11_expand]",
        f"  simp only [{unfold_pim}, minorQ_im_{s}_{k}, MH_{s}_{k}_qim]",
        "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
        "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
        "    Polynomial.eval_neg, Polynomial.eval_zero, Polynomial.eval_one]",
        "  try ring",
        "",
        f"theorem MH_{s}_{k}_sum_entries :",
        f"    {term_sum} = ofLadj ({re_named}) ({im_named}) := by",
        f"  have hpad : {term_sum} = {of_sum} := by",
        f"    simp only [{term_thms}]",
    ]
    if pad_n > n:
        lines.append("    simp [ofLadj_zero]")
    else:
        lines.append("    rfl")
    if n == 1 and pad_n == 1:
        # overwrite with simpler proof
        lines[-6:] = [
            f"theorem MH_{s}_{k}_sum_entries :",
            f"    {term_sum} = ofLadj ({re_named}) ({im_named}) := MH_{s}_{k}_term_0",
            "",
        ]
    else:
        lines += [
            f"  refine hpad.trans ?_",
            f"  simpa [add_assoc] using {adder} " + " ".join(add_args),
            "",
        ]
    lines += [
        f"theorem MH_{s}_{k}_eval :",
        f"    ofLadj ({re_named}) ({im_named}) = minorQ_entry_{s}_{k} := by",
        f"  rw [MH_{s}_{k}_sum_poly_re, MH_{s}_{k}_sum_poly_im, ofLadj_add_Phi11,",
        f"    minorQ_entry_{s}_{k}]",
        "",
        f"theorem MH_{s}_{k} : minorCoeffsH {s} {k} = minorQ {s} {k} := by",
        "  simp [minorCoeffsH, minorOrder, bilinearCoeffs, monomPair, Hrow,",
        "    crossIndex, Pi.sub_apply]",
        f"  rw [H_apply_{r00}_{p}, H_apply_{r11}_{q}]" if p != q else
        f"  rw [H_apply_{r00}_{p}, H_apply_{r11}_{p}]",
    ]
    # The simp of bilinearCoeffs is delicate. Instead prove a computational
    # unfolding in a dedicated lemma per (s,k) by reducing both sides to H products.
    # We replace the last theorem with a more explicit proof below.
    # Remove the incomplete last theorem and write a clearer one.
    del lines[-6:]
    lines += [
        f"theorem MH_{s}_{k} :",
        f"    minorQ_entry_{s}_{k} = {term_sum} :=",
        f"  (MH_{s}_{k}_eval).symm.trans (MH_{s}_{k}_sum_entries).symm",
        "",
        f"theorem MH_{s}_{k}_eq :",
        f"    minorQ ({s} : Fin 9) ({k} : Fin 21) = minorQ_entry_{s}_{k} :=",
        f"  minorQ_apply_{s}_{k}",
        "",
    ]
    lines += footer()
    return lines


def matmul(A, B):
    rows = len(A)
    mid = len(B)
    cols = len(B[0])
    out = []
    for i in range(rows):
        row = []
        for j in range(cols):
            acc_re, acc_im = [], []
            for t in range(mid):
                pre, pim = g.lmul_raw(A[i][t], B[t][j])
                acc_re = g.add(acc_re, pre)
                acc_im = g.add(acc_im, pim)
            row.append((acc_re, acc_im))
        out.append(row)
    return out


def eq_mod_phi(x, y) -> bool:
    return g.reduce_phi(x[0]) == g.reduce_phi(y[0]) and g.reduce_phi(x[1]) == g.reduce_phi(y[1])


