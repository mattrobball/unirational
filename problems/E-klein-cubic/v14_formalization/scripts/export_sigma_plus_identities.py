#!/usr/bin/env python3
"""Emit bounded L*H and N*H Lean identities with Φ11 quotient witnesses.

Writes only under --out-dir.  Each matrix entry is a separate Lean file so
the stock heartbeat budget is never asked to unfold a full 6×6 product.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JSON_PATH = ROOT / "results" / "sigma_plus_segre_Ki.json"
PHI = [Fraction(1)] * 11


def trim(a):
    a = list(a)
    while a and a[-1] == 0:
        a.pop()
    return a


def add(a, b):
    n = max(len(a), len(b))
    return trim([(a[i] if i < len(a) else 0) + (b[i] if i < len(b) else 0)
                 for i in range(n)])


def neg(a):
    return [-x for x in a]


def sub(a, b):
    return add(a, neg(b))


def mul(a, b):
    if not a or not b:
        return []
    out = [Fraction(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return trim(out)


def divmod_phi(a):
    """Return (q, r) with a = q * Φ11 + r and deg r < 10."""
    aa = [Fraction(x) for x in a] + [Fraction(0)] * 12
    q = [Fraction(0)] * max(1, len(aa) - 10)
    for n in range(len(aa) - 1, 9, -1):
        c = aa[n]
        if c:
            q[n - 10] += c
            aa[n] = 0
            for j in range(n - 10, n):
                aa[j] -= c
    rem = (aa[:10] + [Fraction(0)] * 10)[:10]
    recon = add(mul(trim(q), PHI), rem)
    orig = trim([Fraction(x) for x in a])
    if recon != orig:
        raise SystemExit(f"Φ11 division failed: {orig} vs {recon}")
    return trim(q), rem


def reduce_phi(a):
    return divmod_phi(a)[1]


def kdec(x):
    return [Fraction(int(a), int(b)) for a, b in x]


def ldec(cell):
    return kdec(cell["re"]), kdec(cell["im"])


def lmul_raw(x, y):
    a, b = x
    c, d = y
    return (sub(mul(a, c), mul(b, d)), add(mul(a, d), mul(b, c)))


def lmat(rows):
    return [[ldec(c) for c in r] for r in rows]


def lean_rat(x: Fraction) -> str:
    if x.denominator == 1:
        return str(x.numerator)
    return f"({x.numerator} / {x.denominator} : ℚ)"


def lean_poly(a) -> str:
    terms = []
    for i, c in enumerate(trim(list(a))):
        if not c:
            continue
        if i == 0:
            terms.append(f"C ({lean_rat(c)})")
        elif i == 1:
            terms.append(f"C ({lean_rat(c)}) * X")
        else:
            terms.append(f"C ({lean_rat(c)}) * X ^ {i}")
    return " + ".join(terms) if terms else "(0 : Polynomial ℚ)"


def header_import(extra_imports=None) -> list[str]:
    extras = extra_imports or []
    return [
        "/-",
        "Auto-generated by scripts/export_sigma_plus_identities.py.",
        "Stock-limit, kernel-checkable plus Segre entry identities.",
        "-/",
        "import V14Formalization.D12SigmaPlusSegreEval",
        *extras,
        "",
        "noncomputable section",
        "open Matrix Polynomial",
        "namespace V14Formalization.D12SigmaPlusSegreCore",
        "open D12PolynomialData",
        "",
    ]


def footer() -> list[str]:
    return [
        "end V14Formalization.D12SigmaPlusSegreCore",
        "",
    ]


def emit_apply(name: str, rows: int, cols: int) -> list[str]:
    lines = header_import()
    for i in range(rows):
        for j in range(cols):
            lines += [
                f"theorem {name}_apply_{i}_{j} :",
                f"    {name} ({i} : Fin {rows}) ({j} : Fin {cols}) = {name}_entry_{i}_{j} := by",
                f"  unfold {name}",
                "  simp [Matrix.of_apply]",
                "",
            ]
    lines += footer()
    return lines


def emit_entry(prefix: str, A: str, B: str, i: int, j: int, kmax: int,
               terms, q_re, q_im, target_re, target_im, want_one: bool,
               mul_lemma: str | None = None) -> list[str]:
    extra = [
        f"import V14Formalization.D12SigmaPlusSegreApply{A}",
        f"import V14Formalization.D12SigmaPlusSegreApply{B}",
    ]
    lines = header_import(extra)
    rhs = "1" if want_one else "0"
    close = "ofLadj_one" if want_one else "ofLadj_zero"
    if mul_lemma is None:
        mul_lemma = "mul_apply_fin9" if A == "L" else "mul_apply_fin9_N"
    lines += [
        f"def {prefix}_qre_{i}_{j} : Polynomial ℚ := {lean_poly(q_re)}",
        f"def {prefix}_qim_{i}_{j} : Polynomial ℚ := {lean_poly(q_im)}",
        "",
    ]
    for t, (pre, pim) in enumerate(terms):
        lines += [
            f"def {prefix}_pre_{i}_{j}_{t} : Polynomial ℚ := {lean_poly(pre)}",
            f"def {prefix}_pim_{i}_{j}_{t} : Polynomial ℚ := {lean_poly(pim)}",
            f"theorem {prefix}_pre_eq_{i}_{j}_{t} :",
            f"    {A}_re_{i}_{t} * {B}_re_{t}_{j} - {A}_im_{i}_{t} * {B}_im_{t}_{j} =",
            f"      {prefix}_pre_{i}_{j}_{t} := by",
            "  refine Polynomial.funext fun r => ?_",
            f"  simp only [{A}_re_{i}_{t}, {A}_im_{i}_{t}, {B}_re_{t}_{j}, {B}_im_{t}_{j},",
            f"    {prefix}_pre_{i}_{j}_{t}]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try grind",
            f"theorem {prefix}_pim_eq_{i}_{j}_{t} :",
            f"    {A}_re_{i}_{t} * {B}_im_{t}_{j} + {A}_im_{i}_{t} * {B}_re_{t}_{j} =",
            f"      {prefix}_pim_{i}_{j}_{t} := by",
            "  refine Polynomial.funext fun r => ?_",
            f"  simp only [{A}_re_{i}_{t}, {A}_im_{i}_{t}, {B}_re_{t}_{j}, {B}_im_{t}_{j},",
            f"    {prefix}_pim_{i}_{j}_{t}]",
            "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
            "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
            "    Polynomial.eval_neg, Polynomial.eval_zero]",
            "  try grind",
            f"theorem {prefix}_term_{i}_{j}_{t} :",
            f"    {A}_entry_{i}_{t} * {B}_entry_{t}_{j} =",
            f"      ofLadj {prefix}_pre_{i}_{j}_{t} {prefix}_pim_{i}_{j}_{t} := by",
            f"  rw [{A}_entry_{i}_{t}, {B}_entry_{t}_{j}, ofLadj_mul,",
            f"    {prefix}_pre_eq_{i}_{j}_{t}, {prefix}_pim_eq_{i}_{j}_{t}]",
            "",
        ]
    re_named = " + ".join(f"{prefix}_pre_{i}_{j}_{t}" for t in range(kmax))
    im_named = " + ".join(f"{prefix}_pim_{i}_{j}_{t}" for t in range(kmax))
    unfold_pre = ", ".join(f"{prefix}_pre_{i}_{j}_{t}" for t in range(kmax))
    unfold_pim = ", ".join(f"{prefix}_pim_{i}_{j}_{t}" for t in range(kmax))
    term_sum = " + ".join(f"{A}_entry_{i}_{t} * {B}_entry_{t}_{j}" for t in range(kmax))
    term_thms = ", ".join(f"{prefix}_term_{i}_{j}_{t}" for t in range(kmax))
    tgt_re = "1" if want_one else "0"
    tgt_im = "0"
    lines += [
        f"theorem {prefix}_sum_poly_re_{i}_{j} :",
        f"    {re_named} = ({tgt_re} : Polynomial ℚ) + Phi11 * {prefix}_qre_{i}_{j} := by",
        "  refine Polynomial.funext fun r => ?_",
        f"  rw [Phi11_expand]",
        f"  simp only [{unfold_pre}, {prefix}_qre_{i}_{j}]",
        "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
        "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
        "    Polynomial.eval_neg, Polynomial.eval_zero, Polynomial.eval_one]",
        "  try grind",
        "",
        f"theorem {prefix}_sum_poly_im_{i}_{j} :",
        f"    {im_named} = ({tgt_im} : Polynomial ℚ) + Phi11 * {prefix}_qim_{i}_{j} := by",
        "  refine Polynomial.funext fun r => ?_",
        f"  rw [Phi11_expand]",
        f"  simp only [{unfold_pim}, {prefix}_qim_{i}_{j}]",
        "  simp [Polynomial.eval_add, Polynomial.eval_sub, Polynomial.eval_mul,",
        "    Polynomial.eval_C, Polynomial.eval_X, Polynomial.eval_pow,",
        "    Polynomial.eval_neg, Polynomial.eval_zero, Polynomial.eval_one]",
        "  try grind",
        "",
        f"theorem {prefix}_sum_entries_{i}_{j} :",
        f"    {term_sum} =",
        f"      ofLadj ({re_named}) ({im_named}) := by",
        f"  simp only [{term_thms}]",
        "  simpa [add_assoc] using ofLadj_add9",
    ]
    args = []
    for t in range(kmax):
        args.append(f"{prefix}_pre_{i}_{j}_{t}")
        args.append(f"{prefix}_pim_{i}_{j}_{t}")
    lines[-1] += " " + " ".join(args)
    lines += [
        "",
        f"theorem {prefix}_eval_{i}_{j} :",
        f"    ofLadj ({re_named}) ({im_named}) = {rhs} := by",
        f"  rw [{prefix}_sum_poly_re_{i}_{j}, {prefix}_sum_poly_im_{i}_{j}, ofLadj_add_Phi11]",
        f"  exact {close}",
        "",
        f"theorem {prefix}_entry_{i}_{j} : ({A} * {B}) {i} {j} = {rhs} := by",
        f"  rw [{mul_lemma}]",
    ]
    for t in range(kmax):
        lines.append(f"  rw [{A}_apply_{i}_{t}, {B}_apply_{t}_{j}]")
    lines += [
        f"  exact ({prefix}_sum_entries_{i}_{j}).trans {prefix}_eval_{i}_{j}",
        "",
    ]
    lines += footer()
    return lines


def emit_aggregate(lh_pairs, nh_pairs) -> list[str]:
    lines = [
        "/-",
        "Auto-generated plus Segre aggregate identities.",
        "-/",
    ]
    for i, j in lh_pairs:
        lines.append(f"import V14Formalization.D12SigmaPlusSegreLH_{i}_{j}")
    for i, j in nh_pairs:
        lines.append(f"import V14Formalization.D12SigmaPlusSegreNH_{i}_{j}")
    lines += [
        "",
        "noncomputable section",
        "open Matrix",
        "namespace V14Formalization.D12SigmaPlusSegreData",
        "open D12SigmaPlusSegreCore",
        "",
        "theorem L_mul_H : L * H = 1 := by",
        "  ext i j",
        "  fin_cases i <;> fin_cases j",
    ]
    for i, j in lh_pairs:
        lines.append(f"  · exact LH_entry_{i}_{j}")
    lines += [
        "",
        "theorem N_mul_H : N * H = 0 := by",
        "  ext i j",
        "  fin_cases i <;> fin_cases j",
    ]
    for i, j in nh_pairs:
        lines.append(f"  · exact NH_entry_{i}_{j}")
    lines += [
        "",
        "end V14Formalization.D12SigmaPlusSegreData",
        "",
    ]
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--only", type=str, default="",
                        help="optional 'LH_i_j' or 'NH_i_j' or 'apply'")
    args = parser.parse_args()
    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    data = json.loads(JSON_PATH.read_text())
    H = lmat(data["cross_coordinate_H_9x6"])
    L = lmat(data["left_inverse_L_6x9"])
    N = lmat(data["annihilator_N_3x9"])

    only = args.only

    if only in ("", "apply"):
        (out / "D12SigmaPlusSegreApplyH.lean").write_text(
            "\n".join(emit_apply("H", 9, 6)))
        (out / "D12SigmaPlusSegreApplyL.lean").write_text(
            "\n".join(emit_apply("L", 6, 9)))
        (out / "D12SigmaPlusSegreApplyN.lean").write_text(
            "\n".join(emit_apply("N", 3, 9)))
        print("wrote apply modules")

    lh_pairs = []
    for i in range(6):
        for j in range(6):
            acc_re = []
            acc_im = []
            terms = []
            for t in range(9):
                pre, pim = lmul_raw(L[i][t], H[t][j])
                terms.append((pre, pim))
                acc_re = add(acc_re, pre)
                acc_im = add(acc_im, pim)
            qre, rre = divmod_phi(acc_re)
            qim, rim = divmod_phi(acc_im)
            want = ([Fraction(1)] + [Fraction(0)] * 9, [Fraction(0)] * 10) if i == j else (
                [Fraction(0)] * 10, [Fraction(0)] * 10)
            if rre != want[0] or rim != want[1]:
                raise SystemExit(f"L*H remainder failed at {i},{j}: {rre}, {rim}")
            lh_pairs.append((i, j))
            tag = f"LH_{i}_{j}"
            if only in ("", tag, f"LH_{i}_{j}"):
                path = out / f"D12SigmaPlusSegreLH_{i}_{j}.lean"
                path.write_text("\n".join(emit_entry(
                    "LH", "L", "H", i, j, 9, terms, qre, qim, rre, rim, i == j)))
                print("wrote", path.name)

    nh_pairs = []
    for i in range(3):
        for j in range(6):
            acc_re = []
            acc_im = []
            terms = []
            for t in range(9):
                pre, pim = lmul_raw(N[i][t], H[t][j])
                terms.append((pre, pim))
                acc_re = add(acc_re, pre)
                acc_im = add(acc_im, pim)
            qre, rre = divmod_phi(acc_re)
            qim, rim = divmod_phi(acc_im)
            if rre != [Fraction(0)] * 10 or rim != [Fraction(0)] * 10:
                raise SystemExit(f"N*H remainder failed at {i},{j}: {rre}, {rim}")
            nh_pairs.append((i, j))
            tag = f"NH_{i}_{j}"
            if only in ("", tag, f"NH_{i}_{j}"):
                path = out / f"D12SigmaPlusSegreNH_{i}_{j}.lean"
                path.write_text("\n".join(emit_entry(
                    "NH", "N", "H", i, j, 9, terms, qre, qim, rre, rim, False)))
                print("wrote", path.name)

    if only == "":
        path = out / "D12SigmaPlusSegreData.lean"
        path.write_text("\n".join(emit_aggregate(lh_pairs, nh_pairs)))
        print("wrote", path.name)
    print("json_sha", hashlib.sha256(JSON_PATH.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
    __import__("sys").path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__)))
    from module_annotation_hook import reapply_module_annotations
    reapply_module_annotations()
