#!/usr/bin/env python3
"""Emit ten bounded nonvanishing certificates for row zero of the restricted S action.

Each source entry is reduced by its X^10 coefficient times Phi11.  The reduced
polynomial is visibly nonzero and has degree below 10, so its image in
AdjoinRoot(Phi11) is nonzero.  This avoids a large polynomial Bezout
normalization in Lean.
"""

from __future__ import annotations

import argparse
from fractions import Fraction as F
from pathlib import Path

import export_d12_generator_relations_lean as base

ROOT = Path(__file__).resolve().parents[1]
OUT_ROOT = ROOT / "V14Formalization"
MODULE = "D12GeneratorSRow0Nonzero"
PHI11 = [F(1)] * 11


def lean_rat(q: F) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : ℚ)"
    return f"({q.numerator} / {q.denominator} : ℚ)"


def emit(out_root: Path) -> Path:
    phase = base.phase_matrix()
    products = base.matmul(base.compound(phase), base.expected_b())[0]
    certs = []
    eval_names = []
    for j, p in enumerate(products):
        top = p[10] if len(p) > 10 else F(0)
        reduced = base.sub(p, base.scale(top, PHI11))
        if not reduced or len(reduced) > 10:
            raise SystemExit(f"bad degree reduction at row-zero entry {j}")
        witness = next(i for i, c in enumerate(reduced) if c)
        certs.append(f"""def phaseValue_{j} : Polynomial ℚ := {base.lean_poly(p)}

def reducedValue_{j} : Polynomial ℚ :=
  phaseValue_{j} - C {lean_rat(top)} * Phi11

theorem phaseValue_eq_{j} :
    (PluckerNaturality.compound2Lex S6Phase_poly * B_poly) 0 {j} =
      phaseValue_{j} :=
  D12GeneratorSPhaseRow13.source_phase_product_0_{j}

theorem phaseValue_reduction_{j} :
    phaseValue_{j} = reducedValue_{j} + C {lean_rat(top)} * Phi11 := by
  simp [reducedValue_{j}]

theorem reducedValue_{j}_ne_zero : reducedValue_{j} ≠ 0 := by
  intro hzero
  have hc := congrArg (fun p : Polynomial ℚ => p.coeff {witness}) hzero
  norm_num [reducedValue_{j}, phaseValue_{j}, Phi11,
    Finset.sum_range_succ, coeff_one] at hc

theorem reducedValue_{j}_natDegree_lt :
    reducedValue_{j}.natDegree < WeilRep.Φ11.natDegree := by
  rw [WeilRep.Φ11_natDegree]
  have hle : reducedValue_{j}.natDegree ≤ 9 :=
      natDegree_le_iff_coeff_eq_zero.mpr (by
    intro n hn
    by_cases h10 : n = 10
    · subst n
      norm_num [reducedValue_{j}, phaseValue_{j}, Phi11,
        Finset.sum_range_succ, coeff_X, coeff_one]
    have h0 : n ≠ 0 := by omega
    have h1 : n ≠ 1 := by omega
    have h2 : n ≠ 2 := by omega
    have h3 : n ≠ 3 := by omega
    have h4 : n ≠ 4 := by omega
    have h5 : n ≠ 5 := by omega
    have h6 : n ≠ 6 := by omega
    have h7 : n ≠ 7 := by omega
    have h8 : n ≠ 8 := by omega
    have h9 : n ≠ 9 := by omega
    simp [reducedValue_{j}, phaseValue_{j}, Phi11,
      Finset.sum_range_succ, h0, h1, h2, h3, h4, h5, h6, h7, h8,
      h9, h10, coeff_C, coeff_X, coeff_one])
  omega

theorem eval_phaseValue_{j}_ne_zero :
    D12PolynomialEvaluation.evalPolyAt WeilRep.ζ phaseValue_{j} ≠ 0 := by
  rw [phaseValue_reduction_{j}, map_add, map_mul,
    D12U6PolynomialSeal.evalPhi11_ζ, mul_zero, add_zero]
  change aeval WeilRep.ζ reducedValue_{j} ≠ 0
  intro hzero
  apply AdjoinRoot.mk_ne_zero_of_natDegree_lt WeilRep.Φ11_monic
    reducedValue_{j}_ne_zero reducedValue_{j}_natDegree_lt
  rw [← AdjoinRoot.aeval_eq (f := WeilRep.Φ11) reducedValue_{j}]
  exact hzero

theorem eval_source_phase_product_0_{j}_ne_zero :
    D12PolynomialEvaluation.evalPolyAt WeilRep.ζ
      ((PluckerNaturality.compound2Lex S6Phase_poly * B_poly) 0 {j}) ≠ 0 := by
  rw [phaseValue_eq_{j}]
  exact eval_phaseValue_{j}_ne_zero
""")
        eval_names.append(f"eval_source_phase_product_0_{j}_ne_zero")

    dispatcher = "\n".join(
        f"  | ⟨{j}, _⟩ => {name}" for j, name in enumerate(eval_names)
    )
    text = f"""/-
  Bounded nonvanishing certificates for row zero of the restricted Fourier
  generator.  Auto-generated by scripts/export_d12_s_row0_nonzero_lean.py.
  Stock limits; no evaluator escape.
-/
import V14Formalization.D12GeneratorInvariance

noncomputable section

open Matrix Polynomial

namespace V14Formalization.{MODULE}

open D12PolynomialData D12PolynomialEvaluation
open D12GeneratorPolynomialCore D12GeneratorInvariance

{''.join(certs)}

theorem eval_source_phase_product_row0_ne_zero (j : Fin 10) :
    evalPolyAt WeilRep.ζ
      ((PluckerNaturality.compound2Lex S6Phase_poly * B_poly) 0 j) ≠ 0 :=
  match j with
{dispatcher}

theorem cFourier_ne_zero : WeilRep.cFourier ≠ 0 := by
  intro hzero
  have h := WeilRep.cFourier_sq_mul_eleven
  rw [hzero, zero_pow (by decide), zero_mul] at h
  have hneg : (-1 : WeilRep.K) ≠ 0 := by norm_num
  exact hneg h.symm

theorem SrestrictedAction_row0_ne_zero (j : Fin 10) :
    SrestrictedAction 0 j ≠ 0 := by
  change evalPolyAt WeilRep.ζ
      ((PluckerNaturality.compound2Lex S6_poly * B_poly) 0 j) ≠ 0
  rw [congrArg (fun M : Matrix (Fin 15) (Fin 10) (Polynomial ℚ) => M 0 j)
    compound_S6_mul_B_factor]
  simp only [Matrix.smul_apply, smul_eq_mul, map_mul,
    D12U6Semantic.eval_cFourierPoly]
  exact mul_ne_zero (mul_ne_zero cFourier_ne_zero cFourier_ne_zero)
    (eval_source_phase_product_row0_ne_zero j)

end V14Formalization.{MODULE}
"""
    out_root.mkdir(parents=True, exist_ok=True)
    path = out_root / f"{MODULE}.lean"
    path.write_text(text)
    return path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, default=OUT_ROOT)
    args = parser.parse_args()
    path = emit(args.out_dir)
    print(f"wrote {path} ({path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
    __import__("sys").path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__)))
    from module_annotation_hook import reapply_module_annotations
    reapply_module_annotations()
