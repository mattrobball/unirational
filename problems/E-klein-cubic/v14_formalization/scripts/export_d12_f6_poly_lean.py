#!/usr/bin/env python3
"""Export the bounded polynomial seal for the six-dimensional D12 reflection.

The output contains 36 independent certificates

    directEntryPoly(i,j) - F6(i,j) = Phi11 * q(i,j)

over Q[X].  Exact rational polynomial division is performed before any Lean
source is emitted, and generation fails closed on a nonzero remainder.

An optional first argument redirects the generated Lean file for deterministic
replay audits.
"""
from __future__ import annotations

import hashlib
import json
import sys
from fractions import Fraction
from pathlib import Path
from typing import Iterable, List, Sequence

ROOT = Path(__file__).resolve().parents[1]
JSON_PATH = ROOT / "results" / "d12_lean_K.json"
DEFAULT_OUTPUT = ROOT / "V14Formalization" / "D12F6PolynomialData.lean"
SCHEMA = "v14.d12.f6.polynomial.v1"

Poly = List[Fraction]


def trim(p: Iterable[Fraction]) -> Poly:
    out = list(p)
    while out and out[-1] == 0:
        out.pop()
    return out


def add(a: Sequence[Fraction], b: Sequence[Fraction]) -> Poly:
    n = max(len(a), len(b))
    return trim(
        (a[i] if i < len(a) else 0) + (b[i] if i < len(b) else 0)
        for i in range(n)
    )


def sub(a: Sequence[Fraction], b: Sequence[Fraction]) -> Poly:
    return add(a, [-x for x in b])


def mul(a: Sequence[Fraction], b: Sequence[Fraction]) -> Poly:
    if not a or not b:
        return []
    out = [Fraction(0) for _ in range(len(a) + len(b) - 1)]
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return trim(out)


def power(a: Sequence[Fraction], n: int) -> Poly:
    out = [Fraction(1)]
    for _ in range(n):
        out = mul(out, a)
    return out


def monomial(n: int) -> Poly:
    return [Fraction(0)] * n + [Fraction(1)]


def divide_exact(a: Sequence[Fraction], b: Sequence[Fraction]) -> Poly:
    remainder = trim(a)
    quotient = [Fraction(0)] * max(0, len(remainder) - len(b) + 1)
    while len(remainder) >= len(b):
        k = len(remainder) - len(b)
        coefficient = remainder[-1] / b[-1]
        quotient[k] += coefficient
        remainder = sub(
            remainder,
            [Fraction(0)] * k + [coefficient * x for x in b],
        )
    if remainder:
        raise ValueError(f"nonzero Phi11 remainder: {remainder}")
    return trim(quotient)


def rat(x: Fraction) -> str:
    if x.denominator == 1:
        return str(x.numerator)
    return f"({x.numerator} / {x.denominator} : ℚ)"


def vector(p: Sequence[Fraction], n: int) -> str:
    padded = list(p) + [Fraction(0)] * (n - len(p))
    return "![" + ", ".join(rat(x) for x in padded[:n]) + "]"


def z11(n: int) -> int:
    return n % 11


C_FOURIER = [
    Fraction(-1, 11), Fraction(-2, 11), 0, Fraction(-2, 11),
    Fraction(-2, 11), Fraction(-2, 11), 0, 0, 0, Fraction(-2, 11),
]


def direct_entry(i: int, j: int) -> Poly:
    result = mul([-x for x in C_FOURIER], monomial(z11(2 * i * i)))
    if j == 0:
        return result
    symmetric = add(monomial(z11(4 * i * j)), monomial(z11(-4 * i * j)))
    return mul(result, mul(monomial(z11(9 * j * j)), symmetric))


def emit(output: Path) -> None:
    raw_json = JSON_PATH.read_bytes()
    data = json.loads(raw_json)
    f6 = [
        [[Fraction(n, d) for n, d in entry] for entry in row]
        for row in data["operators"]["F6x6"]
    ]
    if len(f6) != 6 or any(len(row) != 6 for row in f6):
        raise ValueError("operators.F6x6 is not 6 by 6")
    if any(len(entry) > 10 for row in f6 for entry in row):
        raise ValueError("an F6 entry exceeds the degree-9 power basis")
    if data["group_bridge"]["F6_word"] != "TTTTSTTTTTTTS":
        raise ValueError("unexpected group_bridge.F6_word")

    phi11 = [Fraction(1)] * 11
    targets = [[direct_entry(i, j) for j in range(6)] for i in range(6)]
    quotients = [
        [divide_exact(sub(targets[i][j], f6[i][j]), phi11)
         for j in range(6)]
        for i in range(6)
    ]
    quotient_size = max(len(q) for row in quotients for q in row)
    source_sha = hashlib.sha256(raw_json).hexdigest()
    payload_bytes = json.dumps(
        {
            "F6x6": data["operators"]["F6x6"],
            "F6_word": data["group_bridge"]["F6_word"],
        },
        separators=(",", ":"),
        sort_keys=True,
    ).encode()
    payload_sha = hashlib.sha256(payload_bytes).hexdigest()

    lines: List[str] = []
    append = lines.append
    append("/-")
    append("  D12 six-dimensional reflection polynomial seal data.")
    append("  Auto-generated by scripts/export_d12_f6_poly_lean.py.")
    append("  DO NOT HAND-EDIT.")
    append(f"  Schema: {SCHEMA}")
    append(f"  Source JSON sha256: {source_sha}")
    append(f"  F6 word/payload sha256: {payload_sha}")
    append("-/")
    append("import V14Formalization.D12F6Semantic")
    append("")
    append("noncomputable section")
    append("open Polynomial Matrix BigOperators")
    append("namespace V14Formalization.D12F6PolynomialData")
    append("open D12PolynomialData D12U6Semantic D12F6Semantic")
    append("")
    append(f"abbrev QuotCoeff := Fin {quotient_size} → ℚ")
    append("def ofQuot (c : QuotCoeff) : Polynomial ℚ :=")
    append(f"  ∑ i : Fin {quotient_size}, C (c i) * X ^ i.val")
    append("")
    for n in range(11):
        append(
            f"private theorem zval_{n} : "
            f"ZMod.val ({n} : ZMod 11) = {n} := by decide"
        )
    append("")
    for n in (2, 3, 4):
        append(f"private theorem C_{n}_over_11 :")
        append(
            f"    C ({n} / 11 : ℚ) = "
            f"({n} : Polynomial ℚ) * C (1 / 11 : ℚ) := by"
        )
        append(
            f"  rw [show ({n} : Polynomial ℚ) = C {n} by "
            f"exact (map_natCast C {n}).symm, ← map_mul]"
        )
        append("  norm_num")
    append("")
    for i in range(6):
        for j in range(6):
            append(
                f"def F6c_{i}_{j} : Polynomial ℚ := "
                f"D12PolynomialData.of10 {vector(f6[i][j], 10)}"
            )
    append("")
    append("def F6_poly : Matrix (Fin 6) (Fin 6) (Polynomial ℚ) := ![")
    for i in range(6):
        suffix = "," if i < 5 else ""
        append(
            "  ![" + ", ".join(f"F6c_{i}_{j}" for j in range(6)) + "]" + suffix
        )
    append("]")
    append("")
    for i in range(6):
        for j in range(6):
            append(
                f"def quotient_{i}_{j} : Polynomial ℚ := "
                f"ofQuot {vector(quotients[i][j], quotient_size)}"
            )
    append("")
    for i in range(6):
        for j in range(6):
            a = z11(2 * i * i)
            if j == 0:
                rhs = f"-cFourierPoly * X ^ {a}"
            else:
                b = z11(9 * j * j)
                c = z11(4 * i * j)
                d = z11(-4 * i * j)
                rhs = (
                    f"-cFourierPoly * X ^ {a} * "
                    f"(X ^ {b} * (X ^ {c} + X ^ {d}))"
                )
            append(f"theorem direct_expanded_{i}_{j} :")
            append(
                f"    D12F6Semantic.directEntryPoly ({i} : Fin 6) "
                f"({j} : Fin 6) = {rhs} := by"
            )
            append(
                f"  have ha : ZMod.val "
                f"(2 * (({i} : Fin 6).val : ZMod 11) ^ 2) = {a} := by decide"
            )
            if j == 0:
                append("  unfold D12F6Semantic.directEntryPoly phasePoly")
                append("  rw [ha, if_pos rfl]")
                append("  simp")
            else:
                append(
                    f"  have hb : ZMod.val "
                    f"(9 * (({j} : Fin 6).val : ZMod 11) ^ 2) = {b} := by decide"
                )
                append(
                    f"  have hc : ZMod.val (4 * (({i} : Fin 6).val : ZMod 11) * "
                    f"(({j} : Fin 6).val : ZMod 11)) = {c} := by decide"
                )
                append(
                    f"  have hd : ZMod.val (-(4 * (({i} : Fin 6).val : ZMod 11) * "
                    f"(({j} : Fin 6).val : ZMod 11))) = {d} := by decide"
                )
                append("  unfold D12F6Semantic.directEntryPoly phasePoly")
                append("  simp only [ha, hb, hc, hd]")
                append(f"  rw [if_neg (by decide : ({j} : Fin 6) ≠ 0)]")
            append("")
            append(f"theorem direct_sub_F6_{i}_{j} :")
            append(f"    D12F6Semantic.directEntryPoly ({i} : Fin 6) "
                   f"({j} : Fin 6) -")
            append(f"      F6c_{i}_{j} = Phi11 * quotient_{i}_{j} := by")
            append(f"  rw [direct_expanded_{i}_{j}]")
            append("  norm_num [cFourierPoly,")
            append(
                f"    F6c_{i}_{j}, quotient_{i}_{j}, ofQuot, "
                "D12PolynomialData.of10, Phi11,"
            )
            append("    Fin.sum_univ_succ, Finset.sum_range_succ,")
            append("    zval_0, zval_1, zval_2, zval_3, zval_4, zval_5,")
            append("    zval_6, zval_7, zval_8, zval_9, zval_10] <;>")
            append("    simp only [C_2_over_11, C_3_over_11, C_4_over_11] <;>")
            append("      ring")
    append("")
    append("end V14Formalization.D12F6PolynomialData")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {output} ({output.stat().st_size} bytes, {len(lines)} lines)")
    print(f"SCHEMA={SCHEMA}")
    print(f"SOURCE_SHA256={source_sha}")
    print(f"F6_WORD_PAYLOAD_SHA256={payload_sha}")
    print(f"QUOTIENT_SIZE={quotient_size}")


def main(argv: Sequence[str]) -> int:
    if len(argv) > 2:
        raise SystemExit(f"usage: {argv[0]} [OUTPUT.lean]")
    output = Path(argv[1]).resolve() if len(argv) == 2 else DEFAULT_OUTPUT
    output.parent.mkdir(parents=True, exist_ok=True)
    emit(output)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
