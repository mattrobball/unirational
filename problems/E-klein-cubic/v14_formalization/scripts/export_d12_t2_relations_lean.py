#!/usr/bin/env python3
"""Emit the bounded diagonal-generator relations for the D12 ten-space.

The compound of the diagonal six-dimensional generator is diagonal.  We
certify ten relevant rows separately, then assemble the five dependent-row
relations.  Only rows 12 and 13 need nonzero Phi11 quotient witnesses.
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_ROOT = ROOT / "V14Formalization"
MODULE = "D12GeneratorT2Relations"

PAIRS = [(i, j) for i in range(6) for j in range(i + 1, 6)]
ROWS = {
    5: (3, "(-1 / 2 : ℚ)", 3),
    8: (1, "(1 / 2 : ℚ)", 1),
    10: (2, "(-1 / 2 : ℚ)", 2),
    12: (4, "(1 / 2 : ℚ)", 4),
    13: (0, "(-1 / 2 : ℚ)", 0),
}
FREE_ROWS = [0, 1, 2, 3, 4, 6, 7, 9, 11, 14]
RELEVANT = sorted(set(FREE_ROWS) | set(ROWS) | {src for src, _, _ in ROWS.values()})


def exponent(row: int) -> int:
    a, b = PAIRS[row]
    return (a * a) % 11 + (b * b) % 11


def coefficient(row: int) -> str:
    for dep, (_, coeff, _) in ROWS.items():
        if row == dep:
            return coeff
    return "(1 : ℚ)"


def column(row: int) -> int:
    for dep, (_, _, col) in ROWS.items():
        if row == dep:
            return col
    return FREE_ROWS.index(row)


def quotient(row: int) -> str:
    if row == 12:
        return "C (1 / 2 : ℚ) * X ^ 4 + C (-1 / 2 : ℚ) * X ^ 3"
    if row == 13:
        return "C (-1 / 2 : ℚ) * X ^ 2 + C (1 / 2 : ℚ) * X"
    return "0"


def diagonal_row(row: int) -> str:
    a, b = PAIRS[row]
    ea, eb = (a * a) % 11, (b * b) % 11
    e = exponent(row)
    return f"""private theorem compound_row_{row} (j : Fin 15) :
    PluckerNaturality.compound2Lex T6_poly {row} j =
      if j = {row} then X ^ {e} else 0 := by
  fin_cases j <;>
    simp [compound2Lex_apply_pairLex, T6_poly,
      D12U6Semantic.phasePoly, PluckerNaturality.pairLexVec,
      show (({a} : ZMod 11) ^ 2).val = {ea} by decide,
      show (({b} : ZMod 11) ^ 2).val = {eb} by decide,
      show ({ea} : ZMod 11).val = {ea} by decide,
      show ({eb} : ZMod 11).val = {eb} by decide] <;>
    ring

theorem product_row_{row} (j : Fin 10) :
    (PluckerNaturality.compound2Lex T6_poly * B_poly) {row} j =
      if j = {column(row)} then C {coefficient(row)} * X ^ {e} else 0 := by
  rw [Matrix.mul_apply]
  simp_rw [compound_row_{row}]
  fin_cases j <;> simp [B_poly] <;> ring
"""


def relation(row: int) -> str:
    src, coeff, col = ROWS[row]
    q = quotient(row)
    return f"""def quotient_{row} : Polynomial ℚ := {q}

theorem relation_{row} (j : Fin 10) :
    (PluckerNaturality.compound2Lex T6_poly * B_poly) {row} j -
      C {coeff} *
        (PluckerNaturality.compound2Lex T6_poly * B_poly) {src} j =
      Phi11 * (if j = {col} then quotient_{row} else 0) := by
  rw [product_row_{row}, product_row_{src}]
  by_cases h : j = {col}
  · subst j
    simp only [if_pos, quotient_{row}, Phi11, Finset.sum_range_succ]
    ring_nf
    simp only [C_eq_smul_one, smul_mul_assoc, mul_smul_comm, one_mul,
      mul_one, smul_smul]
    module
  · simp [h]

theorem eval_relation_{row}
    {{R : Type*}} [CommRing R] [Algebra ℚ R]
    (z : R) (hPhi : D12PolynomialEvaluation.evalPolyAt z Phi11 = 0)
    (j : Fin 10) :
    D12PolynomialEvaluation.evalPolyAt z
        ((PluckerNaturality.compound2Lex T6_poly * B_poly) {row} j) =
      algebraMap ℚ R {coeff} *
        D12PolynomialEvaluation.evalPolyAt z
          ((PluckerNaturality.compound2Lex T6_poly * B_poly) {src} j) := by
  exact D12GeneratorPolynomialCore.eval_relation_of_modPhi z hPhi _ _ _
    {coeff} (relation_{row} j)
"""


def restricted_row(i: int, row: int) -> str:
    return f"""theorem restrictedAction_eval_row_{i}
    {{R : Type*}} [CommRing R] [Algebra ℚ R] (z : R) (j : Fin 10) :
    restrictedAction
        (D12PolynomialEvaluation.evalMatrixAt z
          (PluckerNaturality.compound2Lex T6_poly * B_poly)) {i} j =
      Matrix.diagonal (fun k => z ^ eigenExponent k) {i} j := by
  change D12PolynomialEvaluation.evalPolyAt z
      ((PluckerNaturality.compound2Lex T6_poly * B_poly) {row} j) = _
  rw [product_row_{row}]
  by_cases h : j = {i}
  · subst j
    simp [D12PolynomialEvaluation.evalPolyAt, eigenExponent]
  · rw [if_neg h, map_zero, Matrix.diagonal_apply_ne' _ h]
"""


def emit(out_root: Path) -> Path:
    rows = "\n".join(diagonal_row(row) for row in RELEVANT)
    relations = "\n".join(relation(row) for row in sorted(ROWS))
    exponent_vector = ", ".join(str(exponent(row)) for row in FREE_ROWS)
    restricted_rows = "\n".join(
        restricted_row(i, row) for i, row in enumerate(FREE_ROWS)
    )
    restricted_dispatch = "\n  ".join(
        f"· exact restrictedAction_eval_row_{i} z j" for i in range(10)
    )
    text = f"""/-
  Sparse diagonal standard-generator certificate.
  Auto-generated by scripts/export_d12_t2_relations_lean.py.
  Stock limits; no evaluator escape.
-/
import V14Formalization.D12GeneratorPolynomialCore

noncomputable section

open Matrix Polynomial

namespace V14Formalization.{MODULE}

open D12PolynomialData D12GeneratorPolynomialCore

private theorem C_eq_smul_one (a : ℚ) :
    C a = a • (1 : Polynomial ℚ) := by
  rw [Polynomial.smul_eq_C_mul, mul_one]

{rows}

def eigenExponent : Fin 10 → Nat := ![{exponent_vector}]

{restricted_rows}

theorem restrictedAction_eval
    {{R : Type*}} [CommRing R] [Algebra ℚ R] (z : R) :
    restrictedAction
        (D12PolynomialEvaluation.evalMatrixAt z
          (PluckerNaturality.compound2Lex T6_poly * B_poly)) =
      Matrix.diagonal fun i => z ^ eigenExponent i := by
  apply Matrix.ext
  intro i j
  fin_cases i
  {restricted_dispatch}

{relations}
end V14Formalization.{MODULE}
"""
    out_root.mkdir(parents=True, exist_ok=True)
    path = out_root / f"{MODULE}.lean"
    path.write_text(text)
    return path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, default=OUT_ROOT)
    args = parser.parse_args()
    path = emit(args.out_dir)
    print(f"wrote {path} ({path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
    __import__("sys").path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__)))
    from module_annotation_hook import reapply_module_annotations
    reapply_module_annotations()
