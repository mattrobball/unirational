def part1(p, say):
    m = Model(p)
    idx = {A: i for i, A in enumerate(m.G)}

    def gen(elts):
        S = {m.Id}
        fr = [m.Id]
        while fr:
            nf = []
            for A in fr:
                for g in elts:
                    B = m.mm(A, g)
                    if B not in S:
                        S.add(B)
                        nf.append(B)
            fr = nf
        return frozenset(S)

    seen, noncyc = set(), set()
    for A in m.G:
        if A == m.Id:
            continue
        for B in m.G:
            if B == m.Id or m.mm(A, B) != m.mm(B, A):
                continue
            H = gen([A, B])
            if H in seen:
                continue
            seen.add(H)
            if not all(m.mm(x, y) == m.mm(y, x) for x in H for y in H):
                continue
            if not any(m.morder(x) == len(H) for x in H):
                noncyc.add(H)
    orders = sorted(set(len(H) for H in noncyc))
    say(f"P1 subgroups generated by a commuting pair: {len(seen)}")
    say(f"P1 non-cyclic abelian subgroups: {len(noncyc)}, orders {orders}")
    allV4 = all(len(H) == 4 and all(m.morder(x) in (1, 2) for x in H) for H in noncyc)
    say(f"P1 every non-cyclic abelian subgroup is a Klein four-group: {allV4}")
    elt_orders = sorted(set(m.morder(x) for H in noncyc for x in H))
    say(f"P1 element orders occurring in non-cyclic abelian subgroups: {elt_orders}")
    noC = elt_orders == [1, 2]
    say(f"P1 no element of order 3,5,6,11 lies in a non-cyclic abelian subgroup: {noC}")
    ok = (len(noncyc) == 55 and orders == [4] and allV4 and noC)

    # corner orbit count: triples (V, z, s), z != s in V\1
    V4s = m.klein_fours()
    triples = []
    for H in V4s:
        nt = [x for x in H if x != m.Id]
        for z in nt:
            for s in nt:
                if z != s:
                    triples.append((H, z, s))
    say(f"P1 corner labels (V, z, s) with z != s in V: {len(triples)}")
    key = lambda t: (frozenset(t[0]), t[1], t[2])
    tset = set(key(t) for t in triples)
    orbits, todo = [], set(tset)
    while todo:
        t0 = next(iter(todo))
        orb = set()
        for g in m.G:
            gi = m.matinv(g)
            H2 = frozenset(m.mm(m.mm(g, x), gi) for x in t0[0])
            orb.add((H2, m.mm(m.mm(g, t0[1]), gi), m.mm(m.mm(g, t0[2]), gi)))
        orbits.append(len(orb))
        todo -= orb
    say(f"P1 G-orbits on corner labels: {len(orbits)}, sizes {sorted(orbits)}")
    stab = [A for A in m.G
            if frozenset(m.mm(m.mm(A, x), m.matinv(A)) for x in triples[0][0]) == frozenset(triples[0][0])
            and m.mm(m.mm(A, triples[0][1]), m.matinv(A)) == triples[0][1]
            and m.mm(m.mm(A, triples[0][2]), m.matinv(A)) == triples[0][2]]
    say(f"P1 setwise stabilizer of one corner label: order {len(stab)} "
        f"(= V4: {len(stab) == 4})")
    ok &= (sorted(orbits) == [165, 165] and len(stab) == 4)
    return ok


