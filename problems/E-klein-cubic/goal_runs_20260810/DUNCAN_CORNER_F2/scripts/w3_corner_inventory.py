# characters of V4 as elements of F_2^2 encoded 0,1,2,3 with XOR addition
NAME = {0: "0", 1: "a", 2: "b", 3: "c"}


def show(t):
    return "(" + ",".join(NAME[x] for x in t) + ")"


def faithful(t):
    """V4 acts faithfully iff the weights generate the character group,
    i.e. the intersection of their kernels is trivial."""
    return len({0, 1, 2, 3} & set()) == 0 and _span(t) == 3


def _span(t):
    s = {0}
    for x in t:
        s |= {y ^ x for y in s}
    return len(s) - 1  # 0 / 1 / 3


def succ(t):
    """All states reachable by one smooth V4-invariant blowup at the point."""
    out = set()
    n = len(t)
    for mask in range(1 << n):
        S = [t[i] for i in range(n) if mask >> i & 1]
        if len(S) > n - 2:            # codim of the centre must be >= 2
            continue
        N = [t[i] for i in range(n) if not mask >> i & 1]
        for chi in set(N):
            rest = list(N)
            rest.remove(chi)
            T2 = tuple(sorted(S + [chi] + [chi ^ nu for nu in rest]))
            out.add(T2)
    return out


def part2(say):
    A, B, C = 1, 2, 3                  # a = chi_z, b = chi_s, c = chi_r, a^b = c
    start = {tuple(sorted((0, A, B, C))): "general point of ell_V",
             tuple(sorted((A, A, B, C))): "type-I V4 point [B]"}
    say("P2 initial states on P(W) (the ONLY V4-fixed loci of P^4):")
    for t, lab in start.items():
        say(f"     {show(t)}   {lab}   codim of Fix(V4) = {4 - t.count(0)}")

    # full BFS
    dist = {t: 0 for t in start}
    par = {t: None for t in start}
    q = deque(start)
    while q:
        t = q.popleft()
        for u in succ(t):
            if u not in dist:
                dist[u] = dist[t] + 1
                par[u] = t
                q.append(u)
    say(f"P2 reachable faithful states: {len(dist)}")
    bym0 = defaultdict(list)
    for t in dist:
        bym0[t.count(0)].append(t)
    for k in sorted(bym0):
        say(f"P2   codim Fix(V4) = {4-k}: {len(bym0[k])} states: "
            f"{sorted(show(t) for t in bym0[k])}")
    faithless = [t for t in dist if _span(t) != 3]
    say(f"P2 states violating faithfulness (must be none): {len(faithless)}")

    targets = [t for t in dist if t.count(0) == 2]
    say(f"P2 FABULOUS-CORNER states (codim-2 V4-fixed locus): "
        f"{sorted(show(t) for t in targets)}")
    shapes_ok = all(len(set(x for x in t if x)) == 2 for t in targets)
    say(f"P2 every such state has TWO DISTINCT nontrivial normal characters "
        f"(so G_{{D_ij}} = V4, G_{{D_i}} = ker chi_2, G_{{D_j}} = ker chi_1): {shapes_ok}")

    def path(t):
        out = []
        while t is not None:
            out.append(show(t))
            t = par[t]
        return " <- ".join(out)
    for t in sorted(targets):
        say(f"P2 shortest unrestricted path to {show(t)}: {path(t)} (length {dist[t]})")

    # ---- G-equivariance restriction (Lemma C) -------------------------------
    # At a general point of ell_V the full local group is A4 = N_G(V4) and the
    # normal representation a+b+c is the IRREDUCIBLE 3-dimensional rep of A4;
    # hence the only legal centre through a general point of ell_V is ell_V
    # itself, i.e. S = {0}.  After that blowup the residual C3 is broken
    # (Stab_G(S_tau) = Stab_G(M_tau) = V4) and all V4-invariant centres are
    # legal again.
    ell = tuple(sorted((0, A, B, C)))
    legal_first = set()
    for u in succ(ell):
        # S = {0} corresponds to blowing up ell_V itself
        for chi in (A, B, C):
            rest = [x for x in (A, B, C) if x != chi]
            cand = tuple(sorted([0, chi] + [chi ^ nu for nu in rest]))
            legal_first.add(cand)
    say(f"P2 states reachable from {show(ell)} by the ONLY G-legal first move "
        f"(blow up ell_V): {sorted(show(t) for t in legal_first)}")
    d2 = {t: 0 for t in legal_first}
    par2 = {t: None for t in legal_first}
    q = deque(legal_first)
    while q:
        t = q.popleft()
        for u in succ(t):
            if u not in d2:
                d2[u] = d2[t] + 1
                par2[u] = t
                q.append(u)

    def path2(t):
        out = []
        while t is not None:
            out.append(show(t))
            t = par2[t]
        return " <- ".join(out) + " <- [blow up ell_V] <- " + show(ell)
    tt = [t for t in d2 if t.count(0) == 2]
    for t in sorted(tt):
        say(f"P2 G-legal route to {show(t)}: {path2(t)}  "
            f"(total blowups after ell_V: {d2[t]+1})")
    say("P2 the T2/T3 route of the packet realises (0,a,b,c) -> (0,a,a,b) -> (0,0,a,b) "
        "with centres P~_z (a component of Fix(z)) and M~_s (a component of "
        "Fix(s) inside E_V), both stabilizer-stratified.")
    return len(faithless) == 0 and shapes_ok and len(targets) > 0


