"""W3 -- full fabulous-corner inventory.

Two independent parts.

PART 1 (group theory, exact over the 660 matrices).  Proposition A:
  by Duncan def:toroidal(c) (lines 83-90) G_{D_ij} is ABELIAN of rank <= 2,
  and by thm:pairs (line 728) fabulous <=> non-cyclic.  We enumerate every
  non-cyclic abelian subgroup of PSL(2,11) and check they are exactly the 55
  Klein four-groups; hence a fabulous pair forces G_{D_ij} = V4 and the two
  divisorial stabilizers are two DISTINCT COMMUTING involutions.  We also
  check that no element of order 3, 5, 6 or 11 lies in any non-cyclic abelian
  subgroup, so no corner involving a C3/C5/C6/C11-divisor can ever be
  fabulous.

PART 2 (local reachability, exhaustive).  At a V4-fixed point of any smooth
model, record the multiset of the 4 V4-weights on the tangent space (elements
of the character group F_2^2, written additively as 0,a,b,c with a+b+c=0).
Faithfulness of the V4-action forces the weights to generate F_2^2.
For a smooth V4-invariant blowup centre C through the point with
T_xC = S (a sub-multiset, codim r = 4-|S| >= 2) and N = T/S, the V4-fixed
points of the exceptional divisor sit over the character sub-bundles, and at
a point over the chi-piece the new weight multiset is

      T' = S  u  {chi}  u  {chi + nu : nu in N minus one copy of chi}.

The V4-fixed locus through a point has codimension #{nontrivial weights}, so
a FABULOUS CORNER exists at that point iff the multiset is (0,0,x,y) with
x != y both nonzero -- and then G_{D_i} = ker(y), G_{D_j} = ker(x),
G_{D_ij} = V4.  We BFS the whole state graph from the only two states that
occur on P(W) itself, both unrestricted and under the G-equivariance
restriction of Lemma C.
"""
