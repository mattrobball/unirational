"""Emit a Macaulay2 script that recomputes every row of the ledger by an
IDEAL-THEORETIC route (no eigenvalue analysis at all):

    Fix(g) subset P^4  =  V( 2x2 minors of [ x | g.x ] )      (x an eigenvector of g)
    X^H                =  V(F) + sum_{g in gens(H)} Fix(g)

and reports dim / degree / radical-ness / decomposition of each.  Run over
GF(331) (all needed roots of unity present) and GF(661).
"""
import os
import sys
from collections import deque

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'results')
sys.path.insert(0, HERE)


def primefac(n):
    out, d = set(), 2
    while d * d <= n:
        while n % d == 0:
            out.add(d)
            n //= d
        d += 1
    if n > 1:
        out.add(n)
    return out


def root_of_unity(p, n):
    for a in range(2, p):
        r = pow(a, (p - 1) // n, p)
        if r != 1 and all(pow(r, n // q, p) != 1 for q in primefac(n)):
            return r
    raise RuntimeError


def fmul(A, B):
    return tuple(sum(A[2 * i + k] * B[2 * k + j] for k in range(2)) % 11
                 for i in range(2) for j in range(2))


def fcanon(A):
    A = tuple(a % 11 for a in A)
    B = tuple((-a) % 11 for a in A)
    return min(A, B)


FONE, FS, FT = fcanon((1, 0, 0, 1)), fcanon((0, 2, 5, 0)), fcanon((1, 2, 0, 1))


def build(p):
    z = root_of_unity(p, 11)
    zp = [pow(z, e, p) for e in range(11)]
    qr = {1, 3, 4, 5, 9}
    g = sum((1 if a in qr else -1) * zp[a] for a in range(1, 11)) % p
    js, signs = [1, 3, 2, 5, 4], [1, 1, -1, 1, 1]
    inv11 = pow(11, -1, p)
    S = [[(signs[k] * signs[i]) * (zp[(9 * j * l) % 11] - zp[(-9 * j * l) % 11])
          * (-g) * inv11 % p for k, l in enumerate(js)] for i, j in enumerate(js)]
    T = [[zp[(js[i] * js[i]) % 11] if i == j else 0 for j in range(5)] for i in range(5)]

    def mm(A, B):
        return [[sum(A[i][t] * B[t][j] for t in range(5)) % p for j in range(5)]
                for i in range(5)]
    rho = {FONE: [[1 if i == j else 0 for j in range(5)] for i in range(5)]}
    elts, dq = [FONE], deque([FONE])
    while dq:
        a = dq.popleft()
        for b, R in ((FS, S), (FT, T)):
            c = fcanon(fmul(a, b))
            if c not in rho:
                rho[c] = mm(rho[a], R)
                elts.append(c)
                dq.append(c)
    assert len(elts) == 660
    idx = {e: i for i, e in enumerate(elts)}
    mul = [[idx[fcanon(fmul(a, b))] for b in elts] for a in elts]
    return elts, idx, [rho[e] for e in elts], mul


def gen_sub(mul, one, gens):
    S, fr = {one}, [one]
    while fr:
        nf = []
        for x in fr:
            for g in gens:
                y = mul[x][g]
                if y not in S:
                    S.add(y)
                    nf.append(y)
        fr = nf
    return frozenset(S)


def elt_order(e):
    n, x = 1, e
    while x != FONE:
        x = fcanon(fmul(x, e))
        n += 1
    return n


def name(H, ordr):
    n = len(H)
    o = sorted(ordr[h] for h in H)
    if n == 6:
        return 'C6' if 6 in o else 'S3'
    if n == 12:
        return 'D12' if 6 in o else 'A4'
    return {1: '1', 2: 'C2', 3: 'C3', 4: 'V4', 5: 'C5', 10: 'D10', 11: 'C11',
            55: 'F55', 60: 'A5', 660: 'G'}[n]


def classes_of(mul, one, elts, ordr):
    inv = {}
    for i, e in enumerate(elts):
        a, b, c, d = e
        det = (a * d - b * c) % 11
        di = pow(det, -1, 11)
        inv[i] = elts.index(fcanon(((d * di) % 11, (-b * di) % 11,
                                    (-c * di) % 11, (a * di) % 11)))

    def conj(H, g):
        return frozenset(mul[mul[g][h]][inv[g]] for h in H)

    def orbit(H):
        return frozenset(conj(H, g) for g in range(660))
    triv = frozenset({one})
    reps, gens, seen = [triv], [[]], set(orbit(triv))
    frontier = [0]
    while frontier:
        nf = []
        for hi in frontier:
            H, gH = reps[hi], gens[hi]
            for g in range(660):
                if g in H:
                    continue
                K = gen_sub(mul, one, gH + [g])
                if K in seen:
                    continue
                reps.append(K)
                gens.append(gH + [g])
                seen |= orbit(K)
                nf.append(len(reps) - 1)
        frontier = nf
    return list(zip(reps, gens))


def main():
    lines = []
    lines.append('-- RECEIVER_LEDGER_X : ideal-theoretic recomputation of X^H')
    lines.append('-- generated by scripts/emit_m2.py ; run with:  M2 --script scripts/ledger_ideals.m2')
    lines.append('nfail = 0;')
    expect = {'1': (3, 3), 'C2': (1, 4), 'C3': (0, 6), 'V4': (0, 6), 'C5': (0, 4),
              'S3': (-1, 0), 'C6': (0, 2), 'D10': (-1, 0), 'C11': (0, 5),
              'A4': (-1, 0), 'D12': (-1, 0), 'F55': (-1, 0), 'A5': (-1, 0),
              'G': (-1, 0)}
    for p in (331, 661):
        elts, idx, rho, mul = build(p)
        one = idx[FONE]
        ordr = [elt_order(e) for e in elts]
        cls = classes_of(mul, one, elts, ordr)
        lines.append('')
        lines.append('kk = GF %d;' % p)
        lines.append('R = kk[x0,x1,x2,x3,x4];')
        lines.append('F = x0^2*x1 + x1^2*x2 + x2^2*x3 + x3^2*x4 + x4^2*x0;')
        lines.append('xx = matrix{{x0},{x1},{x2},{x3},{x4}};')
        lines.append('fixIdeal = (M) -> minors(2, xx | M*xx);')
        seen = {}
        for H, gens in cls:
            nm = name(H, ordr)
            seen[nm] = seen.get(nm, 0) + 1
            lab = nm + ('' if seen[nm] == 1 else '_b')
            if not gens:
                gens = []
            mats = []
            for g in gens:
                M = rho[g]
                mats.append('matrix{' + ','.join(
                    '{' + ','.join(str(M[i][j] % p) for j in range(5)) + '}'
                    for i in range(5)) + '}')
            if mats:
                idl = 'ideal(F) + ' + ' + '.join('fixIdeal(%s)' % m for m in mats)
            else:
                idl = 'ideal(F)'
            d, deg = expect[nm]
            lines.append('')
            lines.append('-- row %s  (|H| = %d)' % (lab, len(H)))
            lines.append('I = saturate(%s);' % idl)
            lines.append('dp = if I == ideal(1_R) then -1 else dim I - 1;')
            lines.append('dg = if dp < 0 then 0 else degree I;')
            lines.append('rad = if dp < 0 then true else (I == radical I);')
            lines.append(('<< "ROW %s p=%d projdim " << dp << " degree " << dg '
                          '<< " radical " << rad << endl;') % (lab, p))
            lines.append('if dp != %d or dg != %d then (nfail = nfail + 1; '
                         '<< "FAIL %s p=%d expected projdim %d degree %d" << endl;) '
                         'else << "PASS %s p=%d" << endl;'
                         % (d, deg, lab, p, d, deg, lab, p))
        lines.append('')
    lines.append('<< "M2 failures: " << nfail << endl;')
    lines.append('<< (if nfail == 0 then "LEDGER_IDEALS_M2_OK" else "LEDGER_IDEALS_M2_FAILED") << endl;')
    path = os.path.join(HERE, 'ledger_ideals.m2')
    with open(path, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
