sys.path.insert(0, HERE)

from klein_exact import (Cyc, Cyc3, ZERO, ONE, Grp, klein_eval, mat_mul,
                         mat_vec, identity, nullspace, rank, rowspace_basis,
                         rref, Poly)

T0 = time.time()
OUT = {}
LINES = []


def log(s):
    print(s, flush=True)
    LINES.append(s)


# ------------------------------------------------------------------ helpers

def eigbasis(M, sign):
    rows = [[M[i][j] - (Cyc.from_int(sign) if i == j else ZERO)
             for j in range(5)] for i in range(5)]
    return nullspace(rows, 5)


def klein_poly(c, nv):
    tot = Poly(nv=nv)
    for k in range(5):
        tot = tot + c[k] * c[k] * c[(k + 1) % 5]
    return tot


def restrict_F(basis, nv):
    coords = []
    for i in range(5):
        p = Poly(nv=nv)
        for k in range(nv):
            mono = tuple(1 if j == k else 0 for j in range(nv))
            p = p + Poly({mono: basis[k][i]}, nv=nv)
        coords.append(p)
    return klein_poly(coords, nv).c


def coords_in_basis(basis, w, n):
    """solve sum_j c_j basis[j] = w (basis of an n-dim subspace of k^5)."""
    aug = [[basis[j][i] for j in range(n)] + [w[i]] for i in range(5)]
    R, _piv = rref(aug)
    sol = [ZERO] * n
    for row in R:
        piv = None
        for j in range(n):
            if not row[j].is_zero():
                piv = j
                break
        if piv is None:
            assert row[n].is_zero(), 'vector not in span'
            continue
        sol[piv] = row[n]
    for i in range(5):
        acc = ZERO
        for j in range(n):
            acc = acc + basis[j][i] * sol[j]
        assert acc == w[i]
    return sol


def restrict_matrix(A, basis):
    n = len(basis)
    cols = [coords_in_basis(basis, mat_vec(A, basis[k]), n) for k in range(n)]
    return [[cols[j][i] for j in range(n)] for i in range(n)]


def matkey(A):
    return tuple((x.n, x.d) for row in A for x in row)


def gen_group(mats, n):
    I = identity(n)
    elems = {matkey(I): I}
    frontier = [I]
    while frontier:
        nxt = []
        for A in frontier:
            for M in mats:
                B = mat_mul(A, M)
                k = matkey(B)
                if k not in elems:
                    elems[k] = B
                    nxt.append(B)
        frontier = nxt
    return list(elems.values())


def algebra_dim(mats, n):
    """dimension of the unital algebra generated by `mats` inside M_n."""
    span = []
    def flat(A):
        return [A[i][j] for i in range(n) for j in range(n)]
    def add(A):
        R = rowspace_basis(span + [flat(A)])
        if len(R) > len(span):
            span[:] = [list(r) for r in R]
            return True
        return False
    add(identity(n))
    frontier = [identity(n)]
    while frontier:
        nxt = []
        for A in frontier:
            for M in mats:
                B = mat_mul(A, M)
                if add(B):
                    nxt.append(B)
        frontier = nxt
    return len(span)


def linear_characters(els, n):
    """all homomorphisms H -> {+-1} for H = <els>, as sign lists."""
    N = len(els)
    idx = {matkey(A): i for i, A in enumerate(els)}
    mul = [[idx[matkey(mat_mul(els[i], els[j]))] for j in range(N)]
           for i in range(N)]
    inv = [next(j for j in range(N) if mul[i][j] == 0) for i in range(N)]
    comm = set()
    for i in range(N):
        for j in range(N):
            comm.add(mul[mul[i][j]][mul[inv[i]][inv[j]]])
    changed = True
    comm.add(0)
    while changed:
        changed = False
        for a in list(comm):
            for b in list(comm):
                c = mul[a][b]
                if c not in comm:
                    comm.add(c)
                    changed = True
    reps, coset = [], {}
    for i in range(N):
        f = None
        for ri, r in enumerate(reps):
            if mul[inv[r]][i] in comm:
                f = ri
                break
        if f is None:
            reps.append(i)
            f = len(reps) - 1
        coset[i] = f
    k = len(reps)
    out = []
    for mask in range(1 << k):
        sgn = [1 if not (mask >> t) & 1 else -1 for t in range(k)]
        if sgn[coset[0]] != 1:
            continue
        ok = all(sgn[coset[mul[i][j]]] == sgn[coset[i]] * sgn[coset[j]]
                 for i in range(N) for j in range(N))
        if ok:
            out.append([sgn[coset[i]] for i in range(N)])
    return out


def invariant_lines(mats, n):
    """all 1-dim submodules: the isotypic pieces of the linear characters."""
    els = gen_group(mats, n)
    N = len(els)
    chars = linear_characters(els, n)
    lines, dims = [], []
    for chi in chars:
        P = [[ZERO] * n for _ in range(n)]
        for i in range(N):
            c = Cyc.from_int(chi[i])
            for a in range(n):
                for b in range(n):
                    P[a][b] = P[a][b] + c * els[i][a][b]
        s = Cyc.from_frac(1, N)
        P = [[P[a][b] * s for b in range(n)] for a in range(n)]
        B = rowspace_basis(P)
        dims.append(len(B))
        if len(B) == 1:
            lines.append(list(B[0]))
        elif len(B) > 1:
            raise AssertionError('linear isotypic multiplicity > 1')
    return lines, len(els), len(chars), dims


# ------------------------------------------------------------------- Part A

def part_A(G):
    log('--- Part A: exact geometric certificates, all 55 involutions')
    invs = [i for i in range(G.n) if G.ord[i] == 2]
    assert len(invs) == 55
    per = []
    for s in invs:
        M = G.mats[s]
        Wp, Wm = eigbasis(M, 1), eigbasis(M, -1)
        assert len(Wp) == 3 and len(Wm) == 2

        # A1  sigma is diag(1,1,1,-1,-1) in the adapted basis
        Mad = restrict_matrix(M, Wp + Wm)
        want = [[(ONE if i == j and i < 3 else
                  (-ONE if i == j else ZERO)) for j in range(5)]
                for i in range(5)]
        a1 = all(Mad[i][j] == want[i][j] for i in range(5) for j in range(5))

        # A2  F|_{W-} == 0
        a2 = all(v.is_zero() for v in restrict_F(Wm, 2).values())

        # A3  F(w+y): only y-degrees 0 and 2 occur
        yd = sorted({m[3] + m[4] for m, c in restrict_F(Wp + Wm, 5).items()
                     if not c.is_zero()})
        a3 = set(yd) <= {0, 2}

        C = G.centralizer(s)
        assert len(C) == 12
        Mp = [restrict_matrix(G.mats[g], Wp) for g in C]
        Mm = [restrict_matrix(G.mats[g], Wm) for g in C]

        lp, np_, ncp, dp = invariant_lines(Mp, 3)
        lm, nm_, ncm, dm = invariant_lines(Mm, 2)
        a4 = (len(lp) == 1)
        zs = ([sum((Wp[k][i] * lp[0][k] for k in range(3)), ZERO)
               for i in range(5)] if a4 else None)
        a4b = a4 and not klein_eval(zs).is_zero()
        a5 = (len(lm) == 0)
        algp, algm = algebra_dim(Mp, 3), algebra_dim(Mm, 2)
        a5b = (algm == 4)          # Burnside: irreducible on W-
        a4c = (algp == 5)          # triv (+) std with std irreducible

        assert a1 and a2 and a3 and a4 and a4b and a5 and a5b and a4c, s
        per.append({'g': s, 'A1': a1, 'A2': a2, 'A3_ydegs': yd, 'A4': a4,
                    'A4_z_off_X': a4b, 'A4_alg_dim_Wplus': algp,
                    'A5_n_lines_Wminus': len(lm),
                    'A5_alg_dim_Wminus': algm,
                    'image_group_order_Wplus': np_,
                    'image_group_order_Wminus': nm_,
                    'n_linear_chars_Wplus': ncp,
                    'n_linear_chars_Wminus': ncm,
                    'isotypic_dims_Wplus': dp,
                    'isotypic_dims_Wminus': dm})
    log('    A1  sigma = diag(1,1,1,-1,-1) in the adapted basis   : 55/55')
    log('    A2  F|_{W-} == 0                                     : 55/55')
    log('    A3  F(w+y) has y-degrees in {0,2} only               : 55/55')
    log('    A4  exactly ONE C_G(sigma)-invariant line in W+,')
    log('        and its point z_sigma is OFF X                   : 55/55')
    log('    A5  NO C_G(sigma)-invariant line in W- (two proofs)   : 55/55')

    # A6 single conjugacy class
    s0 = invs[0]
    orb = {G.conj(s0, g) for g in range(G.n)}
    a6 = (orb == set(invs))
    log('    A6  the 55 involutions form ONE G-conjugacy class     : %s' % a6)
    assert a6
    return {'per_sigma': per, 'single_class': a6, 'invs': invs}


# ------------------------------------------------------------------- Part B

def part_B(G, invs):
    log('--- Part B: the parity lemma for sigma-equivariant tuples')
    res = []
    # (i) original coordinates, d = 1, 2: solve T(Mv) = M T(v) exactly and
    #     read off the y-parity of the solution space in the adapted basis.
    for s in (invs[0], invs[23]):
        M = G.mats[s]
        Wp, Wm = eigbasis(M, 1), eigbasis(M, -1)
        Bas = Wp + Wm
        # change-of-basis: v = Bas^T * u  (u = adapted coords)
        P = [[Bas[j][i] for j in range(5)] for i in range(5)]   # columns = Bas
        Pinv = _inv5(P)
        for d in (1, 2, 3):
            monos = mons(5, d)
            nm = len(monos)
            midx = {m: i for i, m in enumerate(monos)}
            # unknowns c[i][mono]; equations from T(Mv) - M T(v) = 0.
            # T_i(Mv) : substitute v -> M v  (linear substitution)
            rows = []
            # precompute substituted monomials as polynomials
            lin = []
            for k in range(5):
                p = Poly(nv=5)
                for j in range(5):
                    p = p + Poly({tuple(1 if t == j else 0 for t in range(5)):
                                  M[k][j]}, nv=5)
                lin.append(p)
            subst = {}
            for mo in monos:
                p = Poly.const(ONE, 5)
                for k in range(5):
                    for _ in range(mo[k]):
                        p = p * lin[k]
                subst[mo] = p.c
            # equation for component i and output monomial mo:
            #   sum_mo' c[i][mo'] * subst[mo'][mo]  -  sum_j M[i][j] c[j][mo] = 0
            for i in range(5):
                for mo in monos:
                    row = [ZERO] * (5 * nm)
                    for mo2 in monos:
                        v = subst[mo2].get(mo, ZERO)
                        if not v.is_zero():
                            row[i * nm + midx[mo2]] = row[i * nm + midx[mo2]] + v
                    for j in range(5):
                        if not M[i][j].is_zero():
                            row[j * nm + midx[mo]] = row[j * nm + midx[mo]] - M[i][j]
                    if any(not x.is_zero() for x in row):
                        rows.append(row)
            sols = nullspace(rows, 5 * nm)
            # express each solution in the adapted basis and check parity
            ok = True
            supp = {'plus_ydeg': set(), 'minus_ydeg': set()}
            for sol in sols:
                # T(v) = sum_i e_i * (sum_mo c[i][mo] v^mo).  Adapted:
                #   Tad = Pinv * T(Bas * u)
                comp = []
                for i in range(5):
                    p = Poly(nv=5)
                    for mo in monos:
                        cc = sol[i * nm + midx[mo]]
                        if not cc.is_zero():
                            p = p + Poly({mo: cc}, nv=5)
                    comp.append(p)
                # substitute v = Bas * u
                linu = []
                for k in range(5):
                    p = Poly(nv=5)
                    for j in range(5):
                        p = p + Poly({tuple(1 if t == j else 0
                                            for t in range(5)): P[k][j]}, nv=5)
                    linu.append(p)
                compu = []
                for i in range(5):
                    q = Poly(nv=5)
                    for mo, cc in comp[i].c.items():
                        pp = Poly.const(cc, 5)
                        for k in range(5):
                            for _ in range(mo[k]):
                                pp = pp * linu[k]
                        q = q + pp
                    compu.append(q)
                # apply Pinv
                for a in range(5):
                    q = Poly(nv=5)
                    for b in range(5):
                        if not Pinv[a][b].is_zero():
                            q = q + compu[b] * Poly.const(Pinv[a][b], 5)
                    for mo, cc in q.c.items():
                        if cc.is_zero():
                            continue
                        dy = mo[3] + mo[4]
                        if a < 3:
                            supp['plus_ydeg'].add(dy)
                            if dy % 2:
                                ok = False
                        else:
                            supp['minus_ydeg'].add(dy)
                            if dy % 2 == 0:
                                ok = False
            res.append({'sigma': s, 'd': d, 'mode': 'original-coordinates',
                        'dim_equivariant_space': len(sols),
                        'plus_ydegs': sorted(supp['plus_ydeg']),
                        'minus_ydegs': sorted(supp['minus_ydeg']),
                        'parity_ok': ok})
            log('    sigma=%3d  d=%d : dim Equiv = %2d, y-degrees on the '
                'W+-block %s, on the W--block %s  -> parity %s'
                % (s, d, len(sols), sorted(supp['plus_ydeg']),
                   sorted(supp['minus_ydeg']), 'OK' if ok else 'FAIL'))
            assert ok
    return res


def _inv5(P):
    n = 5
    aug = [[P[i][j] for j in range(n)] + [ONE if i == j else ZERO
                                          for j in range(n)] for i in range(n)]
    R, _piv = rref(aug)
    inv = [[ZERO] * n for _ in range(n)]
    for r, row in enumerate(R):
        piv = next(j for j in range(n) if not row[j].is_zero())
        for j in range(n):
            inv[piv][j] = row[n + j]
    return inv


def mons(n, d):
    if n == 1:
        return [(d,)]
    out = []
    for k in range(d + 1):
        for rest in mons(n - 1, d - k):
            out.append((k,) + rest)
    return out


def main():
    log('FIX-H0 producer, Parts A and B')
    G = Grp()
    assert G.n == 660
    log('    group rebuilt from S,T: %d elements' % G.n)
    A = part_A(G)
    OUT['partA'] = A
    OUT['partB'] = part_B(G, A['invs'])
    os.makedirs(os.path.join(HERE, 'payloads'), exist_ok=True)
    with open(os.path.join(HERE, 'payloads', 'h0_certificates.json'), 'w') as f:
        json.dump(OUT, f, indent=1, sort_keys=True)
    with open(os.path.join(HERE, 'payloads', 'PAYLOAD_geometry.txt'), 'w') as f:
        f.write('\n'.join(LINES) + '\n')
    log('elapsed %.1f s' % (time.time() - T0))
    log('FIX_H0_PRODUCE_AB_OK')


if __name__ == '__main__':
    main()
