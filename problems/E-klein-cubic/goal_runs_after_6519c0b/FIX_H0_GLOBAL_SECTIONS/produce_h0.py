#!/usr/bin/env python3
"""FIX-H0 producer, Parts A and B -- the geometric inputs of Theorems H0-1/2.

Part A  exact certificates from the 5-dim Weil representation, all 55
        involutions:
          A1  dim W+ = 3, dim W- = 2, and sigma = diag(1,1,1,-1,-1) in the
              adapted basis
          A2  F|_{W-} == 0                             (L_sigma subset X)
          A3  F(w+y) has only y-degrees 0 and 2        (sigma-parity of F)
          A4  exactly ONE C_G(sigma)-invariant line in W+, and its point
              z_sigma is OFF X
          A5  NO C_G(sigma)-invariant line in W-       (no residual fixed
              point on L_sigma); confirmed twice (linear-character isotypic
              dimensions, and the Burnside algebra-dimension test)
          A6  all 55 involutions are G-conjugate       (so one smoothness
              certificate for E_sigma covers all 55)
Part B  the parity lemma for sigma-equivariant tuples, solved as an exact
        linear system, in the ORIGINAL coordinates for d = 1,2 and in the
        adapted basis for d = 1..8.

Writes payloads/h0_certificates.json and payloads/PAYLOAD_geometry.txt.
"""
