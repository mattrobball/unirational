"""
Equivariant V14 for G = PSL(2,11):  U = 6-dim Weil rep of SL(2,11),
Lambda^2 U = 5 + 10',  M = the 10',  V14 = Gr(2,U) \cap P(M) \subset P^9.

Everything is built from scratch over F_p (p = 397 primary, 199 control);
both primes contain zeta_11 and a square root of -1/11, which is all the
Weil representation needs.
"""

import itertools
import fp

# ---------------------------------------------------------------- Weil rep

PAIRS = [(i, j) for i in range(6) for j in range(i + 1, 6)]        # 15
PIDX = {q: a for a, q in enumerate(PAIRS)}
QUADS = list(itertools.combinations(range(6), 4))                   # 15


def weil6(p):
    """6-dim (even) Weil representation of SL(2,11) over F_p.

    Returns (A, B, data) with A = rho(T), B = rho(S), S^2 = -I, (ST)^3 = S^2.
    """
    w = fp.prim_root_of_unity(11, p)
    c2 = (-fp.inv(11, p)) % p                       # c^2 = -1/11
    c0 = fp.sqrt_mod(c2, p)
    assert c0 is not None and c0 * c0 % p == c2
    mI = fp.scal(fp.ident(6), p - 1, p)
    for a in range(1, 11):
        A = [[0] * 6 for _ in range(6)]
        A[0][0] = 1
        for j in range(1, 6):
            A[j][j] = pow(w, a * j * j % 11, p)
        for b in range(1, 11):
            for c in (c0, (-c0) % p):
                B = [[0] * 6 for _ in range(6)]
                B[0][0] = c
                for j in range(1, 6):
                    B[0][j] = 2 * c % p
                for k in range(1, 6):
                    B[k][0] = c
                    for j in range(1, 6):
                        e = b * j * k % 11
                        B[k][j] = c * (pow(w, e, p) + pow(w, (-e) % 11, p)) % p
                if fp.key(fp.matmul(B, B, p), p) != fp.key(mI, p):
                    continue
                BA = fp.matmul(B, A, p)
                BA3 = fp.matmul(BA, fp.matmul(BA, BA, p), p)
                if fp.key(BA3, p) == fp.key(mI, p):
                    return A, B, dict(a=a, b=b, c=c, w=w)
    raise RuntimeError("no Weil normalization found")


def closure(gens, p, limit=5000):
    """All elements of the group generated by `gens` (matrices), as keys."""
    idn = fp.ident(len(gens[0]))
    seen = {fp.key(idn, p): idn}
    frontier = [idn]
    while frontier:
        nxt = []
        for X in frontier:
            for g in gens:
                Y = fp.matmul(g, X, p)
                k = fp.key(Y, p)
                if k not in seen:
                    seen[k] = Y
                    nxt.append(Y)
                    if len(seen) > limit:
                        raise RuntimeError("closure too big")
        frontier = nxt
    return seen


def order_of(X, p):
    n = len(X)
    idn = fp.key(fp.ident(n), p)
    Y, o = X, 1
    while fp.key(Y, p) != idn:
        Y = fp.matmul(Y, X, p)
        o += 1
        if o > 5000:
            raise RuntimeError("infinite order?")
    return o


# ---------------------------------------------------------------- Lambda^2

def lam2(G, p):
    """15x15 matrix of Lambda^2 of the 6x6 matrix G."""
    R = [[0] * 15 for _ in range(15)]
    for r, (i, j) in enumerate(PAIRS):
        for cidx, (k, l) in enumerate(PAIRS):
            R[r][cidx] = (G[i][k] * G[j][l] - G[j][k] * G[i][l]) % p
    return R


def commutant_split(gens15, p):
    """Return (dimensions, eigen-bases) of the isotypic split of a 15-dim rep
    whose commutant is 2-dimensional."""
    n = 15
    rows = []
    for g in gens15:
        # X g - g X = 0, unknowns X[i][j] flattened
        for i in range(n):
            for j in range(n):
                row = [0] * (n * n)
                for t in range(n):
                    row[i * n + t] = (row[i * n + t] + g[t][j]) % p
                    row[t * n + j] = (row[t * n + j] - g[i][t]) % p
                rows.append(row)
    ns = fp.nullspace(rows, p)
    assert len(ns) == 2, f"commutant dim {len(ns)} (expected 2)"
    # pick the non-scalar generator
    X = None
    for v in ns:
        Mx = [v[i * n:(i + 1) * n] for i in range(n)]
        offdiag = any(Mx[i][j] for i in range(n) for j in range(n) if i != j)
        diagdiff = len({Mx[i][i] for i in range(n)}) > 1
        if offdiag or diagdiff:
            X = Mx
            break
    assert X is not None
    # eigen-decomposition: X satisfies a quadratic; find eigenvalues by
    # scanning the (at most 2) roots of its minimal polynomial via nullspaces
    pieces = []
    for lam in range(p):
        Y = fp.madd(X, fp.scal(fp.ident(n), (-lam) % p, p), p)
        ns2 = fp.nullspace(Y, p)
        if ns2:
            pieces.append((lam, ns2))
        if sum(len(b) for _, b in pieces) == n:
            break
    return X, pieces


# ---------------------------------------------------------------- the model

class Model:
    def __init__(self, p):
        self.p = p
        A6, B6, self.weil = weil6(p)
        self.A6, self.B6 = A6, B6
        self.gens15 = [lam2(A6, p), lam2(B6, p)]
        X, pieces = commutant_split(self.gens15, p)
        pieces.sort(key=lambda t: len(t[1]))
        assert [len(b) for _, b in pieces] == [5, 10], [len(b) for _, b in pieces]
        self.Nrows = fp.rowspace_basis(pieces[0][1], p)          # 5-dim summand
        self.Mrows = fp.rowspace_basis(pieces[1][1], p)          # 10' summand
        _, self.Mpiv = fp.rref(self.Mrows, p)
        _, self.Npiv = fp.rref(self.Nrows, p)
        assert len(self.Mpiv) == 10 and len(self.Nrows) == 5

    # ---- group elements
    def group15(self):
        if not hasattr(self, "_g15"):
            self._g15 = closure(self.gens15, self.p, limit=2000)
        return self._g15

    def to10(self, g15):
        """10x10 matrix of g15 acting on M in the echelonized basis."""
        p = self.p
        cols = []
        for a in range(10):
            v = fp.matvec(g15, self.Mrows[a], p)
            cols.append([v[c] for c in self.Mpiv])
        return [[cols[a][i] for a in range(10)] for i in range(10)]

    def to5(self, g15):
        p = self.p
        cols = []
        for a in range(5):
            v = fp.matvec(g15, self.Nrows[a], p)
            cols.append([v[c] for c in self.Npiv])
        return [[cols[a][i] for a in range(5)] for i in range(5)]

    # ---- the 15 Plucker quadrics restricted to P(M)
    def omega_forms(self):
        """omega_{ij} as a linear form in y_0..y_9: list of 10 coefficients."""
        return {q: [self.Mrows[a][PIDX[q]] for a in range(10)] for q in PAIRS}

    def quadrics(self, basis=None):
        """15 quadrics as dicts {(a,b): coeff}, a<=b, in the given basis of M
        (default: the echelonized basis)."""
        p = self.p
        rows = self.Mrows if basis is None else basis
        k = len(rows)
        lin = {q: [rows[a][PIDX[q]] for a in range(k)] for q in PAIRS}

        def mul(u, v):
            d = {}
            for a in range(k):
                if not u[a]:
                    continue
                for b in range(k):
                    if not v[b]:
                        continue
                    key = (a, b) if a <= b else (b, a)
                    d[key] = (d.get(key, 0) + u[a] * v[b]) % p
            return d

        def comb(terms):
            d = {}
            for sgn, u, v in terms:
                for key, c in mul(u, v).items():
                    d[key] = (d.get(key, 0) + sgn * c) % p
            return {k2: v2 for k2, v2 in d.items() if v2 % p}

        out = []
        for (i, j, kk, l) in QUADS:
            out.append(comb([(1, lin[(i, j)], lin[(kk, l)]),
                             (-1, lin[(i, kk)], lin[(j, l)]),
                             (1, lin[(i, l)], lin[(j, kk)])]))
        return out


# ---------------------------------------------------------------- utilities

def quad_to_str(q, names):
    """Render {(a,b):c} as a polynomial string."""
    if not q:
        return "0"
    parts = []
    for (a, b) in sorted(q):
        c = q[(a, b)]
        if not c:
            continue
        parts.append(f"{c}*{names[a]}*{names[b]}")
    return "+".join(parts) if parts else "0"


def quad_matrix(q, n, p):
    """Symmetric matrix (2Q) of the quadratic form q in n variables."""
    Msym = [[0] * n for _ in range(n)]
    for (a, b), c in q.items():
        if a == b:
            Msym[a][a] = (Msym[a][a] + 2 * c) % p
        else:
            Msym[a][b] = (Msym[a][b] + c) % p
            Msym[b][a] = (Msym[b][a] + c) % p
    return Msym


def eval_quads(quads, y, p):
    out = []
    for q in quads:
        s = 0
        for (a, b), c in q.items():
            s += c * y[a] * y[b]
        out.append(s % p)
    return out


def jac_quads(quads, y, p):
    """Jacobian matrix (len(quads) x n) of the quadrics at point y."""
    n = len(y)
    J = []
    for q in quads:
        row = [0] * n
        for (a, b), c in q.items():
            if a == b:
                row[a] = (row[a] + 2 * c * y[a]) % p
            else:
                row[a] = (row[a] + c * y[b]) % p
                row[b] = (row[b] + c * y[a]) % p
        J.append(row)
    return J
