#!/usr/bin/env python3
"""Prime-power Sylow audit for C2 x D_{2n}, n odd.

Salvaged from PR #13; see ADJUDICATION_PR13.md.

This supplements ``verify_dihedral_conic_bundle.py`` by checking the full
p-primary rotation subgroup when n is not squarefree (n = 9, 25, 27 below),
where the Sylow subgroup is strictly larger than the subgroup generated by a
single prime-order rotation.

Same model as ``verify_dihedral_conic_bundle.py``: the curve
C_n : q^2 = x^(2n) + y^(2n) in P(1,1,n), with C2 acting trivially on C_n.
The n=3 case is the residual data of THEOREM_RULED_CONIC_BUNDLE_THREEFOLD.md.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import FrozenSet, Iterable, List, Set


@dataclass(frozen=True, order=True)
class E:
    z: int
    r: int
    s: int


def mul(n: int, a: E, b: E) -> E:
    sign = -1 if a.s else 1
    return E((a.z + b.z) % 2, (a.r + sign * b.r) % n, (a.s + b.s) % 2)


def inv(n: int, a: E) -> E:
    return E(a.z, (-a.r if a.s == 0 else a.r) % n, a.s)


def generated(n: int, seeds: Iterable[E]) -> FrozenSet[E]:
    identity = E(0, 0, 0)
    subgroup: Set[E] = {identity, *seeds}
    changed = True
    while changed:
        changed = False
        current = list(subgroup)
        for a in current:
            candidates = [inv(n, a)]
            candidates.extend(mul(n, a, b) for b in current)
            candidates.extend(mul(n, b, a) for b in current)
            for candidate in candidates:
                if candidate not in subgroup:
                    subgroup.add(candidate)
                    changed = True
    return frozenset(subgroup)


def prime_factors(n: int) -> List[int]:
    result: List[int] = []
    p = 2
    while p * p <= n:
        if n % p == 0:
            result.append(p)
            while n % p == 0:
                n //= p
        p += 1
    if n > 1:
        result.append(n)
    return result


def p_part(n: int, p: int) -> int:
    result = 1
    while n % p == 0:
        result *= p
        n //= p
    return result


def check(n: int) -> dict:
    if n < 3 or n % 2 == 0:
        raise ValueError("n must be odd and at least three")

    odd_sylows = {}
    for p in prime_factors(n):
        order = p_part(n, p)
        generator = E(0, n // order, 0)
        subgroup = generated(n, {generator})
        assert len(subgroup) == order
        assert all(g.s == 0 and g.z == 0 for g in subgroup)
        assert order % p == 0 and n % order == 0
        # Witness: [x:y:q]=[0:1:1] lies on q^2=x^(2n)+y^(2n) because 1=0+1,
        # and r^k(0,1,1)=(0,zeta^(-k),1) ~ (0,1,zeta^(kn))=(0,1,1) after
        # rescaling by zeta^k, since q has weight n and zeta^n=1.
        assert (0 ** (2 * n) + 1 ** (2 * n)) == 1 ** 2
        odd_sylows[p] = {"order": order, "witness": "[0:1:1]"}

    sylow_two = generated(n, {E(1, 0, 0), E(0, 0, 1)})
    assert len(sylow_two) == 4
    assert all(mul(n, a, b) == mul(n, b, a) for a in sylow_two for b in sylow_two)
    # Sylow 2 = <z, s>.  Witness: the base point t=x/y=1 is fixed by s, and
    # above it q^2 = 1^(2n)+1^(2n) = 2, so [1:1:sqrt(2)] lies on C_n; s acts
    # trivially on q and z acts trivially on C_n.
    assert (1 ** (2 * n) + 1 ** (2 * n)) == 2
    assert 4 * n % 4 == 0 and (n % 2 == 1)  # |Sylow 2| = 4 because n is odd

    return {
        "n": n,
        "group_order": 4 * n,
        "odd_sylows": odd_sylows,
        "sylow_two": {"order": 4, "witness": "[1:1:sqrt(2)]"},
        "all_sylows_fixed": True,
    }


def main() -> None:
    import json

    report = [check(n) for n in (3, 5, 7, 9, 15, 25, 27)]
    print(json.dumps(report, indent=2, sort_keys=True))
    print("DIHEDRAL_SYLOW_PRIME_POWER_AUDIT: PASS")


if __name__ == "__main__":
    main()
